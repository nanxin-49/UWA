function receipt = run_new_ubuntu_minimal_channel_baseline(output_dir, case_id)
%RUN_NEW_UBUNTU_MINIMAL_CHANNEL_BASELINE Small CPU-double compatibility case.
% The caller supplies a new absolute output directory for this run only.
arguments
    output_dir (1,:) char
    case_id (1,:) char {mustBeMember(case_id, ...
        {'direct_4k','reflect_4k','reflect_9f'})}
end

assert(java.io.File(output_dir).isAbsolute(), 'Absolute output directory required');
assert(~isfolder(output_dir) && ~isfile(output_dir), ...
    'Output directory already exists');
setup_vertical_project();

paramsV = struct( ...
    'f0', 4000, 'c0', 1500, 'env_mode', 'uniform', ...
    'nx', 128, 'ny', 128, 'xw', 25, 'yw', 25, ...
    'z_max', 10, 'z_tx', 10, 'z_rx', 1, ...
    'sigma_src_m', 0.4, 'stepz_lamb', 1, ...
    'sea_hs_target', 0, 'sea_seed', 12345, ...
    'surface_boundary_model', 'kirchhoff_spatial', ...
    'channel_phase_reference', 'direct_dsp', ...
    'enable_bubbles', false, 'use_gpu', false, ...
    'show_figures', false, 'save_mode', 'rx_only', ...
    'enforce_1_over_R', false);
paramsV.enable_surface_reflection = ~strcmp(case_id, 'direct_4k');
paramsV.enable_wideband = strcmp(case_id, 'reflect_9f');
if paramsV.enable_wideband
    paramsV.f_band_hz = [4000, 8000];
    paramsV.Nf_min = 9;
    paramsV.Nf_max = 9;
    paramsV.f_ref_hz = 6000;
end

t0 = tic;
output = vertical_channel_model(paramsV);
required = {'h_direct','h_reflect','h_total','H_direct_f', ...
    'H_reflect_f','H_f','f_axis','idx_f_ref','config'};
assert(all(isfield(output, required)), 'Missing public output field');
complex_arrays = {output.h_direct, output.h_reflect, output.h_total, ...
    output.H_direct_f, output.H_reflect_f, output.H_f};
for k = 1:numel(complex_arrays)
    assert(isa(complex_arrays{k}, 'double') && ...
        all(isfinite(complex_arrays{k}(:))), ...
        'Nonfinite or non-double public component');
end
assert(isa(output.f_axis, 'double') && ...
    all(isfinite(output.f_axis(:))), 'Invalid frequency axis');
assert(isequal(size(output.H_direct_f), size(output.H_f)) && ...
    isequal(size(output.H_reflect_f), size(output.H_f)), ...
    'Component shape mismatch');
assert(numel(output.f_axis) == numel(output.H_f), ...
    'Frequency axis length mismatch');
expected_n = 1 + 8 * double(paramsV.enable_wideband);
assert(numel(output.f_axis) == expected_n, 'Unexpected frequency count');
assert(isscalar(output.idx_f_ref) && ...
    output.idx_f_ref >= 1 && output.idx_f_ref <= expected_n && ...
    output.idx_f_ref == fix(output.idx_f_ref), ...
    'Invalid reference frequency index');
if paramsV.enable_wideband
    assert(abs(output.f_axis(output.idx_f_ref) - 6000) < 1e-9, ...
        'Wrong wideband reference frequency');
else
    assert(abs(output.f_axis(output.idx_f_ref) - 4000) < 1e-9, ...
        'Wrong scalar reference frequency');
end
component_error = max(abs(output.H_f(:) - ...
    output.H_direct_f(:) - output.H_reflect_f(:)));
reference_error = max(abs([ ...
    output.h_direct - output.H_direct_f(output.idx_f_ref), ...
    output.h_reflect - output.H_reflect_f(output.idx_f_ref), ...
    output.h_total - output.H_f(output.idx_f_ref)]));
assert(component_error <= 1e-12 && reference_error <= 1e-12, ...
    'Public component or reference-frequency closure failed');
assert(abs(output.h_total - output.h_direct - output.h_reflect) <= 1e-12, ...
    'Scalar path sum failed');

mkdir(output_dir);
save(fullfile(output_dir, 'channel_result.mat'), 'paramsV', 'output', '-v7');
receipt = struct('status', 'CHANNEL_BASELINE_CASE_PASS', ...
    'case_id', case_id, 'frequency_count', expected_n, ...
    'reference_index', output.idx_f_ref, ...
    'component_max_abs_error', component_error, ...
    'reference_max_abs_error', reference_error, ...
    'elapsed_seconds', toc(t0), 'failed_checks', 0);
fid = fopen(fullfile(output_dir, 'receipt.json'), 'w');
assert(fid > 0, 'Cannot write case receipt');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', jsonencode(receipt, PrettyPrint=true));
disp(receipt);
end
