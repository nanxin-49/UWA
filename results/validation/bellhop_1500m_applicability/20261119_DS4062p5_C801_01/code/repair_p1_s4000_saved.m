function audit=repair_p1_s4000_saved(previous,output)
% Read the accepted numerical artifacts and preserve the old failed figure.
data=load(fullfile(previous,'comparison.mat'),'x','pS','refS','ES','pDS','refDS','EDS');
T=readtable(fullfile(previous,'S_and_DS_fields.csv'),'TextType','string');
assert(height(T)==10 && isequal(T.x_m,[data.x(:);data.x(:)]) && ...
    isequal(T.field,[repmat("S",5,1);repmat("D_plus_S",5,1)]),'CSV receiver order');
assert(max(abs(complex(T.p_real,T.p_imag)-[data.pS;data.pDS]))<1e-17 && ...
    max(abs(complex(T.reference_real,T.reference_imag)-[data.refS;data.refDS]))<1e-17 && ...
    max(abs(T.independent_envelope-[data.ES;data.EDS]))<1e-17,'Saved MAT/CSV agreement');
audit=plot_p1_ds_control(data,fullfile(output,'S4000_DS_repaired'), ...
    'U0 at 4000 Hz | S801 and saved D801 | pressure-release control');
end
