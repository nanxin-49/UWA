function summary = analyze_two_dimensional_closeout_s2c_b_phi(run_dir)
%ANALYZE_TWO_DIMENSIONAL_CLOSEOUT_S2C_B_PHI Saved-field paired analysis.
% No acoustic propagation, density evaluation, or Kirchhoff integration.
arguments
    run_dir (1,:) char
end
assert(isfolder(run_dir) && contains(run_dir,'20261023_s2c_b_phi_plus90_01'));
dest=fullfile(run_dir,'analysis'); assert(~isfolder(dest),'Use saved version; no overwrite');
root=fileparts(fileparts(fileparts(fileparts(run_dir))));
formal=fullfile(root,'results/comparisons/two_dimensional_channel_closeout', ...
    '20261023_s2b_1305/formal_reference_v2/reference_data.mat');
old=fullfile(root,'results/comparisons/two_dimensional_channel_closeout', ...
    '20261023_s2b_1305/checkpoints/pe3.mat');
D=load(formal,'U','x','z','ix9','reference','fk_runs','numerical','flat_exact');
B=load(fullfile(run_dir,'P1','BIE_reference_data.mat'),'U','x','z','resolution_abs');
P=load(fullfile(run_dir,'jobs','pe_phi.mat'),'payload','receipt');
F=load(fullfile(run_dir,'jobs','fullfk_phi.mat'),'payload','receipt');
O=load(old,'payload'); g=closeout_s2c_b_phi_gate(run_dir);
assert(isequal(D.x(:),B.x(:)) && isequal(D.z(:),B.z(:)));
assert(strcmp(P.receipt.status,'COMPLETE') && strcmp(F.receipt.status,'COMPLETE'));
assert(strcmp(P.receipt.budget_amendment_sha256,g.budget_amendment_sha256));
assert(strcmp(F.receipt.budget_amendment_sha256,g.budget_amendment_sha256));
assert(strcmp(F.payload.version,'FullFK_complete_analytic_flat_exterior_GL8_v1'));
assert(P.receipt.flat_control_relative<1e-10);
x=D.x(:); z=D.z(:); ix9=D.ix9(:); n=417;
assert(all(z(1:411)==3) && numel(ix9)==9);
assert(isequal(P.payload.x_m(:),x) && isequal(P.payload.z_m(:),z));
assert(isequal(F.payload.x_m(:),x) && isequal(F.payload.z_m(:),z));
U=complex(zeros(n,2,3)); U(:,1,:)=D.U(:,3,:);
U(:,2,1)=P.payload.u_native(:); U(:,2,2)=B.U(:,1);
U(:,2,3)=F.payload.u_native(:);
assert(all(isfinite(real(U)),'all') && all(isfinite(imag(U)),'all'));
flat=squeeze(D.U(:,1,:));
r0=D.reference(D.reference.case_name=="region_II_low_K",:);
assert(height(r0)==n && isequal(r0.x_m(:),x) && isequal(r0.z_m(:),z));
bie_abs=[r0.resolution_estimate(:),B.resolution_abs(:)];
pe_step=[max(abs(O.payload.step_half_line(:)-U(1:411,1,1))), ...
    max(abs(P.payload.half_step_native(:)-U(:,2,1)))];
assert(numel(O.payload.grid_double_u)==numel(O.payload.u));
assert(numel(P.payload.double_grid_probe_native)==13);
pe_grid=[max(abs(O.payload.grid_double_u(:)-O.payload.u(:))), ...
    max(abs(P.payload.double_grid_probe_native(:)-P.payload.primary_probe_native(:)))];
pe_bound=pe_step+pe_grid; % Frozen-probe max carried across each support.
fk0=abs(D.fk_runs{3,2}.receiver_field(:)-D.fk_runs{3,1}.receiver_field(:));
extra=D.numerical.FullFK_independent_tail_max_abs(D.numerical.case_name=="region_II_low_K");
assert(isscalar(extra)); fk0=fk0+extra;
fk1=abs(F.payload.GL8_800.receiver_field(:)-F.payload.GL8_400.receiver_field(:)) ...
    +abs(F.payload.extent60.receiver_field(:)-F.payload.extent90.receiver_field(:)) ...
    +abs(F.payload.GL8_800.receiver_field(:)-F.payload.extent60.receiver_field(:));
fk_abs=[fk0,fk1];
assert(max(abs(U(:,2,3)-F.payload.GL8_800.receiver_field(:)))==0);
center=find(abs(x(1:411))<=1); edge=find(abs(x(1:411))>=30);
five=ix9([2 4 5 6 8]); supports={(1:411)',center,ix9,five(:),edge};
sid=["line_411","center_11","nine_9","cross_5","edge_104"];
methods=["PE","BIE","FullFK"]; cases=["BASE_M","PHI_PLUS90"];
raw=table; point=table; support=table; paired=table;
for c=1:2
    r=U(:,c,2); near=abs(r)<=max(max(abs(r))*1e-12,10*bie_abs(:,c));
    for m=1:3
        u=U(:,c,m); uf=flat(:,m); du=u-uf; G=u./uf;
        raw=[raw;table(repmat(cases(c),n,1),repmat(methods(m),n,1), ...
            (1:n)',x,z,real(u),imag(u),real(uf),imag(uf), ...
            real(du),imag(du),real(G),imag(G),isfinite(u), ...
            'VariableNames',{'case_name','method','sample_index','x_m','z_m', ...
            'u_native_real','u_native_imag','u_flat_real','u_flat_imag', ...
            'delta_u_real','delta_u_imag','G_real','G_imag','valid'})]; %#ok<AGROW>
    end
    for m=[1 3]
        u=U(:,c,m); e=u-r; ph=angle(u.*conj(r));
        a2=(abs(u)-abs(r)).^2; p2=4*abs(u).*abs(r).*sin(ph/2).^2;
        db=20*log10(abs(u)./abs(r));
        assert(all(isfinite(db)) && all(isfinite(ph)));
        assert(max(abs(abs(e).^2-a2-p2))<1e-12);
        point=[point;table(repmat(cases(c),n,1),repmat(methods(m),n,1), ...
            (1:n)',x,z,real(e),imag(e),abs(e),db,ph,a2,p2,abs(e).^2, ...
            abs(e).^2-a2-p2,bie_abs(:,c),near, ...
            'VariableNames',{'case_name','method','sample_index','x_m','z_m', ...
            'residual_real','residual_imag','residual_abs','amplitude_difference_dB', ...
            'wrapped_phase_difference_rad','amplitude_square','phase_square', ...
            'complex_square','identity_remainder','BIE_resolution_abs','reference_near_zero'})]; %#ok<AGROW>
        for s=1:5
            ii=supports{s}; nn=numel(ii); q=ones(nn,1)/nn;
            den=sum(q.*abs(r(ii)).^2); ed=sum(q.*abs(e(ii)).^2);
            E=sqrt(ed/den); Ea=sqrt(sum(q.*a2(ii))/den); Ep=sqrt(sum(q.*p2(ii))/den);
            [worst,k]=max(abs(e(ii))); k=ii(k);
            [rw,rb,rp,rf,rr]=local_resolution(ii,c,m,U,bie_abs,pe_bound,fk_abs,D.flat_exact(:));
            support=[support;table(cases(c),methods(m),sid(s),nn,"spatial_equal",den,E,Ea,Ep, ...
                sqrt(mean(db(ii).^2)),sqrt(mean(ph(ii).^2)),mean(abs(e(ii))), ...
                median(abs(e(ii))),worst,x(k),z(k),sum(near(ii)), ...
                rb,rp,rf,rr,rw,E>5*rw, ...
                'VariableNames',{'case_name','method','support_id','n','weight_kind', ...
                'BIE_denominator','complex_L2','amplitude_L2','phase_L2', ...
                'amplitude_dB_RMS','wrapped_phase_RMS_rad','mean_abs_residual', ...
                'median_abs_residual','max_abs_residual','worst_x_m','worst_z_m', ...
                'near_zero_count','BIE_resolution','PE_probe_resolution', ...
                'FullFK_resolution','roundoff_allowance','total_empirical_resolution', ...
                'resolved_above_5x'})]; %#ok<AGROW>
        end
    end
end
assert(height(raw)==2502 && height(point)==1668 && height(support)==20);
physical=table((1:n)',x,z,real(U(:,1,2)),imag(U(:,1,2)), ...
    real(U(:,2,2)),imag(U(:,2,2)),real(U(:,2,2)-U(:,1,2)), ...
    imag(U(:,2,2)-U(:,1,2)),abs(U(:,2,2)-U(:,1,2)), ...
    20*log10(abs(U(:,2,2))./abs(U(:,1,2))), ...
    angle(U(:,2,2).*conj(U(:,1,2))),bie_abs(:,1),bie_abs(:,2), ...
    'VariableNames',{'sample_index','x_m','z_m','BASE_BIE_real','BASE_BIE_imag', ...
    'PHI_BIE_real','PHI_BIE_imag','delta_phi_real','delta_phi_imag','delta_phi_abs', ...
    'amplitude_change_dB','wrapped_phase_change_rad', ...
    'BASE_BIE_resolution_abs','PHI_BIE_resolution_abs'});
for s=1:5
    ii=supports{s}; nn=numel(ii); q=ones(nn,1)/nn;
    rbase=U(ii,1,2); rphi=U(ii,2,2); dref=rphi-rbase;
    den0=sum(q.*abs(rbase).^2);
    phys=sqrt(sum(q.*abs(dref).^2)/den0);
    resphys=(norm(bie_abs(ii,1))+norm(bie_abs(ii,2)))/norm(rbase);
    for m=[1 3]
        e0=U(ii,1,m)-rbase; e1=U(ii,2,m)-rphi;
        a=support(support.case_name=="BASE_M"&support.method==methods(m)&support.support_id==sid(s),:);
        b=support(support.case_name=="PHI_PLUS90"&support.method==methods(m)&support.support_id==sid(s),:);
        assert(height(a)==1 && height(b)==1);
        pair_delta=sqrt(sum(q.*abs(e1-e0).^2)/den0);
        pair_abs=(norm(bie_abs(ii,1))+norm(bie_abs(ii,2)) ...
            +sqrt(nn)*(pe_bound(1)+pe_bound(2))*(m==1) ...
            +(norm(fk_abs(ii,1))+norm(fk_abs(ii,2)))*(m==3) ...
            +256*eps*norm(D.flat_exact(ii))*2)/norm(rbase);
        scalar_change=b.complex_L2-a.complex_L2;
        scalar_floor=a.total_empirical_resolution+b.total_empirical_resolution;
        paired=[paired;table(methods(m),sid(s),nn,den0,phys,resphys,phys>5*resphys, ...
            a.complex_L2,b.complex_L2,scalar_change,abs(scalar_change)>5*scalar_floor, ...
            pair_delta,pair_abs,pair_delta>5*pair_abs, ...
            'VariableNames',{'method','support_id','n','BASE_BIE_denominator', ...
            'BIE_physical_response_L2','BIE_paired_resolution', ...
            'BIE_physical_resolved_above_5x','BASE_model_error_L2','PHI_model_error_L2', ...
            'signed_model_error_change','scalar_error_change_resolved_above_5x', ...
            'paired_residual_change_L2','paired_residual_resolution', ...
            'paired_residual_change_resolved_above_5x'})]; %#ok<AGROW>
    end
end
assert(height(paired)==10);
mkdir(dest);
writetable(raw,fullfile(dest,'raw_fields.csv'));
writetable(physical,fullfile(dest,'BIE_physical_pair.csv'));
writetable(point,fullfile(dest,'model_point_diagnostics.csv'));
writetable(support,fullfile(dest,'support_metrics.csv'));
writetable(paired,fullfile(dest,'paired_changes.csv'));
save(fullfile(dest,'analysis_data.mat'),'U','flat','x','z','ix9','sid','supports', ...
    'bie_abs','pe_bound','fk_abs','raw','physical','point','support','paired','-v7.3');
jobs={'main96','self64','space14','window60','window70'};
cost=zeros(1,7);
for j=1:5
    q=load(fullfile(run_dir,'jobs',['bie_' jobs{j} '.mat']),'receipt'); cost(j)=q.receipt.wall_seconds;
end
cost(6)=P.receipt.wall_seconds; cost(7)=F.receipt.wall_seconds;
assert(sum(cost)<g.subbudget_s && g.core_remaining_s-sum(cost)>g.S3A_reserve_s);
summary=struct('status','S2C_B_PHI_PLUS90_ANALYSIS_PENDING_INDEPENDENT_AUDIT', ...
    'source_case','BASE_M S2b formal reference v2','new_case','PHI_PLUS90', ...
    'points',417,'line_points',411,'nine_points',9,'new_acoustic_jobs',7, ...
    'job_acoustic_seconds',cost,'total_new_acoustic_seconds',sum(cost), ...
    'charged_core_seconds',g.charged_prior_seconds+sum(cost), ...
    'authorized_subbudget_s',g.subbudget_s, ...
    'S3A_planning_balance_s',g.core_remaining_s-sum(cost), ...
    'BIE_reference_kind','five independent new boundary solves; empirical not strict bound', ...
    'PE_grid_check_kind','frozen probes only; maximum carried over each support', ...
    'FullFK_version','FullFK_complete_analytic_flat_exterior_GL8_v1', ...
    'budget_amendment_sha256',g.budget_amendment_sha256);
closeout_s2b_json(fullfile(dest,'summary_pending_audit.json'),summary);
disp(summary); disp(support(:,{'case_name','method','support_id','n','complex_L2','total_empirical_resolution','resolved_above_5x'}));
end

function [total,bie,pe,fk,roundoff]=local_resolution(ii,c,m,U,bie_abs,pe_bound,fk_abs,flat_exact)
den=norm(U(ii,c,2)); nn=numel(ii);
bie=norm(bie_abs(ii,c))/den;
pe=double(m==1)*sqrt(nn)*pe_bound(c)/den;
fk=double(m==3)*norm(fk_abs(ii,c))/den;
roundoff=256*eps*norm(flat_exact(ii))/den;
total=bie+pe+fk+roundoff;
end
