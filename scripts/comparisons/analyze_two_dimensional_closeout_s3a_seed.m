function summary = analyze_two_dimensional_closeout_s3a_seed(root,run_dir)
%ANALYZE_TWO_DIMENSIONAL_CLOSEOUT_S3A_SEED Saved seed260001 native fields only.
arguments
    root (1,:) char
    run_dir (1,:) char
end
dest=fullfile(run_dir,'analysis_v2'); assert(~isfolder(dest));
assert(isfolder(root) && startsWith(run_dir,root));
t=load(fullfile(run_dir,'input','reference_data.mat'),'x','z','ix9','U','flat_exact');
x=t.x(:); z=t.z(:); ix9=t.ix9(:); n=numel(x);
assert(n==417 && numel(ix9)==9);
ids={'main96','self64','space14','window60','window70','pe','fullfk'};
J=cell(7,1); cost=zeros(7,1);
for j=1:7
    J{j}=load(fullfile(run_dir,'jobs',[ids{j} '.mat']),'payload','receipt');
    assert(strcmp(J{j}.receipt.status,'COMPLETE'));
    assert(isequal(J{j}.payload.x_m(:),x) && isequal(J{j}.payload.z_m(:),z));
    cost(j)=J{j}.receipt.wall_seconds;
end
assert(sum(cost)<1700);
flat=squeeze(t.U(:,1,:));
rough=[J{6}.payload.u_native(:),J{1}.payload.u_native(:),J{7}.payload.u_native(:)];
assert(isequal(size(rough),[417 3]) && all(isfinite(rough),'all'));
assert(strcmp(J{7}.payload.version,'FullFK_complete_analytic_flat_exterior_GL8_v1'));
bie=rough(:,2); bres=zeros(n,1);
for j=2:5
    bres=max(bres,abs(bie-J{j}.payload.u_native(:)));
end
grid=load(fullfile(run_dir,'jobs','pe_grid.mat'),'payload','receipt');
assert(strcmp(grid.receipt.status,'COMPLETE') && isequal(grid.payload.x_m(:),x));
pe_res=abs(rough(:,1)-J{6}.payload.half_step_native(:)) ...
    +abs(rough(:,1)-grid.payload.u_native(:));
fk=J{7}.payload;
fk_res=abs(fk.GL8_800.receiver_field(:)-fk.GL8_400.receiver_field(:)) ...
    +abs(fk.extent60.receiver_field(:)-fk.extent90.receiver_field(:)) ...
    +abs(fk.GL8_800.receiver_field(:)-fk.extent60.receiver_field(:));
assert(max(abs(fk.GL8_800.receiver_field(:)-rough(:,3)))==0);
% Retain full support and a fixed nine-point report. Every ratio names its denominator.
methods=["PE" "BIE" "FullFK"];
raw=table; points=table; metrics=table;
for m=1:3
    u=rough(:,m); uf=flat(:,m);
    raw=[raw;table(repmat(methods(m),n,1),(1:n)',x,z,real(u),imag(u), ...
        real(uf),imag(uf),real(u-uf),imag(u-uf), ...
        real(u./uf),imag(u./uf), ...
        'VariableNames',{'method','sample_index','x_m','z_m', ...
        'u_rough_real','u_rough_imag','u_flat_real','u_flat_imag', ...
        'delta_u_real','delta_u_imag','G_real','G_imag'})]; %#ok<AGROW>
end
support_ids=["nine_9" "line_411"];
supports={ix9,(1:411)'};
for m=[1 3]
    u=rough(:,m); e=u-bie; dp=angle(u.*conj(bie));
    amp=abs(u)-abs(bie); phase_sq=4*abs(u).*abs(bie).*sin(dp/2).^2;
    assert(max(abs(abs(e).^2-amp.^2-phase_sq))<1e-12);
    points=[points;table(repmat(methods(m),n,1),(1:n)',x,z, ...
        real(e),imag(e),abs(e),amp,20*log10(abs(u)./abs(bie)),dp, ...
        bres,pe_res,fk_res, ...
        'VariableNames',{'method','sample_index','x_m','z_m', ...
        'residual_real','residual_imag','residual_abs','amplitude_difference', ...
        'amplitude_difference_dB','wrapped_phase_difference_rad', ...
        'BIE_max_level_difference_abs','PE_sensitivity_abs', ...
            'FullFK_sensitivity_abs'})]; %#ok<AGROW>
    for s=1:2
        ii=supports{s}; r=bie(ii); v=u(ii); q=abs(v-r);
        den=sum(abs(r).^2);
        E=sqrt(sum(q.^2)/den);
        Ea=sqrt(sum(amp(ii).^2)/den);
        Ep=sqrt(sum(phase_sq(ii))/den);
        [worst,loc]=max(q); worst_index=ii(loc);
        numeric=(norm(bres(ii))+norm(pe_res(ii))*(m==1) ...
            +norm(fk_res(ii))*(m==3)+256*eps*norm(t.flat_exact(ii)))/norm(r);
        metrics=[metrics;table(methods(m),support_ids(s),numel(ii),den,E,Ea,Ep, ...
            sqrt(mean(dp(ii).^2)),sqrt(mean((20*log10(abs(v)./abs(r))).^2)), ...
            mean(q),median(q),worst,worst_index,x(worst_index),z(worst_index), ...
            norm(bres(ii))/norm(r),numeric,E>5*numeric, ...
            'VariableNames',{'method','support_id','n','BIE_rough_denominator_sum_abs2', ...
            'complex_L2','amplitude_L2','phase_L2','phase_RMS_rad', ...
            'amplitude_dB_RMS','mean_abs_residual','median_abs_residual', ...
            'max_abs_residual','worst_index','worst_x_m','worst_z_m', ...
            'BIE_level_resolution_relative','total_empirical_resolution', ...
            'above_5x_empirical_resolution'})]; %#ok<AGROW>
    end
end
assert(height(raw)==1251 && height(points)==834 && height(metrics)==4);
physical=table;
for s=1:2
    ii=supports{s}; b0=flat(ii,2); br=bie(ii); delta=br-b0;
    den=sum(abs(b0).^2); E=sqrt(sum(abs(delta).^2)/den);
    resolution=norm(bres(ii))/norm(b0);
    physical=[physical;table(support_ids(s),numel(ii),den,E, ...
        mean(abs(delta)),median(abs(delta)),max(abs(delta)),resolution,E>5*resolution, ...
        'VariableNames',{'support_id','n','BIE_flat_denominator_sum_abs2', ...
        'BIE_physical_response_L2','mean_abs_delta_u','median_abs_delta_u', ...
        'max_abs_delta_u','BIE_level_resolution_relative','above_5x_empirical_resolution'})]; %#ok<AGROW>
end
flat_pair=table;
for m=[1 3]
    for s=1:2
        ii=supports{s}; f=flat(ii,m); b=flat(ii,2);
        flat_pair=[flat_pair;table(methods(m),support_ids(s),numel(ii), ...
            norm(f-b)/norm(b),max(abs(f-b)), ...
            'VariableNames',{'method','support_id','n','flat_complex_L2_to_BIE', ...
            'flat_max_abs_difference'})]; %#ok<AGROW>
    end
end
mkdir(dest);
writetable(raw,fullfile(dest,'raw_fields.csv'));
writetable(points,fullfile(dest,'point_diagnostics.csv'));
writetable(metrics,fullfile(dest,'model_metrics.csv'));
writetable(physical,fullfile(dest,'BIE_physical_response.csv'));
writetable(flat_pair,fullfile(dest,'flat_controls.csv'));
grid_wall=grid.receipt.wall_seconds;
save(fullfile(dest,'analysis_data.mat'),'x','z','ix9','flat','rough','bres', ...
    'pe_res','fk_res','raw','points','metrics','physical','flat_pair','cost','grid_wall','-v7.3');
summary=struct('status','S3A_SEED260001_ANALYZED_PENDING_INDEPENDENT_AUDIT', ...
    'seed',260001,'new_acoustic_jobs',8,'acoustic_seconds',sum(cost)+grid_wall, ...
    'job_seconds',[cost;grid_wall],'nine_points',9,'line_points',411, ...
    'BIE_reference','five-level empirical sensitivity, same Ubuntu R2023b', ...
    'FullFK_version',J{7}.payload.version, ...
    'shared_charged_after_acoustics_s',3401.424104+sum(cost)+grid_wall, ...
    'S3A_subbudget_s',1700,'S3A_total_planning_s',3000);
fid=fopen(fullfile(dest,'summary_pending_audit.json'),'w');
assert(fid>0); c=onCleanup(@()fclose(fid)); fprintf(fid,'%s',jsonencode(summary,PrettyPrint=true));
disp(summary); disp(metrics); disp(physical);
end
