function [A,B]=pair_arrays(c,pi)
switch pi
    case 1, A=c.G_PE(:); B=c.G_BIE(:);
    case 2, A=c.G_BH(:); B=c.G_BIE(:);
    case 3, A=c.G_PE(:); B=c.G_BH(:);
end
end

function [rows,summary]=point_and_summary(case_id,pair,quantity,A,B,ids,px,pz)
m=two_dimensional_closeout_metrics(A,B,ones(9,1),true(9,1)); rows=cell(9,25);
for k=1:9
    status="valid"; if ~m.valid(k), status="missing_saved_sample"; end
    if m.valid(k)&&~m.reference_nonzero(k), status="zero_reference"; end
    if m.valid(k)&&m.reference_nonzero(k)&&~m.phase_valid(k), status="zero_candidate"; end
    source="E01_plot"; if startsWith(quantity,"raw"), source="E02_plot"; end
    rows(k,:)={case_id,pair,quantity,string(ids{k}),px(k),pz(k),real(A(k)),imag(A(k)), ...
        real(B(k)),imag(B(k)),m.valid(k),status,m.abs_A(k),m.abs_B(k),m.abs_diff(k), ...
        m.rel_diff(k),m.mag_db(k),m.phase_rad(k),m.mag_sq(k),m.phase_sq(k), ...
        m.closure(k),"unknown",source,"none; same saved representation","dimensionless G or native source units"};
end
av=m.abs_diff(isfinite(m.abs_diff)); rv=m.rel_diff(isfinite(m.rel_diff));
db=m.mag_db(isfinite(m.mag_db)); ph=m.phase_rad(isfinite(m.phase_rad));
summary={case_id,pair,quantity,9,m.n_valid,m.n_rel,m.n_db,m.n_phase, ...
    strjoin(string(ids(m.valid)),";"),strjoin(string(ids(~m.valid)),";"), ...
    finite_mean(av),finite_median(av),finite_max(av),max_id(m.abs_diff,ids), ...
    finite_mean(rv),finite_median(rv),finite_max(rv),max_id(m.rel_diff,ids), ...
    finite_mean(db),rms_value(db),finite_max(abs(db)),max_id(abs(m.mag_db),ids), ...
    finite_mean(ph),rms_value(ph),finite_max(abs(ph)),max_id(abs(m.phase_rad),ids), ...
    m.E,metric_label(quantity,m.n_valid),m.mag_fraction,m.phase_fraction, ...
    finite_max(abs(m.closure(isfinite(m.closure))))};
end
function label=metric_label(quantity,n)
if quantity=="raw_native_amplitude_only"
    label="magnitude_L2_array";
elseif n==9
    label="E_array";
else
    label="E_subset";
end
end
function v=finite_mean(x), v=NaN; if ~isempty(x), v=mean(x); end, end
function v=finite_median(x), v=NaN; if ~isempty(x), v=median(x); end, end
function v=finite_max(x), v=NaN; if ~isempty(x), v=max(x); end, end
function v=rms_value(x), v=NaN; if ~isempty(x), v=sqrt(mean(x.^2)); end, end
function id=max_id(x,ids)
id=""; x(~isfinite(x))=-Inf;
if any(isfinite(x)), [~,k]=max(x); id=string(ids{k}); end
end
function v=ternary(test,a,b), if test, v=a; else, v=b; end, end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); cleaner=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(value,PrettyPrint=true)); clear cleaner
end
function value=sha256_file(path)
fid=fopen(path,'rb'); assert(fid>=0); cleaner=onCleanup(@()fclose(fid));
md=java.security.MessageDigest.getInstance('SHA-256');
while ~feof(fid), md.update(fread(fid,1048576,'*uint8')); end
value=string(lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[])));
end
