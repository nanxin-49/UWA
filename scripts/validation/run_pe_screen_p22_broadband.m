function receipt = run_pe_screen_p22_broadband(run_id)
%RUN_PE_SCREEN_P22_BROADBAND PE-only P22 frequency/CIR screening.
arguments
    run_id (1,:) char
end
assert(~isempty(regexp(run_id,'^[A-Za-z0-9_]+$','once')));
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
setup_vertical_project;
outdir=fullfile(root,'results','validation','pe_screen_p22_comm',run_id);
assert(~isfolder(outdir) && ~isfile(outdir),'Run ID already exists');
source_path=fullfile(root,'results','comparisons', ...
    'two_dimensional_channel_closeout','20261026_s3a_seed260003_01', ...
    'input','frozen_source.mat');
assert(isfile(source_path));
s=load(source_path,'src'); frozen=s.src;
assert(frozen.n_original==984 && frozen.z_tx_m==100);
N=984; W=192.1875; c0=1500; ztx=100; zrx=3;
x=-W/2+(0:N-1)'*W/N;
source_tx=ifft(frozen.coeff(:));
assert(max(abs(source_tx-exp(-.5*(x/.3).^2)))<1e-12);
[eta_weak,~]=closeout_s2b_surface(x,.01);
f129=4000+(0:128)'*31.25; f65=f129(1:2:end);
H_direct=complex(zeros(129,2)); H_reflect=H_direct;
pe_seconds=zeros(129,2); direct_error=zeros(129,2);
tau0=(ztx-zrx)/c0;
tic_all=tic;
for isurf=1:2
    eta=zeros(N,1);
    if isurf==2, eta=eta_weak; end
    for ii=1:129
        f=f129(ii); src=closeout2d_source_at_frequency(frozen,f,c0);
        cfg=struct('frequency_hz',f,'c0_mps',c0,'xw_m',W, ...
            'nx',N,'z_tx_m',ztx,'z_rx_m',zrx,'sigma_src_m',.3, ...
            'surface_reflect_coeff',-1,'step_m',.05,'x_rx_m',0, ...
            'reflection_model','model0_normal', ...
            'source_field_override',source_tx,'eta_z_m',eta);
        tick=tic; pe=run_pe_physical_surface_model0_validation(cfg);
        pe_seconds(ii,isurf)=toc(tick);
        ud=pe.direct_receiver*exp(1i*2*pi*f*tau0);
        ua=fk_single_receiver_incident(src,0,zrx);
        direct_error(ii,isurf)=abs(ud-ua)/abs(ua);
        phase=exp(1i*2*pi*f*tau0);
        H_direct(ii,isurf)=conj(ud)*phase;
        H_reflect(ii,isurf)=conj(pe.reflected_native(pe.ix_rx))*phase;
    end
end
H_total=H_direct+H_reflect;
direct_between_surfaces=max(abs(H_direct(:,1)-H_direct(:,2))) / max(abs(H_direct(:)));
direct_max=max(direct_error,[],'all');
closure=max(abs(H_total-H_direct-H_reflect),[],'all') / max(abs(H_total(:)));
assert(direct_max<=1e-10 && direct_between_surfaces<=1e-10 && closure<=1e-12);
% The inclusive 8 kHz endpoint is independently evaluated, not reused as an FFT bin.
endpoint_error=max(abs(H_total(end,:)-H_total(1,:)));
base=1:2:127; refined=1:128;
h65=complex(zeros(64,2)); h129=complex(zeros(128,2));
pdp65=zeros(64,2); pdp129=zeros(128,2);
roundtrip=zeros(2,2); refinement=zeros(1,2); tail=zeros(1,2);
for isurf=1:2
    c65=build_channel_cir_vertical(H_total(base,isurf),f65(1:64), ...
        struct('input_reference','direct_dsp'));
    c129=build_channel_cir_vertical(H_total(refined,isurf),f129(1:128), ...
        struct('input_reference','direct_dsp'));
    h65(:,isurf)=c65.h_tau; h129(:,isurf)=c129.h_tau;
    pdp65(:,isurf)=abs(c65.h_tau).^2;
    pdp129(:,isurf)=abs(c129.h_tau).^2;
    roundtrip(isurf,:)=[norm(fft(h65(:,isurf))-H_total(base,isurf))/norm(H_total(base,isurf)), ...
        norm(fft(h129(:,isurf))-H_total(refined,isurf))/norm(H_total(refined,isurf))];
    refinement(isurf)=norm(h65(:,isurf)-h129(1:64,isurf)) / norm(h129(:,isurf));
    tail(isurf)=sum(pdp129(65:end,isurf))/sum(pdp129(:,isurf));
end
gates=struct('direct_source',direct_max<=1e-10, ...
    'direct_surface_identity',direct_between_surfaces<=1e-10, ...
    'component_closure',closure<=1e-12, ...
    'fft_roundtrip',max(roundtrip,[],'all')<=1e-10, ...
    'frequency_refinement',max(refinement)<=1e-3, ...
    'tail_energy',max(tail)<=1e-3);
failed=sum(~cell2mat(struct2cell(gates)));
status='PE_SCREEN_CIR_GATE_FAILED';
if failed==0, status='PE_SCREEN_CIR_GATE_PASS'; end
receipt=struct('status',status,'matlab_version',version, ...
    'source_path',source_path,'source_id','frozen Gaussian N984 sigma0.3m', ...
    'surface_model','flat and C2 weak sinusoid A0.01m K0.1radpm', ...
    'receiver','P22 x0m z3m','native_phase','exp(-i omega t)', ...
    'dsp_formula','conj(P_native)*exp(i*2*pi*f*tau0)', ...
    'tau0_s',tau0,'frequency_count_refined',129,'frequency_count_base',65, ...
    'fft_bins_refined',128,'fft_bins_base',64,'delay_spacing_s',.00025, ...
    'window_base_s',.016,'window_refined_s',.032, ...
    'direct_max_relative',direct_max,'direct_between_surfaces',direct_between_surfaces, ...
    'component_closure_relative',closure,'endpoint_absolute_difference',endpoint_error, ...
    'fft_roundtrip_relative',roundtrip,'cir_refinement_relative',refinement, ...
    'refined_tail_energy_fraction',tail,'pe_seconds',sum(pe_seconds,'all'), ...
    'elapsed_seconds',toc(tic_all),'failed_check_count',failed,'gates',gates, ...
    'bie_calls',0,'fullfk_calls',0,'three_dimensional_calls',0);
mkdir(outdir);
save(fullfile(outdir,'pe_screen_p22_broadband.mat'),'receipt','f129','f65', ...
    'H_direct','H_reflect','H_total','h65','h129','pdp65','pdp129', ...
    'pe_seconds','direct_error','-v7.3');
t=table(repmat(f129,2,1),repelem(["flat";"weak_sine"],129), ...
    real(H_direct(:)),imag(H_direct(:)),real(H_reflect(:)),imag(H_reflect(:)), ...
    real(H_total(:)),imag(H_total(:)),pe_seconds(:), ...
    'VariableNames',{'frequency_hz','surface','H_direct_real','H_direct_imag', ...
    'H_reflect_real','H_reflect_imag','H_total_real','H_total_imag','pe_seconds'});
writetable(t,fullfile(outdir,'frequency_response.csv'));
delay_s=(0:127)'*.00025;
td=table(repmat(delay_s,2,1),repelem(["flat";"weak_sine"],128), ...
    real(h129(:)),imag(h129(:)),pdp129(:), ...
    'VariableNames',{'delay_s','surface','cir_real','cir_imag','pdp'});
writetable(td,fullfile(outdir,'cir_pdp_129.csv'));
fid=fopen(fullfile(outdir,'receipt.json'),'w'); assert(fid>0);
cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(receipt,PrettyPrint=true));
disp(receipt);
end
