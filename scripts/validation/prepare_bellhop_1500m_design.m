function receipt = prepare_bellhop_1500m_design(project_root,output_dir)
%PREPARE_BELLHOP_1500M_DESIGN Closed-form design only; no acoustic solver call.
arguments
    project_root (1,:) char
    output_dir (1,:) char
end
assert(isfolder(project_root) && isfolder(fullfile(project_root,'reports')));
assert(~isfolder(output_dir),'Use a new design directory; never overwrite evidence.');
mkdir(output_dir);
c=1500; D=1500; zs=1490; zr=6; x=[0 10 50 100 200];
tags=["D","S","B","BS","SB","SBS","BSB"];
vertical=[zs-zr,zs+zr,2*D-zs-zr,2*D-zs+zr,2*D+zs-zr,2*D+zs+zr,4*D-zs-zr];
ns=[0 1 0 1 1 2 1]; nb=[0 0 1 1 1 1 2];
rows=table(strings(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    'VariableNames',{'path','x_m','vertical_path_m','length_m','delay_s', ...
    'excess_delay_ms','surface_bounces','bottom_bounces','launch_angle_from_vertical_deg'});
for j=1:numel(x)
    ld=hypot(x(j),vertical(1));
    for k=1:numel(tags)
        L=hypot(x(j),vertical(k));
        rows(end+1,:)={tags(k),x(j),vertical(k),L,L/c,1000*(L-ld)/c,ns(k),nb(k),atan2d(x(j),vertical(k))}; %#ok<AGROW>
    end
end
assert(height(rows)==35 && all(isfinite(rows.length_m)));
a=rows(rows.x_m==0,:);
assert(max(abs(a.excess_delay_ms-[0;8;40/3;64/3;2000;2008;6040/3]))<1e-9);
assert(max(rows.launch_angle_from_vertical_deg)<8);
writetable(rows,fullfile(output_dir,'analytic_geometry.csv'));
f=[4000 4062.5 6000 6000.37 7937.5 8000].';
surface_pair_phase=2*pi*f*(2*zr/c);
nulls=table(f,surface_pair_phase,abs(1-exp(-1i*surface_pair_phase)), ...
    'VariableNames',{'frequency_hz','axis_DS_extra_phase_rad','unit_amplitude_DS_cancellation_factor'});
writetable(nulls,fullfile(output_dir,'frequency_anchor_checks.csv'));
stages=["P1_homogeneous_primitives";"P2_beams_orders_fan";"P3_sparse_FFP"; ...
    "P4_smooth_SSP_pilot";"P5_early_H257";"P5_early_refine_H513"];
bellhop=[18;190;0;94;1028;1024];
ffp=[0;0;26;8;0;0];
caps=[300;1200;1200;1200;3600;3600];
plan=table(stages,bellhop,ffp,caps,repmat("PROPOSED_NOT_AUTHORIZED",6,1), ...
    'VariableNames',{'stage','new_Bellhop_job_slots','new_FFP_job_slots','proposed_total_cap_s','authorization'});
writetable(plan,fullfile(output_dir,'stage_cost_plan.csv'));
cfg=struct('schema','bellhop_1500m_design_v1','status','DESIGN_ONLY_AWAITING_REVIEW', ...
    'water_depth_m',D,'source_z_m',zs,'receiver_z_m',zr,'x_m',x, ...
    'frequency_anchors_hz',f.','band_hz',[4000 8000],'source_model','ideal 3D point, 1m pressure reference; width N/A', ...
    'uniform_control_c_mps',c,'water_density_gcm3',1, ...
    'fluid_bottom_example',struct('cp_mps',1600,'density_gcm3',1.8,'atten_db_per_wavelength',0), ...
    'smooth_SSP_example_only',struct('c0_mps',1500,'axis_depth_m',1300,'scale_m',1300,'epsilon',.00737), ...
    'beam_counts',[201 401 801],'Q_initial_m',.625,'step_initial_m',.5, ...
    'reflection_order_checks',[2 4 8],'initial_early_components',{{'D','S','B','BS'}}, ...
    'old_5000m_D_required',false,'current_Bellhop_jobs',0,'current_FFP_jobs',0, ...
    'current_ABC_recomputed',0,'future_jobs_authorized',false, ...
    'early_band_grid',struct('N',256,'endpoint_audit_N',257,'delta_f_hz',15.625,'period_s',.064,'delay_sample_s',.00025), ...
    'full_N8_period_example_s',16.384,'full_N8_unique_frequency_example',65537, ...
    'full_N8_dense_native_job_example',65537*17, ...
    'phase',struct('physical_time','exp(-i omega t)','p_abs_from_native','-conj(p_native)', ...
    'H_DSP_absolute','conj(p_abs)','H_DSP_relative','H_DSP_absolute*exp(+i*2*pi*f*tau_ref)', ...
    'tau_ref','fixed independent direct-time reference, common to compared methods; no fit'), ...
    'resource_gates',struct('launch_available_GiB',1.5,'runtime_minimum_MiB',256,'runtime_fraction_of_launch_available',.3,'per_job_limit_s',120, ...
    'proposed_free_disk_GiB',20,'old_project_output_cap_GiB',15,'serial',true), ...
    'normal_fluid_R_lossless',(1.8*1600-1500)/(1.8*1600+1500));
write_json(fullfile(output_dir,'design_manifest.json'),cfg);
inputs={ ...
 'scripts/validation/support/make_bellhop_rotated_munk_config.m', ...
 'scripts/validation/support/make_bellhop_rotated_direct_field_config.m', ...
 'scripts/validation/support/make_bellhop_rotated_multifield_config.m', ...
 'scripts/validation/support/write_bellhop_rotated_munk_q.m', ...
 'scripts/validation/support/write_bellhop_rotated_multifield_q.m', ...
 'scripts/validation/support/prepare_bellhop_rotated_receiver64_overlay.m', ...
 'scripts/validation/support/optimize_bellhop_rotated_flatwall_overlay.m', ...
 'scripts/validation/support/solve_layered_fluid_ffp.m', ...
 'scripts/validation/support/layered_fluid_green_kernel.m', ...
 'scripts/validation/support/read_bellhop_arrivals_ascii_vertical.m', ...
 'scripts/validation/support/bellhop_rotated_field_poc/RotatedFieldState.f90', ...
 'reports/bellhop_C_FFP_common_point_2026-11-16.md', ...
 'reports/bellhop_C_rays_remote_complete_2026-11-16.md', ...
 'reports/black_channel_basics_report.md'};
hashes=table(string(inputs(:)),strings(numel(inputs),1),'VariableNames',{'path','sha256'});
for k=1:height(hashes)
    assert(isfile(fullfile(project_root,hashes.path(k))));
    hashes.sha256(k)=string(black_file_hash(char(fullfile(project_root,hashes.path(k)))));
end
writetable(hashes,fullfile(output_dir,'inspected_inputs_sha256.csv'));
receipt=struct('status','DESIGN_ONLY_COMPLETE','analytic_rows',height(rows),'anchor_frequencies',numel(f), ...
    'geometry_checks_failed',0,'Bellhop_jobs',0,'FFP_jobs',0,'ABC_recomputed',0, ...
    'production_code_modified',false,'new_physical_qualification',false,'future_stages_authorized',false, ...
    'early_BS_axis_excess_ms',a.excess_delay_ms(a.path=="BS"), ...
    'first_late_SB_axis_excess_s',a.excess_delay_ms(a.path=="SB")/1000, ...
    'max_early_excess_ms',max(rows.excess_delay_ms(ismember(rows.path,["D","S","B","BS"]))), ...
    'max_N8_uniform_relative_delay_s',((1490+7*1500+1494)-1484)/c, ...
    'source_hashes',height(hashes),'matlab_version',version);
write_json(fullfile(output_dir,'checkpoint_design.json'),receipt);
fprintf('DESIGN_ONLY rows%d anchors%d Bellhop0 FFP0 ABC0\n',height(rows),numel(f));
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); closer=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(value,PrettyPrint=true));
end
