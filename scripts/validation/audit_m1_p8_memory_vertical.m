function receipt=audit_m1_p8_memory_vertical(output_dir)
%AUDIT_M1_P8_MEMORY_VERTICAL Read saved receipts and inventory; no propagation.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
assert(java.io.File(output_dir).isAbsolute());
assert(startsWith(char(java.io.File(output_dir).getCanonicalPath()), ...
    [fullfile(root,'results','validation','m1_p8_memory_diagnosis') filesep]));
assert(~isfolder(output_dir),'Preserve previous diagnosis.'); mkdir(output_dir);
t=tic; old_threads=maxNumCompThreads(1); cleanup=onCleanup(@()maxNumCompThreads(old_threads)); %#ok<NASGU>
run=fullfile(root,'results','validation','m1_convergence','20261111_m1_execution_03');
cp_path=fullfile(run,'P8','checkpoint.json'); cp=jsondecode(fileread(cp_path));
sample_path=fullfile(run,'external_resource_samples.csv');
samples=readtable(sample_path,'TextType','string');
p8=samples(strcmp(samples.Job,'P8'),:);
active=p8(p8.JobElapsedSeconds<cp.elapsed_s,:);
assert(height(active)==6 && strcmp(cp.status,'FAILED'));
assert(strcmp(cp.error_message,'RAM reserve fell below 30 percent of initial available RAM.'));
metrics=struct('startup_available_GiB',cp.available_before_bytes/2^30, ...
    'minimum_available_GiB',cp.min_available_bytes/2^30, ...
    'required_reserve_GiB',.3*cp.available_before_bytes/2^30, ...
    'available_decline_GiB',(cp.available_before_bytes-cp.min_available_bytes)/2^30, ...
    'reserve_shortfall_MiB',(.3*cp.available_before_bytes-cp.min_available_bytes)/2^20, ...
    'active_working_set_min_GiB',min(active.WorkingSetBytes)/2^30, ...
    'active_working_set_max_GiB',max(active.WorkingSetBytes)/2^30, ...
    'active_working_set_first_to_last_delta_MiB',(active.WorkingSetBytes(end)-active.WorkingSetBytes(1))/2^20, ...
    'session_peak_working_set_GiB',max(p8.SessionPeakWorkingSetBytes)/2^30, ...
    'session_peak_constant_during_P8',numel(unique(p8.SessionPeakWorkingSetBytes))==1, ...
    'matlab_max_reported_system_memory_GiB',cp.max_matlab_memory_bytes/2^30, ...
    'minimum_start_GiB_if_same_total_decline_repeats', ...
    (cp.available_before_bytes-cp.min_available_bytes)/(.7*2^30));
n=cp.config.n; n2=n^2;
names={'one_real_plane';'one_complex_plane';'P8_two_direct_slice_histories'; ...
    'Z8_two_direct_slice_histories';'five_retirable_outer_complex_buffers'; ...
    'one_local_denominator';'coordinate_XY_pair';'deferred_KX_KY_pair'};
counts=[n2*8;n2*16;2*n*(ceil(97/(.5*1500/8000))+1)*16; ...
    2*n*(ceil(97/(.25*1500/8000))+1)*16;5*n2*16;n2*16;2*n2*8;2*n2*8];
estimates=table(names,counts,counts/2^20,'VariableNames',{'item','payload_bytes','MiB'});
estimates.note=repmat("Static payload arithmetic only, not measured independent allocations or guaranteed RSS savings",height(estimates),1);
[user,sys]=memory; workspace=evalin('base','whos');
current=struct('matlab_version',version,'matlab_pid',feature('getpid'), ...
    'available_physical_bytes',sys.PhysicalMemory.Available,'total_physical_bytes',sys.PhysicalMemory.Total, ...
    'matlab_reported_system_memory_bytes',user.MemUsedMATLAB, ...
    'base_variable_count',numel(workspace),'base_declared_bytes',sum([workspace.bytes]), ...
    'scope','Metadata only; no base values read or cleared. Current snapshot is not reconstruction of P8-time system consumers.');
inputs={cp_path,sample_path,fullfile(run,'resource_stop.json'),fullfile(run,'artifacts_sha256.csv'), ...
    fullfile(root,'src','propagation','vertical_wape_propagator.m'), ...
    fullfile(root,'src','bubble','bubble_environment_vertical.m'), ...
    fullfile(root,'scripts','validation','run_m1_convergence_job_vertical.m')};
input_versions=struct('path',{},'sha256',{});
for j=1:numel(inputs), input_versions(end+1)=struct('path',inputs{j},'sha256',sha(inputs{j})); end %#ok<AGROW>
source_checks=struct('path',{},'match',{});
for j=1:numel(cp.source_sha256)
    x=cp.source_sha256(j); source_checks(end+1)=struct('path',x.path,'match',strcmpi(x.sha256,sha(fullfile(root,x.path)))); %#ok<AGROW>
end
manifest=readtable(fullfile(run,'artifacts_sha256.csv'),'TextType','string');
own_rows=startsWith(manifest.path,"results/validation/m1_convergence/20261111_m1_execution_03/");
old_output_checks=0;
for j=find(own_rows).'
    assert(strcmpi(manifest.sha256(j),sha(fullfile(root,manifest.path(j)))),'Sealed run output SHA mismatch.');
    old_output_checks=old_output_checks+1;
end
writetable(p8,fullfile(output_dir,'p8_process_samples.csv'));
writetable(estimates,fullfile(output_dir,'static_array_budget.csv'));
save(fullfile(output_dir,'diagnosis.mat'),'metrics','current','estimates','input_versions','source_checks');
jsonfile(fullfile(output_dir,'metrics.json'),metrics);
jsonfile(fullfile(output_dir,'current_metadata.json'),current);
receipt=struct('status','DIAGNOSIS_COMPLETE_NO_SOLVE','matlab_pid',feature('getpid'), ...
    'matlab_version',version,'elapsed_s',toc(t),'exit_code',0,'failed_checks',0, ...
    'execution_mode','existing MATLAB MCP, single thread, saved metadata/receipts only', ...
    'config',cp.config,'input_versions_sha256',input_versions,'code_sha256',sha([mfilename('fullpath') '.m']), ...
    'runtime_source_matches',sum([source_checks.match]),'runtime_source_count',numel(source_checks), ...
    'sealed_run_output_sha_checks',old_output_checks,'metrics',metrics, ...
    'limitations',{{'No P8-time global process/OS cache attribution snapshot', ...
        'No live inner-function whos/allocator trace during P8', ...
        'No benchmark or production implementation of proposed optimizations'}}, ...
    'next_allowed_step','Review plan; any implementation and solver rerun must preserve original M1 physical configuration and gates.');
jsonfile(fullfile(output_dir,'checkpoint.json'),receipt);
fprintf('P8_MEMORY_DIAGNOSIS %s\n',jsonencode(struct('status',receipt.status, ...
    'elapsed_s',receipt.elapsed_s,'source_matches',receipt.runtime_source_matches, ...
    'sealed_output_SHA_checks',old_output_checks,'metrics',metrics)));
end
function value=sha(file)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(file,'rb'); cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
while ~feof(fid), bytes=fread(fid,2^20,'*uint8'); if ~isempty(bytes), md.update(typecast(bytes,'int8')); end, end
value=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function jsonfile(file,s)
fid=fopen(file,'w','n','UTF-8'); fprintf(fid,'%s',jsonencode(s,PrettyPrint=true)); fclose(fid);
end
