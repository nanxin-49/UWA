function audit = audit_two_dimensional_s5_s6_analytic_controls(cir_dir,dsp_dir,audit_dir)
%AUDIT_TWO_DIMENSIONAL_S5_S6_ANALYTIC_CONTROLS Reopen saved analytic evidence.
arguments
    cir_dir (1,:) char
    dsp_dir (1,:) char
    audit_dir (1,:) char
end
assert(~isfolder(audit_dir) && ~isfile(audit_dir), ...
    'Use a fresh audit directory.');
s5 = load(fullfile(cir_dir,'nine_point_cir_controls.mat'));
s6 = load(fullfile(dsp_dir,'analytic_dsp_controls.mat'));
cir_csv = readtable(fullfile(cir_dir,'nine_point_cir_metrics.csv'));
geometry_csv = readtable(fullfile(cir_dir,'nine_point_geometry_and_arrivals.csv'));
dsp_csv = readtable(fullfile(dsp_dir,'analytic_dsp_metrics.csv'));

x_expected = repmat([-0.1953125;0;0.1953125],3,1);
z_expected = repelem([2.875;3;3.125],3);
id_expected = ["P11";"P12";"P13";"P21";"P22";"P23";"P31";"P32";"P33"];
geometry_error = max(abs([s5.xrx-x_expected;s5.zrx-z_expected; ...
    geometry_csv.x_m-x_expected;geometry_csv.z_m-z_expected]));
id_match = isequal(string(s5.ids),id_expected) && ...
    isequal(string(geometry_csv.receiver_id),id_expected);
tau_ref_error = abs(s5.tau_ref-96.875/1500);
arrival_error = max(abs([s5.arrival_d-(hypot(s5.xrx,100-s5.zrx)/1500-s5.tau_ref); ...
    s5.arrival_r-(hypot(s5.xrx,100+s5.zrx)/1500-s5.tau_ref); ...
    geometry_csv.direct_relative_s-s5.arrival_d; ...
    geometry_csv.reflect_relative_s-s5.arrival_r]));

N = numel(s5.f);
freq_error = max(abs([s5.f65-(4000+(0:64)'*62.5); ...
    s5.f129-(4000+(0:128)'*31.25); ...
    s5.f-s5.f65(1:64)]));
endpoint_direct = max(abs(exp(-1i*2*pi*8000*s5.arrival_d)- ...
    exp(-1i*2*pi*4000*s5.arrival_d)));
endpoint_reflect = max(abs(exp(-1i*2*pi*8000*s5.arrival_r)- ...
    exp(-1i*2*pi*4000*s5.arrival_r)));
endpoint_error = max(abs([endpoint_direct-s5.receipt.endpoint_direct_phase_difference_max; ...
    endpoint_reflect-s5.receipt.endpoint_reflect_phase_difference_max]));
closure_error = max(abs(s5.Ht-s5.Hd-s5.Hr),[],'all');
fft_error = max(abs(fft(s5.ht,[],1)-s5.Ht),[],'all');
native_error = 0;
for ic = 1:2
    for ir = 1:9
        direct = exp(-1i*2*pi*s5.f*(s5.tau_d(ir)-s5.tau_ref));
        reflect = conj(s5.alpha(ic))*exp(-1i*2*pi*s5.f* ...
            (s5.tau_r(ir)-s5.tau_ref));
        native_error = max(native_error,max(abs([s5.Hd(:,ir,ic)-direct; ...
            s5.Hr(:,ir,ic)-reflect])));
    end
end
cir_metric_csv_error = max(abs(table2array(cir_csv(:,3:end))- ...
    table2array(s5.metrics(:,3:end))),[],'all');

noiseless_errors = sum(s6.bits_noiseless~=s6.bits_noiseless_hat);
awgn_errors = sum(s6.bits_awgn~=s6.bits_awgn_hat);
noise_closure_error = max(abs(s6.tx_awgn+s6.noise-s6.rx_awgn));
evm = sqrt(mean(abs(s6.rx_awgn-s6.tx_awgn).^2)/ ...
    mean(abs(s6.tx_awgn).^2));
awgn_ber_error = abs(awgn_errors/numel(s6.bits_awgn)-s6.receipt.awgn_ber);
evm_error = abs(evm-s6.receipt.awgn_evm_rms);
dsp_csv_error = max(abs([dsp_csv.awgn_bit_errors-awgn_errors; ...
    dsp_csv.awgn_ber-s6.receipt.awgn_ber; ...
    dsp_csv.awgn_evm_rms-s6.receipt.awgn_evm_rms]));
frequency_carrier_error = max(abs([s6.f_axis_hz-(4000+(0:63)'*62.5); ...
    s6.frequency_meta.f_bb_axis_hz-(s6.f_axis_hz-6000)]));
frequency_response_error = max(abs([s6.frequency_meta.H_baseband-s6.H_f; ...
    fftshift(fft(s6.frequency_meta.h_full))-s6.H_f]));
natural_bits = s6.bits_awgn;
natural_bits(2:2:end) = xor(s6.bits_awgn(1:2:end), ...
    s6.bits_awgn(2:2:end));
[tx_check,~] = modem_psk('modulate',natural_bits,4);
tx_mapping_error = max(abs(tx_check-s6.tx_awgn));
natural_hat = modem_psk('demodulate',s6.rx_awgn,4);
gray_hat = natural_hat;
gray_hat(2:2:end) = xor(natural_hat(1:2:end),natural_hat(2:2:end));
gray_demod_error_count = sum(gray_hat~=s6.bits_awgn_hat);
q = 0.5*erfc(sqrt(10^(s6.cfg.EbN0_dB/10)));
binomial_probability_error = abs(q-s6.receipt.gray_qpsk_predicted_ber);
interval = s6.receipt.awgn_bit_error_prediction_count_95;
n_bits = numel(s6.bits_awgn);
binomial_interval_valid = local_binom_cdf(interval(1)-1,n_bits,q)<0.025 && ...
    local_binom_cdf(interval(1),n_bits,q)>=0.025 && ...
    local_binom_cdf(interval(2)-1,n_bits,q)<0.975 && ...
    local_binom_cdf(interval(2),n_bits,q)>=0.975;

gates = struct('geometry',geometry_error==0 && id_match, ...
    'global_time_reference',tau_ref_error<=1e-14 && arrival_error<=1e-14, ...
    'frequency_grid',freq_error==0 && N==64 && ...
        s5.receipt.refined_independent_fft_bins==128 && ...
        abs(s5.receipt.refined_delay_window_s-0.032)<=1e-15 && ...
        endpoint_error<=1e-12, ...
    'native_and_component_closure',native_error<=1e-10 && closure_error<=1e-10, ...
    'fft_and_csv',fft_error<=1e-10 && cir_metric_csv_error<=1e-10, ...
    'dsp_counts',noiseless_errors==0 && ...
        awgn_errors==s6.receipt.awgn_bit_errors, ...
    'dsp_noise_and_csv',noise_closure_error<=1e-12 && ...
        awgn_ber_error<=1e-14 && evm_error<=1e-14 && dsp_csv_error<=1e-14, ...
    'dsp_frequency_contract',frequency_carrier_error==0 && ...
        frequency_response_error<=1e-12 && ...
        s6.frequency_meta.circular_shift_samples==0, ...
    'gray_awgn_prediction',tx_mapping_error<=1e-12 && ...
        gray_demod_error_count==0 && binomial_probability_error<=1e-14 && ...
        binomial_interval_valid);
failed_check_count=sum(~cell2mat(struct2cell(gates)));
if failed_check_count==0
    status='ANALYTIC_CONTROLS_INDEPENDENT_AUDIT_PASS';
else
    status='ANALYTIC_CONTROLS_INDEPENDENT_AUDIT_FAIL';
end
audit = struct('status',status,'failed_check_count',failed_check_count, ...
    'geometry_error_m',geometry_error,'global_tau_ref_error_s',tau_ref_error, ...
    'arrival_error_s',arrival_error,'frequency_grid_error_hz',freq_error, ...
    'endpoint_phase_audit_error',endpoint_error, ...
    'native_formula_max_abs_error',native_error, ...
    'component_closure_max_abs_error',closure_error, ...
    'fft_max_abs_error',fft_error,'cir_csv_max_abs_error',cir_metric_csv_error, ...
    'noiseless_bit_errors_recomputed',noiseless_errors, ...
    'awgn_bit_errors_recomputed',awgn_errors, ...
    'noise_closure_max_abs_error',noise_closure_error, ...
    'awgn_ber_error',awgn_ber_error,'evm_error',evm_error, ...
    'dsp_csv_error',dsp_csv_error,'gates',gates);
audit.frequency_carrier_error_hz=frequency_carrier_error;
audit.frequency_response_max_abs_error=frequency_response_error;
audit.gray_tx_mapping_max_abs_error=tx_mapping_error;
audit.gray_demod_mismatch_count=gray_demod_error_count;
audit.binomial_probability_error=binomial_probability_error;
audit.binomial_interval_valid=binomial_interval_valid;
mkdir(audit_dir);
fid=fopen(fullfile(audit_dir,'audit.json'),'w');
assert(fid>0,'Cannot write audit.json.');
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(audit,PrettyPrint=true));
disp(audit);
if failed_check_count>0
    error('Analytic controls independent audit failed.');
end
end

function cdf = local_binom_cdf(k,n,p)
if k<0
    cdf=0;
elseif k>=n
    cdf=1;
else
    cdf=betainc(1-p,n-k,k+1);
end
end
