function output = prepare_bellhop_rotated_multifield_overlay(field_overlay,output_dir)
%PREPARE_BELLHOP_ROTATED_MULTIFIELD_OVERLAY Explicit flat-wall reflection order.
% mode5 alternates physical surface/bottom walls in a folded Q chart. It keeps
% source c/outplane integral/exact coordinates and disables implicit Amp<.005.
arguments
    field_overlay (1,:) char
    output_dir (1,:) char
end
assert(~isfolder(output_dir)); mkdir(output_dir);
for name={'sspMod.f90','influence.f90','RotatedFieldState.f90'}
    copyfile(fullfile(field_overlay,name{1}),fullfile(output_dir,name{1}));
end
step=normalize(fileread(fullfile(field_overlay,'Step.f90')));
anchor='    WallHit = WallActive .AND. iWallSeg > 0 .AND. ABS( wallResidual ) <= 1.0d-8';
step=once(step,anchor,join([anchor ...
    "    IF(RotQEnabled.AND.WallActive.AND.iWallSeg>0.AND..NOT.WallHit) THEN" ...
    "       IF(ABS(wallResidual)<1d-3.OR.(ray0%x(1)<WallX(1,1).AND.ray2%x(1)>WallX(1,1))) &" ...
    "            WRITE(94,'(*(ES25.16E3,1X))') WallX(1,1),ray0%x,ray2%x,h,hw0,hw1,wallResidual" ...
    "    END IF"],newline));
% At a Q breakpoint coinciding with the physical wall, h4 can win over
% hWall by one ulp. Never enlarge that wall-clipped step to native min-step.
step=once(step,'h == hWall ) THEN', ...
    '(h == hWall .OR. (RotQEnabled.AND.h<=hWall)) ) THEN');
write(fullfile(output_dir,'Step.f90'),step);
path=fullfile(field_overlay,'bellhop.f90');
assert(strcmp(black_file_hash(path),'4e75264611a5d0b6e8dd5f59f6c8884cfeb914b3b2548dd3a2a4ea606d28e8d4'));
text=normalize(fileread(path));
text=once(text,'ModeCode > 4','ModeCode > 5');
% All existing mode3 flat-wall geometry hooks are also needed by mode5.
text=strrep(text,'IWallMode == 3','( IWallMode == 3 .OR. IWallMode == 5 )');
text=once(text,'IWallMode /= 2 .AND. IWallMode /= 3 .AND. IWallMode /= 4 .AND.', ...
    'IWallMode /= 2 .AND. IWallMode /= 3 .AND. IWallMode /= 4 .AND. IWallMode /= 5 .AND.');
text=once(text,'(IWallMode /= 3 .AND. MINVAL', ...
    '(IWallMode /= 3 .AND. IWallMode /= 5 .AND. MINVAL');
text=once(text,'  TYPE(HSInfo) :: RotQWallHS',join([ ...
    "  TYPE(HSInfo) :: RotQWallHS, RotQBottomHS" ...
    "  INTEGER :: RotQRequestedOrder=1, RotQWallCount=0, RotQSurfaceCount=0, RotQBottomCount=0" ...
    "  REAL(KIND=8) :: RotQFirstWall=0d0, RotQWaterDepth=5000d0"],newline));
text=once(text,'     CLOSE(RotFile)',join([ ...
    "     RotQFirstWall=IWallR0" ...
    "     RotQBottomHS=RotQWallHS; RotQBottomHS%BC='A'" ...
    "     IF(IWallMode==5) THEN" ...
    "        READ(RotFile,*,IOSTAT=RotIOS) RotQRequestedOrder,RotQWaterDepth" ...
    "        IF(RotIOS/=0.OR.RotQRequestedOrder<1.OR.RotQRequestedOrder>50.OR.RotQWaterDepth<=0d0) &" ...
    "             CALL ERROUT('BELLHOP-MULTI','Invalid explicit reflection order/depth')" ...
    "        IF(RotQFirstWall<=0d0.OR.RotQFirstWall>=RotQWaterDepth) &" ...
    "             CALL ERROUT('BELLHOP-MULTI','Invalid first-wall range')" ...
    "     END IF" ...
    "     CLOSE(RotFile)"],newline));
text=once(text,'  iSmallStepCtr = 0',join([ ...
    "  iSmallStepCtr = 0" ...
    "  IF(IWallMode==5) THEN" ...
    "     IWallR0=RotQFirstWall" ...
    "     RotQWallCount=0; RotQSurfaceCount=0; RotQBottomCount=0" ...
    "     CALL ConfigureWallProfile(IWallRProfile,IWallZProfile,IWallNProfile)" ...
    "  END IF"],newline));
anchor="        CALL Reflect2D( is, WallHS, 'TOP', WallT, WallN, WallKappa, RTop, NTopPTS )"+newline+ ...
    "        ray2D( is + 1 )%NumTopBnc = ray2D( is )%NumTopBnc + 1";
text=once(text,anchor,join([ ...
    anchor ...
    "        IF(IWallMode==5) THEN" ...
    "           RotQWallCount=RotQWallCount+1" ...
    "           IF(WallHS%BC=='V') THEN" ...
    "              RotQSurfaceCount=RotQSurfaceCount+1" ...
    "           ELSE" ...
    "              RotQBottomCount=RotQBottomCount+1" ...
    "           END IF" ...
    "           ray2D(is+1)%NumTopBnc=RotQSurfaceCount" ...
    "           ray2D(is+1)%NumBotBnc=RotQBottomCount" ...
    "        END IF"],newline));
anchor='        WallDidReflect    = .TRUE.';
text=once(text,anchor,join([ ...
    anchor ...
    "        IF(IWallMode==5.AND.RotQWallCount<RotQRequestedOrder) THEN" ...
    "           IWallR0=IWallR0+RotQWaterDepth" ...
    "           CALL ConfigureWallProfile(IWallRProfile+(IWallR0-RotQFirstWall),IWallZProfile,IWallNProfile)" ...
    "           WallActive=.TRUE." ...
    "           IF(WallHS%BC=='V') THEN" ...
    "              WallHS=RotQBottomHS" ...
    "           ELSE" ...
    "              WallHS%BC='V'" ...
    "           END IF" ...
    "        END IF"],newline));
text=once(text,'ray2D( is + 1 )%Amp < 0.005', ...
    '(IWallMode/=5 .AND. ray2D( is + 1 )%Amp < 0.005)');
old=join([ ...
    '  IF ( ray2D( Beam%Nsteps )%NumTopBnc /= 1 .OR. ray2D( Beam%Nsteps )%NumBotBnc /= 0 ) &' ...
    "       CALL ERROUT( 'BELLHOP-IWALL', 'Unexpected outer-boundary or repeated reflection' )"],newline);
new=join([ ...
    "  IF(IWallMode==5) THEN" ...
    "     IF(RotQWallCount/=RotQRequestedOrder) CALL ERROUT('BELLHOP-MULTI','Requested reflection order not reached')" ...
    "     IF(ray2D(Beam%Nsteps)%NumTopBnc/=RotQSurfaceCount.OR.ray2D(Beam%Nsteps)%NumBotBnc/=RotQBottomCount) &" ...
    "          CALL ERROUT('BELLHOP-MULTI','Unexpected artificial boundary reflection')" ...
    "  ELSE" old "  END IF"],newline);
text=once(text,old,new);
text=once(text,'  CALL BellhopCore',join([ ...
    "  OPEN(UNIT=95,FILE=TRIM(FileRoot)//'.mwdiag',STATUS='REPLACE',ACTION='WRITE')" ...
    "  WRITE(95,'(A)') '# alpha_deg requested_order walls_done surface_bounces bottom_bounces steps end_r_m end_amp'" ...
    "  OPEN(UNIT=94,FILE=TRIM(FileRoot)//'.mwstep',STATUS='REPLACE',ACTION='WRITE')" ...
    "  WRITE(94,'(A)') '# wall_r r0 q0 r2 q2 h hw0 hw1 residual'" ...
    "  CALL BellhopCore" ...
    "  CLOSE(94)" ...
    "  CLOSE(95)"],newline));
anchor="  WRITE(97,'(*(ES25.16E3,1X))') RadDeg*alpha, ray2D(Beam%Nsteps)%x, &";
text=once(text,anchor,join([ ...
    "  IF(IWallMode==5) WRITE(95,'(*(ES25.16E3,1X))') RadDeg*alpha,REAL(RotQRequestedOrder,KIND=8), &" ...
    "       REAL(RotQWallCount,KIND=8),REAL(RotQSurfaceCount,KIND=8),REAL(RotQBottomCount,KIND=8), &" ...
    "       REAL(Beam%Nsteps,KIND=8),ray2D(Beam%Nsteps)%x(1),ray2D(Beam%Nsteps)%Amp" ...
    anchor],newline));
write(fullfile(output_dir,'bellhop.f90'),text);
module=normalize(fileread(fullfile(field_overlay,'bellhopMod.f90')));
module=once(module,'MaxN = 100000','MaxN = 600000');
write(fullfile(output_dir,'bellhopMod.f90'),module);
build=normalize(fileread(fullfile(field_overlay,'build_rotated_field.ps1')));
build=strrep(build,'bellhop_rotated_field_2020.exe','bellhop_rotated_multifield_2020.exe');
build=strrep(build,'Bellhop 2020 validation-only direct and one-flat-wall rotated Q; 3D spreading remains diagnostic', ...
    'Bellhop 2020 validation-only explicit-order folded Q; derived 3D transport; full field unqualified');
write(fullfile(output_dir,'build_rotated_multifield.ps1'),build);
files={'bellhop.f90','bellhopMod.f90','Step.f90','sspMod.f90','influence.f90','RotatedFieldState.f90'};
hashes=struct('path',{},'sha256',{});
for j=1:numel(files)
    path=fullfile(output_dir,files{j}); hashes(j)=struct('path',path,'sha256',black_file_hash(path));
end
output=struct('status','SOURCE_PREPARED_NOT_COMPILED','output_dir',output_dir,'source_sha256',hashes, ...
    'max_ray_nodes',600000,'scope','Explicit requested reflection order; no complete field qualification yet', ...
    'unrun_checks',{{'compile','disabled regression','multi-reflection coefficients/counts/field consistency','resource pilot','full field/FFP'}});
write(fullfile(output_dir,'checkpoint.json'),jsonencode(output,PrettyPrint=true)); disp(jsonencode(output));
end
function t=normalize(t)
t=strrep(t,sprintf('\r\n'),newline);
end
function t=once(t,old,new)
assert(isscalar(strfind(t,char(old))),'Patch anchor drift.');
t=strrep(char(t),char(old),char(new));
end
function write(path,value)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); c=onCleanup(@()fclose(fid));
fprintf(fid,'%s',value);
end
