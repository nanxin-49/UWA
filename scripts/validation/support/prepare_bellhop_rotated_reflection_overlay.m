function output = prepare_bellhop_rotated_reflection_overlay(direct_overlay,official_root,output_dir)
%PREPARE_BELLHOP_ROTATED_REFLECTION_OVERLAY One flat wall with folded Q SSP.
% mode3 enables only this isolated extension. Native Reflect2D is preserved.
% Native R spreading is still diagnostic; this stage fixes chart/beam width,
% one-sided incident gradient, and duplicate Q-seam kick, not full 3D spreading.
arguments
    direct_overlay (1,:) char
    official_root (1,:) char
    output_dir (1,:) char
end
assert(~isfolder(output_dir)); mkdir(output_dir);
bh=fullfile(direct_overlay,'bellhop.f90');
assert(strcmp(black_file_hash(bh),'ad535ddf8fc01590387a5ce57e571fe9f7005bcdc523cb7fc6f3e6dba951699b'));
text=normalize(fileread(bh));
text=once(text,'ModeCode > 2','ModeCode > 3');
text=once(text,'MINVAL( Pos%Rr( 1 : Pos%NRr ) ) <= IWallR0', ...
    'MINVAL( Pos%Rr( 1 : Pos%NRr ) ) < IWallR0 .OR. (IWallMode /= 3 .AND. MINVAL(Pos%Rr(1:Pos%NRr)) == IWallR0)');
text=strrep(text,'IWallMode == 1','( IWallMode == 1 .OR. IWallMode == 3 )');
text=once(text,'IWallMode /= 2 .AND.','IWallMode /= 2 .AND. IWallMode /= 3 .AND.');
text=once(text,"  IF ( IWallMode == 2 ) THEN","  IF ( IWallMode == 2 .OR. IWallMode == 3 ) THEN");
text=once(text,"  INTEGER             :: IWallMode = 1",join([ ...
    "  INTEGER             :: IWallMode = 1" ...
    "  TYPE(HSInfo) :: RotQWallHS" ...
    "  REAL(KIND=8) :: RotQOrigin = 0d0, RotCPReal, RotCPImag, RotRho"],newline));
text=once(text,'  INTEGER                         :: ii, ModeCode', ...
    '  INTEGER                         :: ii, ModeCode, RotFile, RotIOS');
anchor="  WRITE( PRTFile, * ) 'Validation-only wall covariance mode = ', IWallMode";
read_block=join([ ...
    "  IF ( IWallMode == 3 ) THEN" ...
    "     RotQWallHS = Bdry%Top%HS" ...
    "     OPEN(NEWUNIT=RotFile,FILE=TRIM(FileRootIn)//'.rotq',STATUS='OLD',ACTION='READ',IOSTAT=RotIOS)" ...
    "     IF (RotIOS /= 0) CALL ERROUT('BELLHOP-ROTQ','Missing .rotq wall properties')" ...
    "     READ(RotFile,*,IOSTAT=RotIOS) RotQOrigin, RotQWallHS%BC, RotCPReal, RotCPImag, RotRho" ...
    "     IF (RotIOS /= 0 .OR. RotRho <= 0d0) CALL ERROUT('BELLHOP-ROTQ','Invalid .rotq wall properties')" ...
    "     IF (RotQWallHS%BC /= 'V' .AND. RotQWallHS%BC /= 'A') CALL ERROUT('BELLHOP-ROTQ','Only vacuum/fluid walls')" ...
    "     RotQWallHS%cP = CMPLX(RotCPReal,RotCPImag,KIND=8)" ...
    "     RotQWallHS%cS = CMPLX(0d0,0d0,KIND=8)" ...
    "     RotQWallHS%rho = RotRho" ...
    "     CLOSE(RotFile)" ...
    "  END IF" ...
    anchor],newline);
text=once(text,anchor,read_block);
text=once(text,"  ray2D( 1 )%c         = c",join([ ...
    "  ray2D( 1 )%c         = c" ...
    "  RotQEnabled = IWallMode == 3" ...
    "  RotQSourceC = c"],newline));
text=once(text,"  WallHS%BC        = 'V'", ...
    "  WallHS%BC        = 'V'"+newline+"  IF ( IWallMode == 3 ) WallHS = RotQWallHS");
text=once(text,'-ray2D( is + 1 )%x( 2 ) ]','2d0 * RotQOrigin - ray2D( is + 1 )%x( 2 ) ]');
original="  CALL EvaluateSSP( ray2D( is )%x, c, cimag, gradc, crr, crz, czz, rho, freq, 'TAB' )   ! just to get c";
incident=join([ ...
    "  IF ( IWallMode == 3 ) THEN" ...
    "     ! Folded Q changes derivative at the wall: Reflect2D needs incident-side medium." ...
    "     CALL EvaluateSSP( [NEAREST(ray2D(is)%x(1),-1d0),ray2D(is)%x(2)], c, cimag, gradc, crr, crz, czz, rho, freq, 'TAB' )" ...
    "  ELSE" original "  END IF"],newline);
text=once(text,original,incident);
% Close the wall intersection to the exact known plane before changing chart.
% This removes nanometre geometric residuals; it never fills receiver fields.
text=once(text,'  REAL(KIND=8) :: RotQOrigin = 0d0, RotCPReal, RotCPImag, RotRho', ...
    "  REAL(KIND=8) :: RotQOrigin = 0d0, RotCPReal, RotCPImag, RotRho"+newline+ ...
    "  REAL(KIND=8) :: RotQSnapResidual = 0d0");
text=once(text,'        IncidentState = ray2D( is1 )',join([ ...
    "        IF (IWallMode == 3) THEN" ...
    "           RotQSnapResidual = ray2D(is1)%x(1) - IWallR0" ...
    "           IF (ABS(RotQSnapResidual)>1d-8) CALL ERROUT('BELLHOP-ROTQ','Wall root closure exceeds 1e-8m')" ...
    "           ray2D(is1)%x(1) = IWallR0" ...
    "        END IF" ...
    "        IncidentState = ray2D( is1 )"],newline));
text=once(text,'NEAREST(ray2D(is)%x(1),-1d0)','NEAREST(IWallR0,-1d0)');
text=once(text,"     RotQWallHS = Bdry%Top%HS", ...
    "     IF (MAXVAL(ABS(IWallRProfile-IWallR0))>1d-10) CALL ERROUT('BELLHOP-ROTQ','Mode3 requires a flat vertical wall')"+newline+ ...
    "     RotQWallHS = Bdry%Top%HS");
text=once(text, ...
    "'tau_receiver_real tau_receiver_imag min_post_dr n_post kappa wall_seg wall_lambda wall_tg wall_th wall_rm wall_rn'", ...
    "'tau_receiver_real tau_receiver_imag min_post_dr n_post kappa wall_seg wall_lambda wall_tg wall_th wall_rm wall_rn pre_snap_wall_residual_m'");
text=once(text, ...
    '       REAL( WallSeg, KIND=8 ), WallLambda, IWallTgDiag, IWallThDiag, IWallRMDiag, IWallRNDiag', ...
    '       REAL( WallSeg, KIND=8 ), WallLambda, IWallTgDiag, IWallThDiag, IWallRMDiag, IWallRNDiag, RotQSnapResidual');
write(fullfile(output_dir,'bellhop.f90'),text);

step=normalize(fileread(fullfile(direct_overlay,'Step.f90')));
step=once(step,"  IMPLICIT NONE",join([ ...
    "  IMPLICIT NONE" ...
    "  LOGICAL :: RotQEnabled = .FALSE." ...
    "  REAL(KIND=8) :: RotQSourceC = 0d0"],newline));
step=once(step,"    IF ( iSegz /= iSegz0 .OR. iSegr /= iSegr0 ) THEN",join([ ...
    "    ! Native Reflect2D supplies the physical wall kick. Do not also apply" ...
    "    ! a Q interpolation-gradient jump at the same chart seam." ...
    "    IF ( ( iSegz /= iSegz0 .OR. iSegr /= iSegr0 ) .AND. .NOT.(RotQEnabled .AND. WallHit) ) THEN"],newline));
write(fullfile(output_dir,'Step.f90'),step);

ip=fullfile(official_root,'Bellhop','influence.f90');
assert(strcmp(black_file_hash(ip),'8188087f79548c4b640dd4c2c1ad547a5dc46dba729fd42154a491039f544c1c'));
influence=normalize(fileread(ip));
influence=once(influence,'  USE WriteRay',"  USE WriteRay"+newline+"  USE Step, ONLY: RotQEnabled, RotQSourceC");
first=strfind(influence,'  SUBROUTINE InfluenceGeoHatCart(');
last=strfind(influence,'  END SUBROUTINE InfluenceGeoHatCart');
assert(isscalar(first) && isscalar(last));
last=last+strlength('  END SUBROUTINE InfluenceGeoHatCart')-1;
part=influence(first:last);
anchor='    q0           = ray2D( 1 )%c / Dalpha   ! Reference for J = q0 / q';
part=once(part,anchor,string(anchor)+newline+ ...
    "    IF ( RotQEnabled ) q0 = RotQSourceC / Dalpha ! physical source survives post-wall branch isolation");
anchor="    irT = MINLOC( Pos%Rr( 1 : Pos%NRr ), MASK = Pos%Rr( 1 : Pos%NRr ) > rA )   ! find index of first receiver to the right of rA";
part=once(part,anchor,join([ ...
    "    IF ( RotQEnabled ) THEN" ...
    "       ! The branch starts at a physical wall, not at the singular source." ...
    "       irT = MINLOC(Pos%Rr(1:Pos%NRr),MASK=Pos%Rr(1:Pos%NRr) >= rA)" ...
    "    ELSE" anchor "    END IF"],newline));
influence=[influence(1:first-1),part,influence(last+1:end)];
write(fullfile(output_dir,'influence.f90'),influence);

build=normalize(fileread(fullfile(direct_overlay,'build_rotated_direct_q.ps1')));
anchor="Copy-Item -LiteralPath (Join-Path $supportDir 'bellhop.f90') -Destination (Join-Path $buildRoot 'Bellhop\bellhop.f90') -Force";
build=once(build,anchor,anchor+newline+ ...
    "Copy-Item -LiteralPath (Join-Path $supportDir 'influence.f90') -Destination (Join-Path $buildRoot 'Bellhop\influence.f90') -Force");
build=once(build,"'WriteRay.f90','influence.f90','Step.f90'","'WriteRay.f90','Step.f90','influence.f90'");
build=strrep(build,'bellhop_rotated_direct_q_2020.exe','bellhop_rotated_reflected_q_2020.exe');
build=strrep(build,'direct rotated Q; reflected Q remains disabled','direct and one-flat-wall rotated Q; 3D spreading remains diagnostic');
write(fullfile(output_dir,'build_rotated_reflected_q.ps1'),build);
output=struct('status','SOURCE_PREPARED_NOT_COMPILED','scope','Single flat wall Q; source spreading still diagnostic', ...
    'direct_overlay_sha256',black_file_hash(bh),'official_influence_sha256',black_file_hash(ip), ...
    'bellhop_sha256',black_file_hash(fullfile(output_dir,'bellhop.f90')), ...
    'step_sha256',black_file_hash(fullfile(output_dir,'Step.f90')), ...
    'influence_sha256',black_file_hash(fullfile(output_dir,'influence.f90')), ...
    'output_dir',output_dir,'unrun_checks',{{'compilation','disabled mode regression','one-sided gradient/pq audit','reflection coefficient/time/field audit'}});
write(fullfile(output_dir,'checkpoint.json'),jsonencode(output,PrettyPrint=true));
disp(jsonencode(output));
end
function result=normalize(text)
result=strrep(text,sprintf('\r\n'),newline);
end
function text=once(text,old,new)
assert(isscalar(strfind(text,char(old))),'Patch anchor drift.');
text=strrep(char(text),char(old),char(new));
end
function write(path,text)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); c=onCleanup(@()fclose(fid));
fprintf(fid,'%s',text);
end