function c=summarize_deepsea3d_azimuth_comparison(s)
%SUMMARIZE_DEEPSEA3D_AZIMUTH_COMPARISON Separate field contrast and model error.
assert(s.reference_ready && numel(s.fk)==5);
b=s.baseline;fx=b.fk(2);rx=b.runs(b.reference_index).result;
fy=s.fk(2);ry=s.runs(s.reference_index).result;
mx=local_metrics(fx,rx);my=local_metrics(fy,ry);
refs_x=[b.runs(b.coarse_index).result,b.runs(b.fine_index).result,rx];
refs_y=[s.runs(s.coarse_index).result,s.runs(s.fine_index).result,ry];
row_x=local_row("x",0,b.cfg,mx,fx,rx,refs_x);
row_y=local_row("y",90,s.cfg,my,fy,ry,refs_y);
names=fieldnames(mx);envelopes=struct([]);
for j=1:numel(names)
    name=names{j};vx=local_variants(b.fk,refs_x,name);vy=local_variants(s.fk,refs_y,name);
    lo_x=min(vx);hi_x=max(vx);lo_y=min(vy);hi_y=max(vy);direction="UNRESOLVED";
    if lo_y>hi_x,direction="INCREASE";elseif hi_y<lo_x,direction="DECREASE";end
    row=struct('metric',string(name),'x_min',lo_x,'x_max',hi_x,'y_min',lo_y,'y_max',hi_y, ...
        'primary_difference',my.(name)-mx.(name),'ranges_disjoint',hi_y<lo_x || lo_y>hi_x,'direction',direction);
    if j==1,envelopes=repmat(row,numel(names),1);else,envelopes(j)=row;end
end
directionality=[local_contrast('reflect_native',rx,ry,fx,fy,refs_x,refs_y), ...
    local_contrast('rough_correction',rx,ry,fx,fy,refs_x,refs_y)];
c=struct('metrics_x',mx,'metrics_y',my,'row_x',row_x,'row_y',row_y, ...
    'envelopes',envelopes,'directionality',directionality, ...
    'reference_variant_count_each',3,'FK_variant_count_each',5, ...
    'scope','fixed anisotropic sea; empirical discrete reference/FK variants, not confidence intervals or rigorous bounds');
end
function m=local_metrics(f,r)
m=struct('reflected_complex',abs(f.reflect_native-r.reflect_native)/abs(r.reflect_native), ...
    'increment_complex',abs(f.rough_correction-r.rough_correction)/abs(r.rough_correction), ...
    'reflected_magnitude',abs(abs(f.reflect_native)-abs(r.reflect_native))/abs(r.reflect_native), ...
    'increment_magnitude',abs(abs(f.rough_correction)-abs(r.rough_correction))/abs(r.rough_correction), ...
    'reflected_phase_rad',angle(f.reflect_native*conj(r.reflect_native)), ...
    'increment_phase_rad',angle(f.rough_correction*conj(r.rough_correction)));
end
function v=local_variants(fk,refs,name)
v=zeros(numel(fk)*numel(refs),1);j=0;
for f=fk
    for r=refs
        m=local_metrics(f,r);j=j+1;v(j)=m.(name);
    end
end
end
function row=local_row(axis,phi,cfg,m,f,r,refs)
bg=deepsea3d_flat(cfg,0);
row=struct('axis',axis,'azimuth_deg',phi,'q',.1, ...
    'reflected_complex',m.reflected_complex,'increment_complex',m.increment_complex, ...
    'reflected_magnitude',m.reflected_magnitude,'increment_magnitude',m.increment_magnitude, ...
    'reflected_phase_rad',m.reflected_phase_rad,'increment_phase_rad',m.increment_phase_rad, ...
    'reference_reflect_real',real(r.reflect_native),'reference_reflect_imag',imag(r.reflect_native), ...
    'reference_delta_real',real(r.rough_correction),'reference_delta_imag',imag(r.rough_correction), ...
    'reference_reflect_abs',abs(r.reflect_native),'reference_delta_abs',abs(r.rough_correction), ...
    'reference_total_abs',abs(r.total_native), ...
    'flat_total_condition',(abs(bg.direct_native)+abs(bg.reflect_native))/abs(bg.total_native), ...
    'rough_total_condition',(abs(bg.direct_native)+abs(r.reflect_native))/abs(r.total_native), ...
    'reflected_background_increment_condition',(abs(bg.reflect_native)+abs(r.rough_correction))/abs(r.reflect_native), ...
    'pressure_order_sum_indicator',sum(abs(r.terms))/abs(r.rough_correction), ...
    'FK_density_indicator',f.cancellation_condition, ...
    'total_complex_error',abs(f.total_native-r.total_native)/abs(r.total_native), ...
    'reference_total_variant_change',max(arrayfun(@(v)abs(v.total_native-r.total_native)/abs(r.total_native),refs)));
end
function row=local_contrast(field,rx,ry,fx,fy,refs_x,refs_y)
px=rx.(field);py=ry.(field);contrast=py-px;contrast_fk=fy.(field)-fx.(field);
variants=complex(zeros(numel(refs_x)*numel(refs_y),1));relative=real(variants);j=0;
for x=refs_x
    for y=refs_y
        j=j+1;variants(j)=y.(field)-x.(field);relative(j)=abs(variants(j))/abs(x.(field));
    end
end
spread=max(abs(variants-contrast));
row=struct('field',string(field),'y_minus_x_real',real(contrast),'y_minus_x_imag',imag(contrast), ...
    'relative_complex_change_to_x',abs(contrast)/abs(px),'y_to_x_magnitude_ratio',abs(py)/abs(px), ...
    'y_minus_x_phase_rad',angle(py*conj(px)), ...
    'relative_change_min',min(relative),'relative_change_max',max(relative), ...
    'reference_contrast_abs',abs(contrast),'reference_variant_max_abs_displacement',spread, ...
    'reference_contrast_spread_relative',spread/max(abs(contrast),realmin), ...
    'FK_contrast_complex_error',abs(contrast_fk-contrast)/max(abs(contrast),realmin), ...
    'physical_contrast_resolved_against_observed_reference_variants',abs(contrast)>spread, ...
    'nonzero_contrast',abs(contrast)>0);
end
