function p=audit_fk_multifrequency_phase(d)
%AUDIT_FK_MULTIFREQUENCY_PHASE Native phasors and already IFFT-ready transfers.
% Collect scalar complex fields without conjugating them. The physical
% carrier is prescribed geometry, not a fitted unwrap branch/phase offset.
f=vertcat(d.frequency_hz); a=vertcat(d.H_full_dsp); b=vertcat(d.H_fast_dsp);
pr=unwrap(angle(vertcat(d.H_full_reduced))); qr=unwrap(angle(vertcat(d.H_fast_reduced)));
phys=pr+2*pi*f*103/1500; phyq=qr+2*pi*f*103/1500;
p=struct('f_hz',f,'full_physical_unwrapped',phys,'fast_physical_unwrapped',phyq, ...
 'full_physical_blind_unwrap',unwrap(angle(vertcat(d.H_full_physical))), ...
 'fast_physical_blind_unwrap',unwrap(angle(vertcat(d.H_fast_physical))), ...
 'full_dsp_unwrapped',unwrap(angle(a)),'fast_dsp_unwrapped',unwrap(angle(b)), ...
 'full_physical_group_delay_s',-gradient(phys,f)/(2*pi), ...
 'fast_physical_group_delay_s',-gradient(phyq,f)/(2*pi), ...
 'full_dsp_group_delay_s',-gradient(unwrap(angle(a)),f)/(2*pi), ...
 'fast_dsp_group_delay_s',-gradient(unwrap(angle(b)),f)/(2*pi), ...
 'relative_phase_rad',angle(b.*conj(a)), ...
 'reduced_adjacent_phase_max',max(abs(diff(pr))), ...
 'cir_full',ifft(a),'cir_fast',ifft(b),'delay_s',(0:numel(f)-1)'/(numel(f)*mean(diff(f))));
p.relative_phase_max=max(abs(p.relative_phase_rad));
p.group_delay_difference_max_s=max(abs(p.full_dsp_group_delay_s-p.fast_dsp_group_delay_s));
p.cir_l2=norm(p.cir_full-p.cir_fast)/norm(p.cir_full);
end
