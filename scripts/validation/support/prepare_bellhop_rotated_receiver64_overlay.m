function receipt = prepare_bellhop_rotated_receiver64_overlay(accepted_overlay,official_root,output_dir)
%PREPARE_BELLHOP_ROTATED_RECEIVER64_OVERLAY Isolated exact-input precision fix.
% Original ENV values are never changed. Legacy no-sidecar path is retained.
arguments
    accepted_overlay (1,:) char
    official_root (1,:) char
    output_dir (1,:) char
end
assert(~isfolder(output_dir)); mkdir(output_dir);
for name={'Step.f90','sspMod.f90','bellhopMod.f90'}
    copyfile(fullfile(accepted_overlay,name{1}),fullfile(output_dir,name{1}));
end
reader=normtext(fileread(fullfile(official_root,'misc','SourceReceiverPositions.f90')));
reader=once(reader,'  USE monotonicMod',"  USE, INTRINSIC :: ieee_arithmetic, ONLY: ieee_is_finite"+newline+"  USE monotonicMod");
reader=once(reader,'  TYPE ( Position ) :: Pos', ...
    "  REAL(KIND=8), ALLOCATABLE :: ReceiverRangeInput64(:) ! exact ENV input, meters"+newline+"  TYPE ( Position ) :: Pos");
reader=once(reader,'  SUBROUTINE ReadRcvrRanges', ...
    "  SUBROUTINE ReadRcvrRanges( ValidationExactInput )");
reader=once(reader,"    CALL ReadVector( Pos%NRr, Pos%Rr, 'Receiver ranges, Rr', 'km' )",join(string({ ...
    "    LOGICAL, OPTIONAL, INTENT(IN) :: ValidationExactInput" ...
    "    LOGICAL :: exactInput" ...
    "    INTEGER :: ix" ...
    "    REAL(KIND=8), ALLOCATABLE :: rangesKm64(:)" ...
    "    exactInput=.FALSE." ...
    "    IF(PRESENT(ValidationExactInput)) exactInput=ValidationExactInput" ...
    "    IF(ALLOCATED(ReceiverRangeInput64)) DEALLOCATE(ReceiverRangeInput64)" ...
    "    IF(exactInput) THEN" ...
    "       READ(ENVFile,*) Pos%NRr" ...
    "       IF(Pos%NRr<=0) CALL ERROUT('ReadRcvrRanges-R64','Invalid count')" ...
    "       ALLOCATE(rangesKm64(Pos%NRr),ReceiverRangeInput64(Pos%NRr))" ...
    "       READ(ENVFile,*) rangesKm64" ...
    "       IF(ANY(.NOT.ieee_is_finite(rangesKm64))) CALL ERROUT('ReadRcvrRanges-R64','Nonfinite input')" ...
    "       IF(ANY(rangesKm64(2:)<=rangesKm64(:Pos%NRr-1))) CALL ERROUT('ReadRcvrRanges-R64','Input must strictly increase; no sorting')" ...
    "       ReceiverRangeInput64=1000d0*rangesKm64" ...
    "       IF(ANY(.NOT.ieee_is_finite(ReceiverRangeInput64))) CALL ERROUT('ReadRcvrRanges-R64','Nonfinite meter input')" ...
    "       IF(ANY(ReceiverRangeInput64(2:)<=ReceiverRangeInput64(:Pos%NRr-1))) CALL ERROUT('ReadRcvrRanges-R64','Meter input must strictly increase')" ...
    "       IF(ALLOCATED(Pos%Rr)) DEALLOCATE(Pos%Rr)" ...
    "       ALLOCATE(Pos%Rr(MAX(3,Pos%NRr)))" ...
    "       Pos%Rr=0.0" ...
    "       Pos%Rr(1:Pos%NRr)=REAL(ReceiverRangeInput64,KIND=4) ! metadata only, once" ...
    "       WRITE(PRTFile,*) 'Validation R64 ENV input: REAL(KIND=8),1000d0; count=',Pos%NRr" ...
    "       WRITE(PRTFile,'(5ES25.16E3)') (ReceiverRangeInput64(ix),ix=1,MIN(Pos%NRr,Number_to_Echo))" ...
    "       DEALLOCATE(rangesKm64)" ...
    "    ELSE" ...
    "       CALL ReadVector( Pos%NRr, Pos%Rr, 'Receiver ranges, Rr', 'km' )" ...
    "    END IF"}),newline));
write(fullfile(output_dir,'SourceReceiverPositions.f90'),reader);
re=normtext(fileread(fullfile(official_root,'Bellhop','ReadEnvironmentBell.f90')));
re=once(re,'    INTEGER            :: NPts, NMedia, iostat', ...
    "    INTEGER            :: NPts, NMedia, iostat"+newline+"    LOGICAL :: ValidationExactRanges");
re=once(re,'    CALL ReadRcvrRanges', ...
    "    INQUIRE(FILE=TRIM(FileRoot)//'.r25d',EXIST=ValidationExactRanges)"+newline+ ...
    "    CALL ReadRcvrRanges(ValidationExactRanges)");
write(fullfile(output_dir,'ReadEnvironmentBell.f90'),re);
state=normtext(fileread(fullfile(accepted_overlay,'RotatedFieldState.f90')));
state=once(state,'  USE SourceReceiverPositions, ONLY: Pos', ...
    '  USE SourceReceiverPositions, ONLY: Pos, ReceiverRangeInput64');
state=once(state,'  REAL(KIND=8), ALLOCATABLE :: ReceiverRange64(:), ReceiverDepth64(:)',join(string({ ...
    '  REAL(KIND=8), ALLOCATABLE :: ReceiverRange64(:), ReceiverDepth64(:)' ...
    '  LOGICAL, ALLOCATABLE, PRIVATE :: EvaluationSeen(:,:), ScaleSeen(:)' ...
    '  INTEGER, PRIVATE :: EvaluationUnit, ScaleUnit' ...
    '  LOGICAL, PRIVATE :: ReceiverAuditOpen=.FALSE.'}),newline));
state=once(state,'    ReceiverRange64=REAL(Pos%Rr(1:Pos%NRr),KIND=8)',join(string({ ...
    '    IF(ALLOCATED(ReceiverRangeInput64)) THEN' ...
    '       ReceiverRange64=ReceiverRangeInput64' ...
    '    ELSE' ...
    '       ReceiverRange64=REAL(Pos%Rr(1:Pos%NRr),KIND=8) ! legacy no-sidecar only' ...
    '    END IF'}),newline));
state=once(state,'    IF(.NOT.exists) RETURN',join(string({ ...
    '    IF(.NOT.exists) RETURN' ...
    "    IF(.NOT.ALLOCATED(ReceiverRangeInput64)) CALL ERROUT('BELLHOP-R64','Exact path cannot use float32 fallback')"}),newline));
state=once(state,'    ExactCoordinatesEnabled=.TRUE.',join(string({ ...
    '    ExactCoordinatesEnabled=.TRUE.' ...
    "    IF(STORAGE_SIZE(ReceiverRange64(1))/=64) CALL ERROUT('BELLHOP-R64','Receiver precision is not64bit')" ...
    "    IF(ANY(ABS(ReceiverRangeInput64-ReceiverRange64)>2d0*SPACING(ReceiverRangeInput64))) &" ...
    "       CALL ERROUT('BELLHOP-R64','ENV64 and exact sidecar mismatch beyond unit-conversion rounding')" ...
    '    CALL OpenExactReceiverAudit(FileRoot)' }),newline));
extra=join(string({ ...
    '  SUBROUTINE OpenExactReceiverAudit(FileRoot)' ...
    '    CHARACTER(LEN=*), INTENT(IN) :: FileRoot' ...
    '    INTEGER :: u' ...
    '    IF(ALLOCATED(EvaluationSeen)) DEALLOCATE(EvaluationSeen,ScaleSeen)' ...
    '    ALLOCATE(EvaluationSeen(Pos%NRz,Pos%NRr),ScaleSeen(Pos%NRr))' ...
    '    EvaluationSeen=.FALSE.; ScaleSeen=.FALSE.' ...
    "    OPEN(NEWUNIT=u,FILE=TRIM(FileRoot)//'.rr64input',ACCESS='STREAM',FORM='UNFORMATTED',STATUS='REPLACE')" ...
    '    WRITE(u) Pos%NRr,Pos%NRz,KIND(ReceiverRangeInput64),KIND(ReceiverRange64)' ...
    '    WRITE(u) ReceiverRangeInput64,ReceiverRange64,ReceiverDepth64,Pos%Rr(1:Pos%NRr)' ...
    '    CLOSE(u)' ...
    "    OPEN(NEWUNIT=EvaluationUnit,FILE=TRIM(FileRoot)//'.rr64eval',ACCESS='STREAM',FORM='UNFORMATTED',STATUS='REPLACE')" ...
    '    WRITE(EvaluationUnit) Pos%NRr,Pos%NRz' ...
    "    OPEN(NEWUNIT=ScaleUnit,FILE=TRIM(FileRoot)//'.rr64scale',ACCESS='STREAM',FORM='UNFORMATTED',STATUS='REPLACE')" ...
    '    WRITE(ScaleUnit) Pos%NRr' ...
    '    ReceiverAuditOpen=.TRUE.' ...
    '  END SUBROUTINE OpenExactReceiverAudit' ...
    '  SUBROUTINE RecordExactReceiverEvaluation(ir,iz,actual)' ...
    '    INTEGER, INTENT(IN) :: ir,iz' ...
    '    REAL(KIND=8), INTENT(IN) :: actual(2)' ...
    '    IF(.NOT.ExactCoordinatesEnabled) RETURN' ...
    "    IF(TRANSFER(actual(1),0_8)/=TRANSFER(ReceiverRange64(ir),0_8).OR. &" ...
    '       TRANSFER(actual(2),0_8)/=TRANSFER(ReceiverDepth64(iz),0_8)) &' ...
    "         CALL ERROUT('BELLHOP-R64','Actual field coordinate lost exact bits')" ...
    '    IF(.NOT.EvaluationSeen(iz,ir)) THEN' ...
    '       WRITE(EvaluationUnit) ir,iz,actual' ...
    '       EvaluationSeen(iz,ir)=.TRUE.' ...
    '    END IF' ...
    '  END SUBROUTINE RecordExactReceiverEvaluation' ...
    '  SUBROUTINE RecordExactReceiverScale(ir,actual)' ...
    '    INTEGER, INTENT(IN) :: ir' ...
    '    REAL(KIND=8), INTENT(IN) :: actual' ...
    '    IF(.NOT.ExactCoordinatesEnabled) RETURN' ...
    "    IF(TRANSFER(actual,0_8)/=TRANSFER(ReceiverRange64(ir),0_8)) CALL ERROUT('BELLHOP-R64','Scale coordinate lost exact bits')" ...
    '    IF(.NOT.ScaleSeen(ir)) THEN' ...
    '       WRITE(ScaleUnit) ir,actual' ...
    '       ScaleSeen(ir)=.TRUE.' ...
    '    END IF' ...
    '  END SUBROUTINE RecordExactReceiverScale' ...
    '  SUBROUTINE CloseExactReceiverAudit()' ...
    '    IF(ReceiverAuditOpen) THEN' ...
    '       CLOSE(EvaluationUnit); CLOSE(ScaleUnit); ReceiverAuditOpen=.FALSE.' ...
    "       WRITE(6,*) 'R64 audit recorded field points=',COUNT(EvaluationSeen),' scale ranges=',COUNT(ScaleSeen)" ...
    '    END IF' ...
    '  END SUBROUTINE CloseExactReceiverAudit' ...
    'END MODULE RotatedFieldState'}),newline);
state=once(state,'END MODULE RotatedFieldState',extra);
write(fullfile(output_dir,'RotatedFieldState.f90'),state);
bh=normtext(fileread(fullfile(accepted_overlay,'bellhop.f90')));
bh=once(bh,'  CALL BellhopCore',"  CALL BellhopCore"+newline+"  CALL CloseExactReceiverAudit()");
bh=once(bh,'     DalphaOpt = SQRT( c / ( 6.0 * freq * Pos%Rr( Pos%NRr ) ) )',join(string({ ...
    '     IF(ExactCoordinatesEnabled) THEN' ...
    '        DalphaOpt=SQRT(c/(6d0*freq*ReceiverRange64(Pos%NRr)))' ...
    '     ELSE' ...
    '        DalphaOpt = SQRT( c / ( 6.0 * freq * Pos%Rr( Pos%NRr ) ) )' ...
    '     END IF'}),newline));
write(fullfile(output_dir,'bellhop.f90'),bh);
ip=normtext(fileread(fullfile(accepted_overlay,'influence.f90')));
a=strfind(ip,'  SUBROUTINE InfluenceGeoHatCart('); b=strfind(ip,'  END SUBROUTINE InfluenceGeoHatCart');
assert(isscalar(a)&&isscalar(b)); b=b+strlength('  END SUBROUTINE InfluenceGeoHatCart')-1; part=ip(a:b);
part=once(part,'                s         =', ...
    "                CALL RecordExactReceiverEvaluation(ir,iz,x_rcvr(:,iz))"+newline+"                s         =");
ip=[ip(1:a-1) part ip(b+1:end)];
ip=once(ip,'          IF ( r ( ir ) == 0 ) THEN',join(string({ ...
    '          IF(ExactCoordinatesEnabled) THEN' ...
    '             CALL RecordExactReceiverScale(ir,ReceiverRange64(ir))' ...
    '             factor=const/SQRT(ReceiverRange64(ir))' ...
    '          ELSE IF ( r ( ir ) == 0 ) THEN'}),newline));
ip=once(ip,'             IF(ExactCoordinatesEnabled) factor=const/SQRT(ReceiverRange64(ir))','');
write(fullfile(output_dir,'influence.f90'),ip);
build=normtext(fileread(fullfile(accepted_overlay,'build_rotated_multifield.ps1')));
anchor="Copy-Item -LiteralPath (Join-Path $supportDir 'Step.f90') -Destination (Join-Path $buildRoot 'Bellhop\Step.f90') -Force";
new=join(string({ ...
    "Copy-Item -LiteralPath (Join-Path $supportDir 'SourceReceiverPositions.f90') -Destination (Join-Path $buildRoot 'misc\SourceReceiverPositions.f90') -Force" ...
    "Copy-Item -LiteralPath (Join-Path $supportDir 'ReadEnvironmentBell.f90') -Destination (Join-Path $buildRoot 'Bellhop\ReadEnvironmentBell.f90') -Force" ...
    anchor}),newline);
build=once(build,anchor,new);
build=strrep(build,'bellhop_rotated_multifield_2020.exe','bellhop_rotated_receiver64_2020.exe');
write(fullfile(output_dir,'build_rotated_receiver64.ps1'),build);
files={'SourceReceiverPositions.f90','ReadEnvironmentBell.f90','RotatedFieldState.f90','bellhop.f90','influence.f90','Step.f90','sspMod.f90','bellhopMod.f90'};
versions=struct('path',{},'sha256',{});
for j=1:numel(files), path=fullfile(output_dir,files{j}); versions(j)=struct('path',path,'sha256',black_file_hash(path)); end
receipt=struct('status','SOURCE_PREPARED_NOT_EXECUTED','output_dir',output_dir,'source_versions',versions, ...
    'scope','REAL8 ENV input/1000d0; R64 exact field and scale paths; original strict gates/physics retained; runtime audit instrumentation', ...
    'unrun_checks',{{'compile','no-solver bitwise preflight','single authorized13th order101beams3columns','runtime coordinate and pressure audit'}});
write(fullfile(output_dir,'checkpoint.json'),jsonencode(receipt,PrettyPrint=true));
fprintf('R64 overlay prepared: %d source files; no solver launched\n',numel(files));
end
function t=normtext(t)
t=strrep(t,sprintf('\r\n'),newline);
end
function t=once(t,a,b)
assert(isscalar(strfind(t,char(a))),'Patch anchor drift.'); t=strrep(char(t),char(a),char(b));
end
function write(path,value)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); cleaner=onCleanup(@()fclose(fid)); fprintf(fid,'%s',value);
end