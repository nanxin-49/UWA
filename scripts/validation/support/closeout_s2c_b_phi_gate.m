function gate = closeout_s2c_b_phi_gate(run_dir)
%CLOSEOUT_S2C_B_PHI_GATE PHI-only amended shared budget, no physics.
arguments
    run_dir (1,:) char
end
assert(isfolder(run_dir) && contains(run_dir,'20261023_s2c_b_phi_plus90_01'));
a=jsondecode(fileread(fullfile(run_dir,'P2_budget_amendment_7506_601.json')));
assert(strcmp(a.authorized_case,'PHI_PLUS90') && a.explicit_user_authorization);
assert(strcmp(a.scope,'S2c-B PHI_PLUS90 only') && ~a.other_candidates_authorized);
assert(a.new_shared_core_cap_s==7506.601 && a.increment_s==306.601);
assert(a.charged_prior_s==2685.7140642 && a.S3A_reserve_s==3000);
assert(a.single_job_cap_s==900 && a.RAM_reserve_fraction==.3);
assert(abs(a.PHI_subbudget_s-(a.new_shared_core_cap_s-a.charged_prior_s-a.S3A_reserve_s))<1e-9);
assert(a.five_BIE_plan_s+a.other_physics_reserve_s+a.failure_reference_reserve_s<=a.PHI_subbudget_s);
root=fileparts(fileparts(fileparts(fileparts(run_dir))));
cfg=fullfile(root,'results','comparisons','two_dimensional_channel_closeout', ...
    '20261023_s2c_a_1642','protocol','PHI_PLUS90_configuration.json');
assert(strcmp(closeout_s2b_hash(cfg), ...
    '3038983c6b78e37a2acb9e570f992f258e33e9064dcce8e72110b9977d21d317'));
gate=struct('case_id','PHI_PLUS90','shared_cap_s',a.new_shared_core_cap_s, ...
    'charged_prior_seconds',a.charged_prior_s,'core_remaining_s', ...
    a.new_shared_core_cap_s-a.charged_prior_s,'subbudget_s',a.PHI_subbudget_s, ...
    'S3A_reserve_s',a.S3A_reserve_s,'other_physics_reserve_s',a.other_physics_reserve_s, ...
    'failure_contingency_s',a.failure_reference_reserve_s, ...
    'single_job_cap_s',a.single_job_cap_s, ...
    'budget_amendment_sha256',closeout_s2b_hash(fullfile(run_dir,'P2_budget_amendment_7506_601.json')), ...
    'configuration_sha256',closeout_s2b_hash(cfg));
end
