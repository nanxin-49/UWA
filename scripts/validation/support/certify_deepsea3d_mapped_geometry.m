function cert=certify_deepsea3d_mapped_geometry(cfg,b)
%CERTIFY_DEEPSEA3D_MAPPED_GEOMETRY Global Lipschitz bound on the physical map.
% C2 radial window has max|w'|=1.875/(support-plateau). Exact frozen Fourier
% coefficients supply an analytic gradient bound between validation samples.
p=cfg.profile;R=p.support_m;h=.125;n=ceil(2*R/h);h=2*R/n;
x=linspace(-R,R,n+1);[xx,yy]=meshgrid(x,x);eta=deepsea3d_surface(xx,yy,p);
A=abs(p.amplitudes_m(:));slope_bound=sum(A.*vecnorm(p.wavevectors_radpm,2,2)) ...
    +1.875/(p.support_m-p.plateau_m)*sum(A);
upper=max(eta(:))+h/sqrt(2)*slope_bound;
% Outside this square the compact perturbation vanishes identically.
upper=max(upper,p.height_m);
cert=struct('sampling_spacing_m',h,'sample_max_height_m',max(eta(:)), ...
    'analytic_gradient_bound',slope_bound,'continuous_height_upper_m',upper, ...
    'continuous_map_jacobian_lower',1-upper/b, ...
    'map_positive',upper<b,'source_outside_strip',cfg.tx_m(3)>b, ...
    'receiver_outside_strip',cfg.rx_m(3)>b,'surface_lower_bound_m',p.height_m-sum(A), ...
    'background_image_outside_water',-cfg.tx_m(3)<p.height_m-sum(A), ...
    'scope','continuous physical C2/Fourier map; not a PDE error bound');
assert(cert.map_positive && cert.source_outside_strip && cert.receiver_outside_strip && cert.background_image_outside_water);
end
