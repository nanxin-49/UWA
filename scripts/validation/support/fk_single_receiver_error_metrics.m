function m = fk_single_receiver_error_metrics(ref,a,scale)
%FK_SINGLE_RECEIVER_ERROR_METRICS Explicit finite/undefined near-null semantics.
if nargin<3, scale=abs(ref); end
assert(isscalar(ref) && isscalar(a) && all(isfinite([real(ref) imag(ref) real(a) imag(a)])), ...
    'fk_validation:NonfinitePressure','Complex pressure must be finite.');
assert(isscalar(scale) && isfinite(scale) && scale>=0, ...
    'fk_validation:InvalidScale','Diagnostic scale must be finite and nonnegative.');
den=max(abs(ref),1e-14); phase_defined=abs(ref)>0 && abs(a)>0;
phase=NaN; if phase_defined, phase=angle(a)-angle(ref); phase=atan2(sin(phase),cos(phase)); end
raw=NaN; if abs(ref)>0, raw=abs(a-ref)/abs(ref); end
m=struct('absolute_error',abs(a-ref),'relative_error',abs(a-ref)/den, ...
    'magnitude_absolute_error',abs(abs(a)-abs(ref)), ...
    'magnitude_relative_error',abs(abs(a)-abs(ref))/den, ...
    'phase_error_rad',phase,'phase_defined',phase_defined, ...
    'raw_relative_error',raw,'relative_defined',abs(ref)>0, ...
    'near_zero',abs(ref)<=max(1e-14,1e-3*scale), ...
    'reference_magnitude',abs(ref),'diagnostic_scale',scale);
values=[m.absolute_error m.relative_error m.magnitude_absolute_error m.magnitude_relative_error];
if phase_defined, values(end+1)=phase; end
if m.relative_defined, values(end+1)=raw; end
m.finite_metrics=all(isfinite(values));
assert(m.finite_metrics,'fk_validation:NonfiniteMetrics','Defined error metrics must be finite.');
end
