function audit = audit_two_dimensional_closeout_s3a_inputs(root,run_dir)
%AUDIT_TWO_DIMENSIONAL_CLOSEOUT_S3A_INPUTS Read-only seed/source/geometry audit.
arguments
    root (1,:) char
    run_dir (1,:) char
end
pilot=fullfile(root,'results','validation','spectral_fast_kirchhoff_pm_pilot');
s=load(fullfile(root,'results','comparisons','two_dimensional_channel_closeout', ...
    '20261023_s2c_a_1642','protocol','frozen_source.mat'),'src');
f=load(fullfile(root,'results','comparisons','two_dimensional_channel_closeout', ...
    '20261023_s2b_1305','formal_reference_v2','reference_data.mat'),'x','z','ix9');
seeds=[260001 260002 260003]; rows=cell(3,1);
parent=[];
for i=1:3
    seed=seeds(i);
    p=readtable(fullfile(pilot,sprintf('seed_%d_coefficients.csv',seed)));
    d=load(fullfile(pilot,sprintf('seed_%d_fields.mat',seed)),'d'); d=d.d;
    [eta,sl,sec,raw]=closeout_s3a_pm_surface(p,d.x_m);
    if isempty(parent), parent=p.Sk_m3; end
    rows{i}=struct('seed',seed,'n_modes',height(p), ...
        'kmax_rad_per_m',max(p.k_rad_per_m), ...
        'same_parent_max_abs',max(abs(p.Sk_m3-parent)), ...
        'source_coeff_max_abs',max(abs(d.cfg.spectral_source.coeff(:)-s.src.coeff(:))), ...
        'saved_embedded_height_max_abs',max(abs(d.eta_m(:)-eta(:))), ...
        'saved_slope_max_abs',max(abs(d.slope(:)-sl(:))), ...
        'saved_curvature_max_abs',max(abs(d.second_derivative(:)-sec(:))), ...
        'embedded_max_height_m',max(abs(eta)), ...
        'embedded_max_slope',max(abs(sl)), ...
        'embedded_center_height_m',closeout_s3a_pm_surface(p,0), ...
        'raw_end_height_m',raw(end), ...
        'flat_external',all(eta(abs(d.x_m)>=50)==0), ...
        'old_fullfk_receiver_count',numel(d.reference_field), ...
        'old_fullfk_z_all_3m',all(d.refcfg.receiver_z_m(:)==3), ...
        'old_fullfk_extent_m',max(abs(d.refcfg.surface_x_m)), ...
        'old_fullfk_status','finite L60 two-term line; not S2b analytic exterior', ...
        'old_PE_status','no qualified native nine-point physical-height field', ...
        'old_BIE_status','none at P11-P33 or current five-level hierarchy');
    assert(rows{i}.n_modes==12 && rows{i}.same_parent_max_abs==0);
    assert(rows{i}.source_coeff_max_abs==0 && rows{i}.flat_external);
    assert(rows{i}.saved_embedded_height_max_abs<1e-12);
    assert(rows{i}.saved_slope_max_abs<1e-12);
    assert(rows{i}.saved_curvature_max_abs<1e-12);
end
assert(all(abs(f.x(f.ix9))<=.2) && isequal(unique(f.z(f.ix9)),[2.875;3;3.125]));
audit=struct('status','INPUT_AUDIT_PASS_REFERENCE_GAPS_OPEN', ...
    'same_source','frozen discrete Gaussian N984', ...
    'frequency_hz',4000,'C2_plateau_m',42,'C2_flat_from_m',50, ...
    'nine_point_indices',f.ix9(:).','nine_point_x_m',f.x(f.ix9).', ...
    'nine_point_z_m',f.z(f.ix9).','seeds',[rows{:}]);
path=fullfile(run_dir,'audit','input_audit.json');
fid=fopen(path,'w'); assert(fid>0); c=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(audit,PrettyPrint=true));
end
