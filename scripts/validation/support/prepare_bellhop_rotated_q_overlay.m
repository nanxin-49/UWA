function output = prepare_bellhop_rotated_q_overlay(output_dir)
%PREPARE_BELLHOP_ROTATED_Q_OVERLAY Freeze a minimal direct-Q derivative.
% Generates source/build inputs only. It does not compile or run anything.
% Reflected-Q mode is deliberately rejected until the medium transform audit.
arguments
    output_dir (1,:) char
end
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
% This file lives in scripts/validation/support: four fileparts reach root.
base=fullfile(root,'scripts','validation','support','bellhop_internal_pm_wall_poc');
assert(~isfolder(output_dir),'Use a new overlay staging directory.');
bh=fullfile(base,'bellhop.f90'); st=fullfile(base,'Step.f90');
assert(strcmp(black_file_hash(bh),'986010216f03d1ef2156730f076fcec27ad8a39cc1a5eb44096726ee33e0e251'));
assert(strcmp(black_file_hash(st),'1f54c01f35ac9682c80d374abc7cfc83ec9ebf72bd4928feded5e19323c757de'));
text=fileread(bh); text=strrep(text,sprintf('\r\n'),newline);
text=replace_once(text,'( ModeCode /= 0 .AND. ModeCode /= 1 )','( ModeCode < 0 .OR. ModeCode > 2 )');
text=replace_once(text, ...
    "  IF ( Beam%RunType( 1 : 1 ) /= 'C' .OR. Beam%Type( 1 : 1 ) /= 'G' ) &", ...
    "  IF ( IWallMode /= 2 .AND. ( Beam%RunType( 1 : 1 ) /= 'C' .OR. Beam%Type( 1 : 1 ) /= 'G' ) ) &");
old=strjoin(["  IF ( SSP%Type /= 'C' .OR. MAXVAL( ABS( REAL( SSP%c( 1 : SSP%NPts ) ) - 1500.0d0 ) ) > 1.0d-10 .OR. &" ...
    "       MAXVAL( ABS( AIMAG( SSP%c( 1 : SSP%NPts ) ) ) ) > 1.0d-12 ) &" ...
    "       CALL ERROUT( 'BELLHOP-IWALL', 'POC requires uniform lossless c = 1500 m/s' )"],newline);
new=strjoin(["  IF ( IWallMode == 2 ) THEN" ...
    "     IF ( SSP%Type /= 'Q' ) CALL ERROUT( 'BELLHOP-ROTQ', 'Direct rotated mode requires Q SSP' )" ...
    "     IF ( MAXVAL( ABS( AIMAG( SSP%c(1:SSP%NPts) ) ) ) > 1d-12 ) &" ...
    "          CALL ERROUT( 'BELLHOP-ROTQ', 'Direct pilot requires lossless water' )" ...
    "     IF ( MAXVAL( ABS( SSP%cMat(2:SSP%NPts,:) - SPREAD(SSP%cMat(1,:),1,SSP%NPts-1) ) ) > 1d-10 ) &" ...
    "          CALL ERROUT( 'BELLHOP-ROTQ', 'Direct pilot requires c(r) independent of transverse depth' )" ...
    "  ELSE" ...
    old "  END IF"],newline);
text=replace_once(text,old,new);
text=replace_once(text,"  IF ( IWallMode == 0 ) THEN"+newline+"     IF ( .NOT. WallDidReflect )", ...
    "  ! Direct Q mode must never be confused with an unreflected wall failure."+newline+ ...
    "  IF ( IWallMode == 2 ) RETURN"+newline+newline+ ...
    "  IF ( IWallMode == 0 ) THEN"+newline+"     IF ( .NOT. WallDidReflect )");
mkdir(output_dir);
write_text(fullfile(output_dir,'bellhop.f90'),text);
copyfile(st,fullfile(output_dir,'Step.f90'));
% Reuse the existing reviewed build order, with no destructive rebuild and
% without fast-math (NaN/Inf checks and coherent phase must remain meaningful).
build=fileread(fullfile(base,'build_bellhop_internal_pm_wall_poc.ps1'));
build=strrep(build,sprintf('\r\n'),newline);
build=replace_once(build,"    [string]$OutputDir = ''", ...
    "    [string]$OutputDir = '',"+newline+"    [Parameter(Mandatory=$true)][string]$ProjectRoot");
build=replace_once(build,"$projectRoot = [System.IO.Path]::GetFullPath((Join-Path $supportDir '..\..\..\..'))", ...
    "$projectRoot = [System.IO.Path]::GetFullPath($ProjectRoot)");
build=replace_once(build,"'results\validation\bellhop_internal_pm_wall_poc'", ...
    "'results\validation\bellhop_rotated_fig12b\build_direct_q'");
start=strfind(build,'if (Test-Path -LiteralPath $buildRoot) {');
stop=strfind(build,'New-Item -ItemType Directory -Path $buildRoot, $binDir -Force | Out-Null');
assert(isscalar(start) && isscalar(stop));
build=[build(1:start-1),sprintf("if (Test-Path -LiteralPath $buildRoot) { throw 'Use a new build output; no cleanup or overwrite is allowed.' }\n"),build(stop:end)];
build=strrep(build,"'-ffast-math',",'');
build=strrep(build,'bellhop_iwall_pm_2020.exe','bellhop_rotated_direct_q_2020.exe');
build=strrep(build,'Bellhop 2020 validation-only fixed-PM internal wall and local covariance overlay', ...
    'Bellhop 2020 validation-only direct rotated Q; reflected Q remains disabled');
write_text(fullfile(output_dir,'build_rotated_direct_q.ps1'),build);
output=struct('status','SOURCE_PREPARED_NOT_COMPILED','output_dir',output_dir, ...
    'base_bellhop_sha256',black_file_hash(bh),'base_step_sha256',black_file_hash(st), ...
    'overlay_bellhop_sha256',black_file_hash(fullfile(output_dir,'bellhop.f90')), ...
    'overlay_step_sha256',black_file_hash(fullfile(output_dir,'Step.f90')), ...
    'generator_sha256',black_file_hash(mfilename('fullpath')+".m"), ...
    'mode2','direct Q only; use .iwcov mode=2, R0=0, receiver=0, seed=0, nprofile=0', ...
    'unrun_checks',{{'Fortran compilation','overlay/official numerical comparison','reflected Q mapping'}});
write_text(fullfile(output_dir,'checkpoint.json'),jsonencode(output,PrettyPrint=true));
disp(jsonencode(output));
end
function text=replace_once(text,old,new)
assert(isscalar(strfind(text,char(old))),'Patch anchor drift; stop instead of modifying unknown code.');
text=strrep(char(text),char(old),char(new));
end
function write_text(path,text)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); closer=onCleanup(@()fclose(fid));
fprintf(fid,'%s',text);
end