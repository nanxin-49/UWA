function output = prepare_bellhop_rotated_field_overlay(wall_overlay,official_root,output_dir)
%PREPARE_BELLHOP_ROTATED_FIELD_OVERLAY Validation-only 2.5D transport/coordinates.
% Source derivation: A_3D/A_native=sqrt(cs*r/(abs(cos(alpha))*integral(c ds))).
% This is geometrical transport, not an amplitude fit or wave-physics upgrade.
arguments
    wall_overlay (1,:) char
    official_root (1,:) char
    output_dir (1,:) char
end
assert(~isfolder(output_dir)); mkdir(output_dir);
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
state=fullfile(root,'scripts','validation','support','bellhop_rotated_field_poc','RotatedFieldState.f90');
copyfile(state,fullfile(output_dir,'RotatedFieldState.f90'));
bh=fullfile(wall_overlay,'bellhop.f90');
assert(strcmp(black_file_hash(bh),'83a27e41642accbb33ab1db2b2ea1e0ad475d4257d8c8e5116a5819c264698b7'));
text=normtext(fileread(bh));
text=once(text,'  USE FatalError','  USE FatalError'+string(newline)+'  USE RotatedFieldState');
text=once(text,'ModeCode > 3','ModeCode > 4');
text=once(text,'IWallMode /= 2 .AND. IWallMode /= 3 .AND.', ...
    'IWallMode /= 2 .AND. IWallMode /= 3 .AND. IWallMode /= 4 .AND.');
text=once(text,'  IF ( IWallMode == 2 .OR. IWallMode == 3 ) THEN', ...
    '  IF ( IWallMode == 2 .OR. IWallMode == 3 .OR. IWallMode == 4 ) THEN');
text=once(text,'     IF ( MAXVAL( ABS( SSP%cMat(2:SSP%NPts,:) - SPREAD(SSP%cMat(1,:),1,SSP%NPts-1) ) ) > 1d-10 ) &', ...
    '     IF ( IWallMode /= 4 .AND. MAXVAL( ABS( SSP%cMat(2:SSP%NPts,:) - SPREAD(SSP%cMat(1,:),1,SSP%NPts-1) ) ) > 1d-10 ) &');
text=once(text,'  CALL ReadInternalPMWall( FileRoot )', ...
    "  CALL ReadInternalPMWall( FileRoot )"+newline+"  CALL ConfigureRotatedField( FileRoot )");
% Guards use actual evaluation coordinates, not the float32 metadata.
first=strfind(text,'  IF ( ( IWallMode == 1 .OR. IWallMode == 3 ) ) THEN');
% This condition also occurs in the reader. Locate only the receiver guard.
anchor='     IF ( .NOT. ANY( ABS( Pos%Rr( 1 : Pos%NRr ) - IWallReceiverRange ) <= 1.0d-3 ) .OR. &';
pos=strfind(text,anchor); assert(isscalar(pos));
endpos=strfind(text(pos:end),"          CALL ERROUT( 'BELLHOP-IWALL', 'Internal-wall POC requires a post-wall receiver range' )");
assert(isscalar(endpos)); stop=pos+endpos-2;
part=text(pos:stop); part=strrep(part,'Pos%Rr','ReceiverRange64');
text=[text(1:pos-1),part,text(stop+1:end)];
text=once(text,'  RotQSourceC = c', ...
    "  RotQSourceC = c"+newline+"  ray2D(1)%out_of_plane_integral = 0d0");
text=once(text,'  ray2D( is1 )%tau = ray2D( is )%tau', ...
    "  ray2D( is1 )%tau = ray2D( is )%tau"+newline+ ...
    "  ray2D( is1 )%out_of_plane_integral = ray2D( is )%out_of_plane_integral");
text=once(text,'  CALL BellhopCore',join([ ...
    "  OPEN(UNIT=97,FILE=TRIM(FileRoot)//'.r25diag',STATUS='REPLACE',ACTION='WRITE')" ...
    "  WRITE(97,'(A)') '# alpha_deg end_r_m end_q_m tau_real_s tau_imag_s integral_cds source_c_mps end_unit_error top_bounces bottom_bounces'" ...
    "  CALL BellhopCore" ...
    "  CLOSE(97)"],newline));
anchor='  IF ( IWallMode == 2 ) RETURN';
rows=join([ ...
    "  WRITE(97,'(*(ES25.16E3,1X))') RadDeg*alpha, ray2D(Beam%Nsteps)%x, &" ...
    "       REAL(ray2D(Beam%Nsteps)%tau,KIND=8), AIMAG(ray2D(Beam%Nsteps)%tau), &" ...
    "       ray2D(Beam%Nsteps)%out_of_plane_integral, RotQSourceC, &" ...
    "       ABS(NORM2(ray2D(Beam%Nsteps)%c*ray2D(Beam%Nsteps)%t)-1d0), &" ...
    "       REAL(ray2D(Beam%Nsteps)%NumTopBnc,KIND=8),REAL(ray2D(Beam%Nsteps)%NumBotBnc,KIND=8)" ...
    "  IF ( IWallMode == 2 .OR. IWallMode == 4 ) RETURN"],newline);
text=once(text,anchor,rows);
% Point transport uses the sound speed at the same interpolated ray state as
% q and tau. Native endpoint-c evaluation is retained when the feature is off.
text=once(text,'  CALL BellhopCore',join([ ...
    "  OPEN(UNIT=96,FILE=TRIM(FileRoot)//'.r25sample',STATUS='REPLACE',ACTION='WRITE')" ...
    "  WRITE(96,'(A)') '# alpha_deg receiver_r_m receiver_q_m fraction c_left_mps c_right_mps q_in integral_cds source_c_mps point_factor c_interp_mps'" ...
    "  CALL BellhopCore" ...
    "  CLOSE(96)"],newline));
write(fullfile(output_dir,'bellhop.f90'),text);

modfile=fullfile(official_root,'Bellhop','bellhopMod.f90');
assert(strcmp(black_file_hash(modfile),'7207eb1b1e50bfca1375bfe2ef51c834f84aefb56175e282d6ac4372c195d916'));
module=normtext(fileread(modfile));
module=once(module,'     REAL   (KIND=8 ) :: x( 2 ), t( 2 ), p( 2 ), q( 2 ), c, Amp, Phase', ...
    '     REAL   (KIND=8 ) :: x( 2 ), t( 2 ), p( 2 ), q( 2 ), c, Amp, Phase, out_of_plane_integral');
write(fullfile(output_dir,'bellhopMod.f90'),module);
step=normtext(fileread(fullfile(wall_overlay,'Step.f90')));
step=once(step,'    ray1%q = ray0%q + halfh * c0        * ray0%p', ...
    "    ray1%q = ray0%q + halfh * c0        * ray0%p"+newline+ ...
    "    ray1%out_of_plane_integral = ray0%out_of_plane_integral + halfh*c0");
step=once(step,'    ray2%q   = ray0%q   + hw0 * c0        * ray0%p  + hw1 * c1        * ray1%p', ...
    "    ray2%q   = ray0%q   + hw0 * c0        * ray0%p  + hw1 * c1        * ray1%p"+newline+ ...
    "    ray2%out_of_plane_integral = ray0%out_of_plane_integral + hw0*c0 + hw1*c1");
write(fullfile(output_dir,'Step.f90'),step);

sspfile=fullfile(official_root,'Bellhop','sspMod.f90');
assert(strcmp(black_file_hash(sspfile),'0614336652fa5c199916e7075a15148fa1118749830af11331a7720c19d73a8b'));
ssp=normtext(fileread(sspfile));
ssp=once(ssp,'  SAVE',"  SAVE"+newline+"  LOGICAL :: FastQSearch = .FALSE.");
first=strfind(ssp,'  SUBROUTINE Quad('); last=strfind(ssp,'  END SUBROUTINE Quad');
assert(isscalar(first) && isscalar(last)); last=last+strlength('  END SUBROUTINE Quad')-1;
part=ssp(first:last);
part=once(part,'    INTEGER                           :: AllocateStatus, iSegT, iz2', ...
    '    INTEGER                           :: AllocateStatus, iSegT, iz2, lo, hi, mid');
old=join([ ...
    "          DO iSegT = 2, SSP%Nr   ! Search for bracketting segment ranges" ...
    "             IF ( x( 1 ) < SSP%Seg%r( iSegT ) ) THEN" ...
    "                iSegr = iSegT - 1" ...
    "                EXIT" ...
    "             END IF" ...
    "          END DO"],newline);
new=join([ ...
    "          IF (FastQSearch) THEN" ...
    "             lo=1; hi=SSP%Nr-1" ...
    "             DO WHILE (lo<=hi)" ...
    "                mid=(lo+hi)/2" ...
    "                IF (x(1)<SSP%Seg%r(mid)) THEN" ...
    "                   hi=mid-1" ...
    "                ELSE IF (x(1)>=SSP%Seg%r(mid+1).AND.mid<SSP%Nr-1) THEN" ...
    "                   lo=mid+1" ...
    "                ELSE" ...
    "                   iSegr=mid; EXIT" ...
    "                END IF" ...
    "             END DO" ...
    "          ELSE" old "          END IF"],newline);
part=once(part,old,new); ssp=[ssp(1:first-1),part,ssp(last+1:end)];
write(fullfile(output_dir,'sspMod.f90'),ssp);

ip=normtext(fileread(fullfile(wall_overlay,'influence.f90')));
ip=once(ip,'  USE Step, ONLY: RotQEnabled, RotQSourceC', ...
    "  USE Step, ONLY: RotQEnabled, RotQSourceC"+newline+"  USE RotatedFieldState");
first=strfind(ip,'  SUBROUTINE InfluenceGeoHatCart('); last=strfind(ip,'  END SUBROUTINE InfluenceGeoHatCart');
assert(isscalar(first) && isscalar(last)); last=last+strlength('  END SUBROUTINE InfluenceGeoHatCart')-1;
part=ip(first:last);
part=once(part,'    COMPLEX (KIND=8) :: dtauds', ...
    "    COMPLEX (KIND=8) :: dtauds"+newline+"    REAL(KIND=8) :: integral_cds");
part=strrep(part,'Pos%Rr','ReceiverRange64'); part=strrep(part,'Pos%Rz','ReceiverDepth64');
anchor='                   Amp      = const * W';
part=once(part,anchor,join([ ...
    anchor ...
    "                   IF (Point3DEnabled) THEN" ...
    "                      integral_cds=ray2D(iS-1)%out_of_plane_integral + s * &" ...
    "                           (ray2D(iS)%out_of_plane_integral-ray2D(iS-1)%out_of_plane_integral)" ...
    "                      IF(integral_cds<=0d0.OR.ABS(COS(alpha))<1d-12) &" ...
    "                           CALL ERROUT('BELLHOP-R25D','Invalid out-of-plane transport; select another chart')" ...
    "                      Amp=Amp*SQRT(RotQSourceC*ReceiverRange64(ir)/(ABS(COS(alpha))*integral_cds))" ...
    "                   END IF"],newline));
part=once(part,'    REAL(KIND=8) :: integral_cds','    REAL(KIND=8) :: integral_cds, c_interp, point_factor');
part=once(part, ...
    '                      Amp=Amp*SQRT(RotQSourceC*ReceiverRange64(ir)/(ABS(COS(alpha))*integral_cds))',join([ ...
    "                      c_interp=ray2D(iS-1)%c+s*(ray2D(iS)%c-ray2D(iS-1)%c)" ...
    "                      IF(c_interp<=0d0) CALL ERROUT('BELLHOP-R25D','Invalid interpolated ray sound speed')" ...
    "                      point_factor=SQRT(RotQSourceC*ReceiverRange64(ir)/(ABS(COS(alpha))*integral_cds))" ...
    "                      Amp=Amp*point_factor*SQRT(c_interp/ray2D(iS)%c)" ...
    "                      IF(ABS(alpha)<1d-14.AND.ABS(ReceiverDepth64(iz)-Pos%Sz(1))<1d-10) THEN" ...
    "                         WRITE(96,'(*(ES25.16E3,1X))') RadDeg*alpha,ReceiverRange64(ir),ReceiverDepth64(iz), &" ...
    "                              s,ray2D(iS-1)%c,ray2D(iS)%c,q,integral_cds,RotQSourceC,point_factor,c_interp" ...
    "                      END IF"],newline));
ip=[ip(1:first-1),part,ip(last+1:end)];
ip=once(ip,'             factor = const / SQRT( ABS( r( ir ) ) )', ...
    "             factor = const / SQRT( ABS( r( ir ) ) )"+newline+ ...
    "             IF(ExactCoordinatesEnabled) factor=const/SQRT(ReceiverRange64(ir))");
write(fullfile(output_dir,'influence.f90'),ip);

build=normtext(fileread(fullfile(wall_overlay,'build_rotated_reflected_q.ps1')));
anchor="Copy-Item -LiteralPath (Join-Path $supportDir 'influence.f90') -Destination (Join-Path $buildRoot 'Bellhop\influence.f90') -Force";
extra=anchor;
for file={'bellhopMod.f90','sspMod.f90','RotatedFieldState.f90'}
    extra=extra+newline+"Copy-Item -LiteralPath (Join-Path $supportDir '"+file{1}+"') -Destination (Join-Path $buildRoot 'Bellhop\"+file{1}+"') -Force";
end
build=once(build,anchor,extra);
build=once(build,"'ArrMod.f90','bdryMod.f90','sspMod.f90',", ...
    "'ArrMod.f90','bdryMod.f90','sspMod.f90','RotatedFieldState.f90',");
build=once(build,"'bellhopMod.o','sspMod.o','ReflectMod.o'", ...
    "'bellhopMod.o','sspMod.o','RotatedFieldState.o','ReflectMod.o'");
build=strrep(build,'bellhop_rotated_reflected_q_2020.exe','bellhop_rotated_field_2020.exe');
write(fullfile(output_dir,'build_rotated_field.ps1'),build);
files={'bellhop.f90','bellhopMod.f90','Step.f90','sspMod.f90','influence.f90','RotatedFieldState.f90'};
hashes=struct('path',{},'sha256',{});
for j=1:numel(files)
    path=fullfile(output_dir,files{j}); hashes(j)=struct('path',path,'sha256',black_file_hash(path));
end
output=struct('status','SOURCE_PREPARED_NOT_COMPILED','output_dir',output_dir,'source_sha256',hashes, ...
    'scope','2.5D geometric point transport, exact receiver coordinates, equivalent Q search; still one wall only', ...
    'unrun_checks',{{'compile','disabled regression','fast-search equivalence','uniform/rotated Munk 3D amplitude','exact-coordinate quantization test','source-plane secondary charts'}});
write(fullfile(output_dir,'checkpoint.json'),jsonencode(output,PrettyPrint=true));
disp(jsonencode(output));
end
function s=normtext(s)
s=strrep(s,sprintf('\r\n'),newline);
end
function s=once(s,old,new)
assert(isscalar(strfind(s,char(old))),'Patch anchor drift.');
s=strrep(char(s),char(old),char(new));
end
function write(path,value)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); c=onCleanup(@()fclose(fid));
fprintf(fid,'%s',value);
end