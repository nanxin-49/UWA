function deepsea_readiness_guard(meta,purpose)
%DEEPSEA_READINESS_GUARD Fail closed for readiness-only research artifacts.
arguments
    meta (1,1) struct
    purpose (1,1) string
end
assert(isfield(meta,'physics_tier') && isfield(meta,'scope') ...
    && isfield(meta,'G1_target_PM') && isfield(meta,'WP2_formal'), ...
    'Readiness:Metadata','Missing evidence contract.');
assert(meta.G1_target_PM=="OPEN" && ~meta.WP2_formal, ...
    'Readiness:Gate','Readiness artifacts cannot release PM gates.');
assert(purpose=="readiness" && any(string(meta.physics_tier)== ...
    ["analytic_control","compact_dual_conditional"]), ...
    'Readiness:Provenance','No readiness/PM diagnostic data in inference.');
if string(meta.physics_tier)=="compact_dual_conditional"
    assert(isfield(meta,'certified_frequencies_hz') && isfield(meta,'frequency_hz') ...
        && all(ismember(meta.frequency_hz,meta.certified_frequencies_hz)), ...
        'Readiness:FrequencyScope','Dual certification is discrete-frequency only.');
end
end
