function add_bellhop_rotated_performance_clocks(source_dir,output_dir)
%ADD_BELLHOP_ROTATED_PERFORMANCE_CLOCKS Sample1/1024 hot calls plus ray timers.
assert(~isfolder(output_dir)); mkdir(output_dir); files=dir(fullfile(source_dir,'*.f90'));
for k=1:numel(files), copyfile(fullfile(files(k).folder,files(k).name),fullfile(output_dir,files(k).name)); end
step=normtext(fileread(fullfile(output_dir,'Step.f90')));
step=strrep(step,'  INTEGER :: PerfWallUnit',join(["  INTEGER :: PerfWallUnit"; ...
"  INTEGER(KIND=8) :: PerfSampleTicks(4)=0,PerfSampleN(4)=0,PerfCoarseTicks(3)=0"; ...
"  INTEGER(KIND=8) :: PerfCoarse0,PerfCoarse1,PerfRate,PerfClockOverhead=0,PerfTmp0,PerfTmp1"],newline));
step=wrap(step,'GetWallGeometry','    PerfGeometryCalls=PerfGeometryCalls+1','PerfGeometryCalls',4);
step=wrap(step,'WallCrossingStep','    PerfCrossCalls=PerfCrossCalls+1','PerfCrossCalls',3);
step=wrap(step,'Step2D','    PerfStepCalls=PerfStepCalls+1','PerfStepCalls',1);
step=wrap(step,'ReduceStep2D','    PerfReduceCalls=PerfReduceCalls+1','PerfReduceCalls',2);
write(fullfile(output_dir,'Step.f90'),step);
ssp=normtext(fileread(fullfile(output_dir,'sspMod.f90')));
ssp=strrep(ssp,'  SAVE',"  SAVE"+newline+"  INTEGER(KIND=8)::PerfSSPCalls=0,PerfSSPTicks=0,PerfSSPN=0");
ssp=char(ssp); a=strfind(ssp,'  SUBROUTINE EvaluateSSP('); b=strfind(ssp,'  END SUBROUTINE EvaluateSSP'); b=b(find(b>a,1)); part=ssp(a:b-1);
part=strrep(part,'    SELECT CASE ( SSP%Type )',join(["    INTEGER(KIND=8)::clock0,clock1"; ...
"    LOGICAL::sample";"    PerfSSPCalls=PerfSSPCalls+1"; ...
"    sample=IAND(PerfSSPCalls,1023_8)==0";"    IF(sample) CALL SYSTEM_CLOCK(clock0)";"    SELECT CASE ( SSP%Type )"],newline));
part=string(part)+newline+join(["    IF(sample) THEN";"       CALL SYSTEM_CLOCK(clock1)"; ...
"       PerfSSPTicks=PerfSSPTicks+clock1-clock0; PerfSSPN=PerfSSPN+1";"    END IF"],newline)+newline;
ssp=[ssp(1:a-1) char(part) ssp(b:end)]; write(fullfile(output_dir,'sspMod.f90'),ssp);
main=normtext(fileread(fullfile(output_dir,'bellhop.f90')));
main=strrep(main,'  USE Step, ONLY: PerfWallUnit,', ...
    "  USE Step, ONLY: PerfSampleTicks,PerfSampleN,PerfCoarseTicks,PerfCoarse0,PerfCoarse1,PerfRate,PerfClockOverhead,PerfTmp0,PerfTmp1, &"+newline+"       PerfWallUnit,");
main=strrep(main,'  CALL BellhopCore',join(["  CALL SYSTEM_CLOCK(COUNT_RATE=PerfRate)"; ...
"  DO jj=1,10000";"     CALL SYSTEM_CLOCK(PerfTmp0); CALL SYSTEM_CLOCK(PerfTmp1)"; ...
"     PerfClockOverhead=PerfClockOverhead+PerfTmp1-PerfTmp0";"  END DO";"  CALL BellhopCore"],newline));
main=strrep(main,'  CLOSE(93)',join(["  CLOSE(93)"; ...
"  OPEN(UNIT=93,FILE=TRIM(FileRoot)//'.perftime',STATUS='NEW')"; ...
"  WRITE(93,*) PerfRate,PerfClockOverhead,10000"; ...
"  WRITE(93,*) PerfSampleTicks";"  WRITE(93,*) PerfSampleN"; ...
"  WRITE(93,*) PerfSSPCalls,PerfSSPTicks,PerfSSPN";"  WRITE(93,*) PerfCoarseTicks";"  CLOSE(93)"],newline));
main=strrep(main,'           CALL TraceRay2D( xs, Angles%alpha( ialpha ), Amp0 )   ! Trace a ray', ...
join(["           CALL SYSTEM_CLOCK(PerfCoarse0)";"           CALL TraceRay2D( xs, Angles%alpha( ialpha ), Amp0 )"; ...
"           CALL SYSTEM_CLOCK(PerfCoarse1)";"           PerfCoarseTicks(1)=PerfCoarseTicks(1)+PerfCoarse1-PerfCoarse0"],newline));
main=strrep(main,'                 CALL InfluenceGeoHatCart(      U, Angles%alpha( ialpha ), Angles%Dalpha )', ...
join(["                 CALL SYSTEM_CLOCK(PerfCoarse0)";"                 CALL InfluenceGeoHatCart(U,Angles%alpha(ialpha),Angles%Dalpha)"; ...
"                 CALL SYSTEM_CLOCK(PerfCoarse1)";"                 PerfCoarseTicks(2)=PerfCoarseTicks(2)+PerfCoarse1-PerfCoarse0"],newline));
anchor='        CALL ScalePressure( Angles%Dalpha, ray2D( 1 )%c, Pos%Rr, U, NRz_per_range, Pos%NRr, Beam%RunType, freq )';
main=strrep(main,anchor,"        CALL SYSTEM_CLOCK(PerfCoarse0)"+newline+anchor+newline+ ...
"        CALL SYSTEM_CLOCK(PerfCoarse1)"+newline+"        PerfCoarseTicks(3)=PerfCoarseTicks(3)+PerfCoarse1-PerfCoarse0");
write(fullfile(output_dir,'bellhop.f90'),main);
build=normtext(fileread(fullfile(source_dir,'build_performance.ps1'))); build=strrep(build,"'-pg',",''); write(fullfile(output_dir,'build_performance.ps1'),build);
end
function text=wrap(text,name,anchor,counter,index)
text=char(text);
a=strfind(text,['  SUBROUTINE ' name '(']); b=strfind(text,['  END SUBROUTINE ' name]); assert(isscalar(a)&&isscalar(b)); part=text(a:b-1);
part=strrep(part,anchor,join(["    INTEGER(KIND=8)::clock0,clock1";"    LOGICAL::sample";string(anchor); ...
"    sample=IAND("+counter+",1023_8)==0";"    IF(sample) CALL SYSTEM_CLOCK(clock0)"],newline));
part=string(part)+newline+join(["    IF(sample) THEN";"       CALL SYSTEM_CLOCK(clock1)"; ...
"       PerfSampleTicks("+index+")=PerfSampleTicks("+index+")+clock1-clock0"; ...
"       PerfSampleN("+index+")=PerfSampleN("+index+")+1";"    END IF"],newline)+newline;
text=[text(1:a-1) char(part) text(b:end)];
end
function text=normtext(text)
text=strrep(text,sprintf('\r\n'),newline);
end
function write(path,text)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); c=onCleanup(@()fclose(fid)); fprintf(fid,'%s',text);
end