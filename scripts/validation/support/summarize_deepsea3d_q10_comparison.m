function c=summarize_deepsea3d_q10_comparison(s)
%SUMMARIZE_DEEPSEA3D_Q10_COMPARISON Native errors and empirical numeric ranges.
assert(s.reference_ready && numel(s.fk)==5);
b=s.baseline;f0=b.fk(2);r0=b.runs(end);f1=s.fk(2);r1=s.runs(s.reference_index).result;
m0=local_metrics(f0,r0);m1=local_metrics(f1,r1);
oldcoarse=b.baseline.coarse.runs([b.baseline.coarse.runs.order]==20);
refs0=[oldcoarse,b.baseline.runs(2),r0];
refs1=[s.runs(s.coarse_index).result,s.runs(s.fine_index).result,r1];
row0=local_row(0,b.cfg,m0,f0,r0,refs0);row1=local_row(.1,s.cfg,m1,f1,r1,refs1);
names=fieldnames(m0);envelopes=struct([]);
for j=1:numel(names)
    name=names{j};values0=local_variants(b.fk,refs0,name);values1=local_variants(s.fk,refs1,name);
    lo0=min(values0);hi0=max(values0);lo1=min(values1);hi1=max(values1);
    direction="UNRESOLVED";
    if lo1>hi0,direction="INCREASE";elseif hi1<lo0,direction="DECREASE";end
    row=struct('metric',string(name),'q0_min',lo0,'q0_max',hi0,'q10_min',lo1,'q10_max',hi1, ...
        'primary_difference',m1.(name)-m0.(name),'ranges_disjoint',hi1<lo0 || lo1>hi0,'direction',direction);
    if j==1,envelopes=repmat(row,numel(names),1);else,envelopes(j)=row;end
end
c=struct('metrics_q0',m0,'metrics_q10',m1,'row_q0',row0,'row_q10',row1,'envelopes',envelopes, ...
    'reference_variant_count_each',3,'FK_variant_count_each',5, ...
    'envelope_scope','Cartesian products of selected-order coarse/fine/domain references and five FK numerical variants; empirical, not a confidence interval or rigorous bound');
end
function m=local_metrics(f,r)
m=struct('reflected_complex',abs(f.reflect_native-r.reflect_native)/abs(r.reflect_native), ...
    'increment_complex',abs(f.rough_correction-r.rough_correction)/abs(r.rough_correction), ...
    'reflected_magnitude',abs(abs(f.reflect_native)-abs(r.reflect_native))/abs(r.reflect_native), ...
    'increment_magnitude',abs(abs(f.rough_correction)-abs(r.rough_correction))/abs(r.rough_correction), ...
    'reflected_phase_rad',angle(f.reflect_native*conj(r.reflect_native)), ...
    'increment_phase_rad',angle(f.rough_correction*conj(r.rough_correction)));
end
function values=local_variants(fk,refs,name)
values=zeros(numel(fk)*numel(refs),1);j=0;
for f=fk
    for r=refs
        m=local_metrics(f,r);j=j+1;values(j)=m.(name);
    end
end
end
function row=local_row(q,cfg,m,f,r,refs)
bg=deepsea3d_flat(cfg,0);
row=struct('q',q,'reflected_complex',m.reflected_complex,'increment_complex',m.increment_complex, ...
    'reflected_magnitude',m.reflected_magnitude,'increment_magnitude',m.increment_magnitude, ...
    'reflected_phase_rad',m.reflected_phase_rad,'increment_phase_rad',m.increment_phase_rad, ...
    'reference_reflect_real',real(r.reflect_native),'reference_reflect_imag',imag(r.reflect_native), ...
    'reference_delta_real',real(r.rough_correction),'reference_delta_imag',imag(r.rough_correction), ...
    'reference_total_abs',abs(r.total_native),'reference_reflect_abs',abs(r.reflect_native), ...
    'reference_delta_abs',abs(r.rough_correction), ...
    'flat_total_condition',(abs(bg.direct_native)+abs(bg.reflect_native))/abs(bg.total_native), ...
    'rough_total_condition',(abs(bg.direct_native)+abs(r.reflect_native))/abs(r.total_native), ...
    'reflected_background_increment_condition',(abs(bg.reflect_native)+abs(r.rough_correction))/abs(r.reflect_native), ...
    'pressure_order_sum_indicator',sum(abs(r.terms))/abs(r.rough_correction), ...
    'FK_density_indicator',f.cancellation_condition,'total_complex_error',abs(f.total_native-r.total_native)/abs(r.total_native), ...
    'reference_total_variant_change',max(arrayfun(@(v)abs(v.total_native-r.total_native)/abs(r.total_native),refs)));
end
