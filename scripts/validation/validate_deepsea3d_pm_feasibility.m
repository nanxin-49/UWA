function state=validate_deepsea3d_pm_feasibility(stage)
%VALIDATE_DEEPSEA3D_PM_FEASIBILITY Bounded one-realization reference probe.
% No FK invocation: a failed independent reference must not rank physics.
arguments
    stage (1,1) string = "status"
end
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
out=fullfile(root,'results','validation','deepsea3d_pm_feasibility');
file=fullfile(out,'feasibility.mat');
if stage=="init"
    assert(~isfile(file),'pmFeasibility:Exists','Existing data must not be overwritten.');
    if ~isfolder(out),mkdir(out);end
    sea=build_deepsea3d_pm_target();
    cfg=struct('frequency_hz',6000,'c0_mps',1500,'tx_m',[0 150.5 1500], ...
        'rx_m',[0 0 5],'center_m',[0 0],'profile',sea.profile);
    state=struct('sea',sea,'cfg',cfg,'runs',struct([]),'observer',struct(), ...
        'reference_ready',false,'support_controlled',false,'G1_status',"INCONCLUSIVE", ...
        'global_G1',"OPEN",'WP2_allowed',false,'FK_solves',0,'matlab_version',version);
    % kind,L,h,N,plateau,support: first three order preflight, then bounded
    % mesh/domain, physical support, and common-coefficient band probes.
    state.jobs=[1 24 .125 12 8 12;1 24 .125 16 8 12;1 24 .125 20 8 12; ...
        1 24 .0625 20 8 12;1 32 .125 20 8 12; ...
        1 32 .125 20 16 24;2 24 .125 20 8 12; ...
        3 24 .125 20 8 12;4 24 .125 20 8 12];
    state.job_names=["N12","N16","N20","mesh","domain", ...
        "support24","remove_long","remove_short","extend_short"];
    state.flat_control=deepsea3d_flat(cfg,0);
    local_json(fullfile(out,'surface_definition.json'),rmfield(sea, ...
        {'profile','kx_radpm','ky_radpm','k_radpm','density_m4','standard_normals', ...
        'coefficient_real','coefficient_imag','baseline_mask','low_removed_mask', ...
        'short_removed_mask','short_extended_mask'}));
    T=table(sea.kx_radpm,sea.ky_radpm,sea.density_m4,sea.standard_normals(:,1), ...
        sea.standard_normals(:,2),sea.coefficient_real,sea.coefficient_imag,sea.baseline_mask, ...
        'VariableNames',{'kx_radpm','ky_radpm','P_m4','normal_real','normal_imag','c_real_m','c_imag_m','baseline'});
    writetable(T,fullfile(out,'parent_coefficients.csv'));
elseif stage=="status"
    a=load(file,'state');state=a.state; return
else
    a=load(file,'state');state=a.state;
end
switch stage
    case "init"
        fprintf('PM Tp %.6g Hfull %.6g modes %d actual H %.6g max height %.6g\n', ...
            sea.Tp_s,sea.Hm0_untruncated_family_m,sea.parent_diagnostics.modes_positive, ...
            sea.parent_diagnostics.realized_Hm0_m,sea.parent_diagnostics.max_abs_height_sampled_m);
    case "next"
        j=numel(state.runs)+1;
        assert(j<=size(state.jobs,1),'pmFeasibility:Finished','All bounded probes completed.');
        v=state.jobs(j,:); cfg=local_cfg(state,v);
        opts=struct('domain_halfwidth_m',v(2),'spacing_m',v(3),'order',v(4), ...
            'residual_order',40,'offgrid',true);
        [mb,~]=memory; r=deepsea3d_dirichlet_fe(cfg,opts); [ma,~]=memory;
        entry=struct('name',state.job_names(j),'settings',v,'result',r, ...
            'before_MiB',mb.MemUsedMATLAB/2^20,'after_MiB',ma.MemUsedMATLAB/2^20);
        state.runs=local_append(state.runs,entry);
        fprintf('%s delta=(%.12g,%.12g) boundary %.6g half %.6g forcing %.6g tail %.6g wall %.3fs\n', ...
            entry.name,real(r.rough_correction),imag(r.rough_correction),r.boundary_residual_relative, ...
            r.offgrid_boundary_residual_relative,r.forcing_series_relative,local_tail(r),r.wall_s);
    case "observe"
        assert(numel(state.runs)>=3,'pmFeasibility:Stage','Complete the order probes.');
        v=state.jobs(3,:);cfg=local_cfg(state,v);
        opts=struct('domain_halfwidth_m',v(2),'spacing_m',v(3),'order',v(4));
        state.observer=observe_deepsea3d_fe_cancellation(cfg,opts,state.runs(3).result);
        fprintf('Replay max cancellation %.6g term error %.3g norm error %.3g\n', ...
            max(state.observer.conditions),state.observer.term_match_error,state.observer.norm_match_error);
    case "audit"
        assert(numel(state.runs)==size(state.jobs,1) && isfield(state.observer,'terms'));
        r=state.runs(3).result;
        g=struct('N16_to_N20',local_change(state.runs(2).result,r), ...
            'N18_to_N20',local_tail(r),'boundary',r.boundary_residual_relative, ...
            'offgrid',r.offgrid_boundary_residual_relative, ...
            'mesh',local_change(state.runs(4).result,r), ...
            'domain',local_change(state.runs(5).result,r));
        state.guards=g;
        state.tail_decreases=all(diff(r.boundary_coefficient_norms(end-4:end))<0) ...
            && all(diff(abs(r.terms(end-4:end)))<0);
        state.reference_ready=all(structfun(@(x)isfinite(x) && x<1e-4,g)) ...
            && state.tail_decreases && r.forcing_series_relative<1e-8;
        % These probes deliberately do not establish a noncompact reference.
        state.support_controlled=false;
        state.complete=true;
        state.reason="Bounded ordinary FE and finite-support probes; no noncompact physical certification";
        local_json(fullfile(out,'artifact_assertions.json'),struct('complete',true, ...
            'reference_ready',state.reference_ready,'support_controlled',false, ...
            'G1_status',state.G1_status,'global_G1',state.global_G1,'WP2_allowed',false, ...
            'FK_solves',0,'seed',state.sea.seed,'new_FE_solves',numel(state.runs), ...
            'coefficients_no_RMS_rescale',true,'no_fit',true));
        writetable(struct2table(g),fullfile(out,'reference_guards.csv'));
        trace_wall=0;if isfield(state,'trace'),trace_wall=sum([state.trace.wall_s]);end
        local_json(fullfile(out,'cost_summary.json'),struct( ...
            'FE_wall_s',sum(arrayfun(@(a)a.result.wall_s,state.runs)), ...
            'observer_wall_s',state.observer.wall_s, ...
            'diagnostic_trace_wall_s',trace_wall, ...
            'maximum_stored_spectral_MiB',max(arrayfun(@(a)a.result.stored_spectral_MiB,state.runs)), ...
            'scope','saved FE kernels, cancellation replay and trace replay; excludes IO/report/static analysis; snapshots are not peaks'));
    case "trace"
        assert(numel(state.runs)>=4,'pmFeasibility:Stage','Complete coarse and fine probes.');
        state.trace=struct([]);
        for j=[3 4]
            v=state.jobs(j,:);cfg=local_cfg(state,v);
            opts=struct('domain_halfwidth_m',v(2),'spacing_m',v(3),'order',v(4));
            d=observe_deepsea3d_pm_trace(cfg,opts,state.runs(j).result);
            state.trace=local_append(state.trace,d);
            fprintf('Exact modal trace h%g residual %.6g M40 bias %.6g cancellation %.6g\n', ...
                v(3),d.exact_trace_residual_relative,d.M40_to_exact_relative,max(d.modal_cancellation_indicators));
            T=table(d.xy_m(:,1),d.xy_m(:,2),d.eta_m,real(d.flat_native),imag(d.flat_native), ...
                real(d.exact_trace_native),imag(d.exact_trace_native), ...
                real(d.M32_trace_native),imag(d.M32_trace_native), ...
                real(d.M40_trace_native),imag(d.M40_trace_native),d.modal_cancellation_indicators, ...
                'VariableNames',{'x_m','y_m','eta_m','flat_real','flat_imag','trace_real','trace_imag', ...
                'M32_real','M32_imag','M40_real','M40_imag','modal_sum_indicator'});
            writetable(T,fullfile(out,sprintf('trace_h%g.csv',v(3))));
        end
    otherwise
        error('pmFeasibility:Stage','Unknown stage.');
end
save(file,'state','-v7'); local_outputs(state,out);
end
function cfg=local_cfg(s,v)
cfg=s.cfg; masks={s.sea.baseline_mask,s.sea.low_removed_mask, ...
    s.sea.short_removed_mask,s.sea.short_extended_mask};
m=masks{v(1)}; c=complex(s.sea.coefficient_real(m),s.sea.coefficient_imag(m));
cfg.profile.amplitudes_m=2*abs(c).';cfg.profile.phases_rad=angle(c).';
cfg.profile.wavevectors_radpm=[s.sea.kx_radpm(m) s.sea.ky_radpm(m)];
cfg.profile.plateau_m=v(5);cfg.profile.support_m=v(6);
end
function x=local_change(a,b)
x=abs(a.rough_correction-b.rough_correction)/max(abs(b.rough_correction),realmin);
end
function x=local_tail(r)
x=abs(r.partials(end)-r.partials(end-2))/max(abs(r.rough_correction),realmin);
end
function a=local_append(a,b)
if isempty(a),a=b;else,a(end+1)=b;end
end
function local_json(file,s)
fid=fopen(file,'w');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(s,PrettyPrint=true));
end
function local_outputs(s,out)
rows=struct([]);terms=struct([]);
for j=1:numel(s.runs)
    a=s.runs(j);r=a.result;v=a.settings;
    row=struct('name',a.name,'spectrum_kind',v(1),'L_m',v(2),'h_m',v(3),'N',v(4), ...
        'plateau_m',v(5),'support_m',v(6),'delta_real',real(r.rough_correction), ...
        'delta_imag',imag(r.rough_correction),'reflect_real',real(r.reflect_native), ...
        'reflect_imag',imag(r.reflect_native),'total_real',real(r.total_native), ...
        'total_imag',imag(r.total_native),'boundary',r.boundary_residual_relative, ...
        'offgrid',r.offgrid_boundary_residual_relative,'forcing',r.forcing_series_relative, ...
        'last_two_change',local_tail(r),'wall_s',r.wall_s,'cpu_s',r.cpu_s, ...
        'max_height_m',r.max_height_m,'spectral_MiB',r.stored_spectral_MiB, ...
        'before_MiB',a.before_MiB,'after_MiB',a.after_MiB);
    rows=local_append(rows,row);
    for n=1:r.order
        terms=local_append(terms,struct('name',a.name,'n',n, ...
            'term_real',real(r.terms(n)),'term_imag',imag(r.terms(n)), ...
            'coefficient_norm',r.boundary_coefficient_norms(n)));
    end
end
if ~isempty(rows),writetable(struct2table(rows),fullfile(out,'runs.csv'));end
if ~isempty(terms),writetable(struct2table(terms),fullfile(out,'terms.csv'));end
end
