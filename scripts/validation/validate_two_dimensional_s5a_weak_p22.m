function receipt = validate_two_dimensional_s5a_weak_p22(frozen_source_path,output_dir,available_physical_bytes)
%VALIDATE_TWO_DIMENSIONAL_S5A_WEAK_P22 Local 6 kHz PE/FullFK reference input.
% Diagnostics only until an independent five-layer BIE reference qualifies.
arguments
    frozen_source_path (1,:) char
    output_dir (1,:) char
    available_physical_bytes (1,1) double {mustBeFinite,mustBePositive}
end
assert(isfile(frozen_source_path) && ~isfolder(output_dir) && ~isfile(output_dir));
estimated_increment_bytes=256*1024^2;
assert(estimated_increment_bytes<=0.7*available_physical_bytes,'RAM gate');
f=6000; c0=1500; A=0.01; x_rx=0; z_rx=3;
s=load(frozen_source_path,'src'); src=closeout2d_source_at_frequency(s.src,f,c0);
N=src.n_original; W=192.1875; x=(-W/2)+(0:N-1)'*W/N;
source_tx=ifft(src.coeff(:));
[eta,~]=closeout_s2b_surface(x,A);
cfg=struct('frequency_hz',f,'c0_mps',c0,'xw_m',W,'nx',N, ...
    'z_tx_m',100,'z_rx_m',z_rx,'sigma_src_m',0.3, ...
    'surface_reflect_coeff',-1,'step_m',0.05,'x_rx_m',x_rx, ...
    'reflection_model','model0_normal','source_field_override',source_tx, ...
    'eta_z_m',eta);
tic_total=tic;
tic_pe=tic; pe=run_pe_physical_surface_model0_validation(cfg);
pe_seconds=toc(tic_pe);
u_direct=fk_single_receiver_incident(src,x_rx,z_rx);
u_flat_reflect=-fk_single_receiver_incident(src,x_rx,-z_rx);
k=2*pi*f/c0;
pe_direct_native=pe.direct_receiver*exp(1i*k*97);
pe_reflect_native=pe.reflected_native(pe.ix_rx);
direct_relative=abs(pe_direct_native-u_direct)/abs(u_direct);
assert(direct_relative<1e-10,'Direct path source gate');
tic_fk=tic;
fk400=closeout_s2b_fullfk_analytic_exterior(src,A,x_rx,z_rx,400,u_flat_reflect);
fk800=closeout_s2b_fullfk_analytic_exterior(src,A,x_rx,z_rx,800,u_flat_reflect);
fk_seconds=toc(tic_fk);
fk_quadrature_relative=abs(fk400.receiver_field-fk800.receiver_field)/ ...
    abs(fk800.receiver_field);
tau_d=97/c0; phase=exp(1i*2*pi*f*tau_d);
H_direct=conj(u_direct)*phase;
H_PE_reflect=conj(pe_reflect_native)*phase;
H_FullFK_reflect=conj(fk800.receiver_field)*phase;
H_PE_total=H_direct+H_PE_reflect;
H_FullFK_total=H_direct+H_FullFK_reflect;
metrics=table(f,A,x_rx,z_rx,direct_relative, ...
    fk_quadrature_relative,abs(pe_reflect_native-fk800.receiver_field), ...
    real(H_direct),imag(H_direct),real(H_PE_reflect),imag(H_PE_reflect), ...
    real(H_FullFK_reflect),imag(H_FullFK_reflect), ...
    real(H_PE_total),imag(H_PE_total), ...
    real(H_FullFK_total),imag(H_FullFK_total),pe_seconds,fk_seconds, ...
    'VariableNames',{'frequency_hz','amplitude_m','receiver_x_m', ...
    'receiver_z_m','direct_relative','fk_400_800_relative', ...
    'pe_fk_reflect_absolute','H_direct_real','H_direct_imag', ...
    'H_PE_reflect_real','H_PE_reflect_imag', ...
    'H_FullFK_reflect_real','H_FullFK_reflect_imag', ...
    'H_PE_total_real','H_PE_total_imag', ...
    'H_FullFK_total_real','H_FullFK_total_imag', ...
    'pe_seconds','fullfk_seconds'});
receipt=struct('status','PRE_REFERENCE_DIAGNOSTIC_ONLY', ...
    'matlab_version',version,'frequency_hz',f,'amplitude_m',A, ...
    'source_id','frozen 984-term Gaussian spatial field', ...
    'representation','native exp(-i omega t), unit-source response', ...
    'common_dsp_origin_s',tau_d,'available_physical_bytes',available_physical_bytes, ...
    'estimated_increment_bytes',estimated_increment_bytes, ...
    'pe_calls',1,'fullfk_evaluations',2,'bie_boundary_solves',0, ...
    'elapsed_seconds',toc(tic_total));
mkdir(output_dir);
save(fullfile(output_dir,'weak_p22_fields.mat'),'metrics','receipt','src', ...
    'u_direct','u_flat_reflect','pe_direct_native','pe_reflect_native', ...
    'fk400','fk800','H_direct','H_PE_reflect','H_FullFK_reflect', ...
    'H_PE_total','H_FullFK_total','frozen_source_path');
writetable(metrics,fullfile(output_dir,'weak_p22_metrics.csv'));
fid=fopen(fullfile(output_dir,'receipt.json'),'w');
assert(fid>0); cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(receipt,PrettyPrint=true));
disp(receipt); disp(metrics(:,1:7));
end
