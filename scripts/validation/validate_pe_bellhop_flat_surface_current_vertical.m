    phase_audit,meta,closure,window_audit,public_regression);
matrix_file=fullfile(out_dir,'pe_bellhop_current_matrix.mat');
validation_run_meta=meta; schema_version='1.0.0';
phase_reference_meta=baseline_cases(1).pe.phase_reference_meta;
validation=struct('schema_version',schema_version,'validation_run_meta',meta, ...
    'phase_reference_meta',phase_reference_meta,'config',cfg, ...
    'phase_audit',phase_audit,'baseline_cases',baseline_cases, ...
    'path_table',path_table,'closure',closure, ...
    'amplitude_metrics',amplitude_metrics,'small_offset',small_offset, ...
    'source_audit',source_audit,'window_audit',window_audit, ...
    'public_regression',public_regression,'matrix_validation',matrix_validation);
save(matrix_file,'validation','matrix_validation','schema_version', ...
    'phase_reference_meta','validation_run_meta','-v7.3');

field_dir=fullfile(visual_dir,'bellhop_fields_raw');
