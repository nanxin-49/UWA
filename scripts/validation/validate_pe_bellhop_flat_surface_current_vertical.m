function cir=local_path_cir(H,f,tref,target,cfg)
cir=local_total_cir(H,f,tref,cfg); mask=abs(cir.delay_s-target)<=0.001;
idx=find(mask); if isempty(idx), error('Path peak window is empty.'); end
[~,j]=max(cir.power(mask)); cir.peak_time_s=cir.delay_s(idx(j));
end

function cir=local_total_cir(H,f,tref,cfg)
F=numel(f); n=(0:F-1).'; df=mean(diff(f)); N=cfg.zero_padding_factor*F;
w=0.5-0.5*cos(2*pi*n/(F-1));
h=fft(H(:).*exp(-1i*2*pi*f(:)*tref).*w,N)/N;
cir=struct('delay_s',tref+(0:N-1).'/(df*N),'h',h,'power',abs(h).^2, ...
    'reference_time_s',tref);
end

function value=local_phase_rms(H,H0,ir)
relative=(H/H(ir)).*conj(H0/H0(ir)); phase=unwrap(angle(relative));
phase=phase-phase(ir); value=sqrt(mean(phase.^2));
end

function db=local_edge_level_db(field)
if isempty(field), db=Inf; return; end
ny=size(field,1); nx=size(field,2); width=max(1,round(0.02*min(nx,ny)));
mask=false(ny,nx); mask(1:width,:)=true; mask(end-width+1:end,:)=true;
mask(:,1:width)=true; mask(:,end-width+1:end)=true;
db=20*log10(max(abs(field(mask)))/max(max(abs(field(:))),realmin));
end

