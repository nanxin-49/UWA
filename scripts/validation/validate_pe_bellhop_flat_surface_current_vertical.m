function validation = validate_pe_bellhop_flat_surface_current_vertical(overrides)
%VALIDATE_PE_BELLHOP_FLAT_SURFACE_CURRENT_VERTICAL Current-version closure.
% Validation only: public PE marching, defaults, and communication are not changed.

if nargin<1 || isempty(overrides), overrides=struct(); end
this_file=mfilename('fullpath');
project_root=fileparts(fileparts(fileparts(this_file)));
addpath(project_root); setup_vertical_project();
addpath(fullfile(project_root,'scripts','reporting'));
cfg=local_defaults(); cfg=local_overrides(cfg,overrides); local_validate_cfg(cfg);

meta=pe_bellhop_current_run_meta_vertical(project_root,struct( ...
    'run_id',cfg.run_id,'bellhop_exe',cfg.bellhop_exe));
cfg.bellhop_exe=meta.bellhop_executable;
out_dir=meta.validation_output_dir; visual_dir=meta.visualization_output_dir;
