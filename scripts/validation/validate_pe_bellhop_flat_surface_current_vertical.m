    'source_validation_mat',matrix_file,'output_dir',field_dir, ...
    'bellhop_exe',cfg.bellhop_exe,'show_figures',false));
validation.field_output=field_output;
validation=local_finalize(validation,cfg);

path_csv=fullfile(out_dir,'baseline_path_comparison.csv');
small_csv=fullfile(out_dir,'small_offset_comparison.csv');
source_csv=fullfile(out_dir,'source_directivity_audit.csv');
window_csv=fullfile(out_dir,'window_sponge_audit.csv');
checks_csv=fullfile(out_dir,'layered_acceptance_checks.csv');
writetable(validation.path_table,path_csv);
writetable(validation.small_offset.table,small_csv);
writetable(validation.source_audit.table,source_csv);
writetable(validation.window_audit.table,window_csv);
writetable(validation.checks,checks_csv);
validation.files=struct('mat',fullfile(out_dir,'pe_bellhop_current_validation.mat'), ...
    'path_csv',path_csv,'small_offset_csv',small_csv,'source_csv',source_csv, ...
    'window_csv',window_csv,'checks_csv',checks_csv,'matrix_mat',matrix_file);
