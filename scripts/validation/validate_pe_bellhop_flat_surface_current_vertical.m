    'output_dir',phase_dir,'validation_run_meta',meta, ...
    'frequency_band_hz',cfg.frequency_band_hz, ...
    'frequency_count',cfg.phase_frequency_count, ...
    'f_ref_hz',cfg.f_ref_hz,'receiver_offsets_m',cfg.baseline_offsets_m));

f_axis_hz=linspace(cfg.frequency_band_hz(1),cfg.frequency_band_hz(2), ...
    cfg.frequency_count).';
[baseline_cases,path_table,closure]=local_baseline_cases(cfg,f_axis_hz,out_dir);
[path_table,amplitude_metrics]=local_amplitude_metrics(path_table,cfg);
small_offset=local_small_offset_cases(cfg,f_axis_hz,out_dir,baseline_cases);
source_audit=local_source_audit(cfg,baseline_cases,small_offset);
