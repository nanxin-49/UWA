function audit = audit_two_dimensional_s5_cost_projections(single_dir,dual_dir,audit_dir)
%AUDIT_TWO_DIMENSIONAL_S5_COST_PROJECTIONS Recompute saved planning tables.
arguments
    single_dir (1,:) char
    dual_dir (1,:) char
    audit_dir (1,:) char
end
assert(~isfolder(audit_dir) && ~isfile(audit_dir), ...
    'Use a fresh audit directory.');
a = readtable(fullfile(single_dir,'per_frequency_layer_projection.csv'));
b = readtable(fullfile(dual_dir,'per_frequency_layer_projection.csv'));
am = jsondecode(fileread(fullfile(single_dir,'model_and_limitations.json')));
bm = jsondecode(fileread(fullfile(dual_dir,'model_and_limitations.json')));
as = jsondecode(fileread(fullfile(single_dir,'summary.json')));
bs = jsondecode(fileread(fullfile(dual_dir,'summary.json')));
assert(height(a)==970 && height(b)==970, 'Unexpected layer table length.');

single_row_error_s = 0;
dual_row_error_s = 0;
memory_error_bytes = 0;
for ii = 1:height(a)
    layer = string(a.layer(ii));
    jj = find(strcmp(am.layers,layer),1);
    assert(~isempty(jj),'Unknown single-anchor layer.');
    predicted = am.baseline_kernel_seconds(jj)* ...
        (a.nodes(ii)/am.baseline_node_counts(jj))^3;
    single_row_error_s = max(single_row_error_s, ...
        abs(predicted-a.projected_bie_kernel_seconds(ii)));
    memory_error_bytes = max(memory_error_bytes, ...
        abs(64*a.nodes(ii)^2+128*2^20-a.estimated_increment_bytes(ii)));

    layer = string(b.layer(ii));
    jj = find(strcmp(bm.layers,layer),1);
    assert(~isempty(jj),'Unknown two-anchor layer.');
    exponent = log(bm.kernel_seconds_8k(jj)/bm.kernel_seconds_6k(jj))/ ...
        log(bm.node_counts_8k(jj)/bm.node_counts_6k(jj));
    predicted = bm.kernel_seconds_6k(jj)* ...
        (b.node_count(ii)/bm.node_counts_6k(jj))^exponent;
    dual_row_error_s = max(dual_row_error_s, ...
        abs(predicted-b.projected_kernel_seconds(ii)));
    memory_error_bytes = max(memory_error_bytes, ...
        abs(64*b.node_count(ii)^2+128*2^20-b.estimated_increment_bytes(ii)));
end

single_sum_error_s = 0;
dual_sum_error_s = 0;
frequency_count_error = 0;
for jj = 1:2
    count = [65,129]; count = count(jj);
    sa = a(a.grid_count==count,:);
    sb = b(b.grid_count==count,:);
    frequency_count_error = max(frequency_count_error, ...
        abs(numel(unique(sa.frequency_hz))-count));
    frequency_count_error = max(frequency_count_error, ...
        abs(numel(unique(sb.frequency_hz))-count));
    single_sum_error_s = max(single_sum_error_s, ...
        abs(sum(sa.projected_bie_kernel_seconds)- ...
        as(jj).projected_weak_sine_bie_kernel_seconds));
    dual_sum_error_s = max(dual_sum_error_s, ...
        abs(sum(sb.projected_kernel_seconds)- ...
        bs(jj).projected_weak_sine_p22_kernel_seconds));
end
base_f = unique(a.frequency_hz(a.grid_count==65));
refined_f = unique(a.frequency_hz(a.grid_count==129));
nesting_error_hz = max(abs(base_f-refined_f(1:2:end)));

gates = struct('single_rows',single_row_error_s<=1e-9, ...
    'dual_rows',dual_row_error_s<=1e-9, ...
    'memory_formula',memory_error_bytes==0, ...
    'summary_sums',single_sum_error_s<=1e-6 && dual_sum_error_s<=1e-6, ...
    'frequency_grid',frequency_count_error==0 && nesting_error_hz==0);
failed_check_count=sum(~cell2mat(struct2cell(gates)));
if failed_check_count==0
    status='PLANNING_TABLES_INDEPENDENT_AUDIT_PASS';
else
    status='PLANNING_TABLES_INDEPENDENT_AUDIT_FAIL';
end
audit = struct('status',status,'failed_check_count',failed_check_count, ...
    'single_anchor_row_max_error_s',single_row_error_s, ...
    'two_anchor_row_max_error_s',dual_row_error_s, ...
    'memory_formula_max_error_bytes',memory_error_bytes, ...
    'single_anchor_summary_error_s',single_sum_error_s, ...
    'two_anchor_summary_error_s',dual_sum_error_s, ...
    'frequency_count_error',frequency_count_error, ...
    'nested_frequency_error_hz',nesting_error_hz, ...
    'single_65_kernel_hours',as(1).projected_weak_sine_bie_kernel_hours, ...
    'single_129_kernel_hours',as(2).projected_weak_sine_bie_kernel_hours, ...
    'dual_65_kernel_hours',bs(1).projected_weak_sine_p22_kernel_hours, ...
    'dual_129_kernel_hours',bs(2).projected_weak_sine_p22_kernel_hours, ...
    'scope','planning table arithmetic only; no timing bound or solve approval', ...
    'gates',gates);
mkdir(audit_dir);
fid=fopen(fullfile(audit_dir,'audit.json'),'w');
assert(fid>0,'Cannot write audit.json.');
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(audit,PrettyPrint=true));
disp(audit);
if failed_check_count>0
    error('Cost planning audit failed.');
end
end
