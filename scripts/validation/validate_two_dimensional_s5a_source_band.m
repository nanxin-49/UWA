function receipt = validate_two_dimensional_s5a_source_band(frozen_source_path,output_dir,available_physical_bytes)
%VALIDATE_TWO_DIMENSIONAL_S5A_SOURCE_BAND Check frozen source/direct field.
% A-stage source control only: no rough reflection, CIR, or communication.
arguments
    frozen_source_path (1,:) char
    output_dir (1,:) char
    available_physical_bytes (1,1) double {mustBeFinite,mustBePositive}
end
assert(isfile(frozen_source_path) && ~isfolder(output_dir) && ~isfile(output_dir));
estimated_increment_bytes=128*1024^2;
assert(estimated_increment_bytes<=.7*available_physical_bytes,'RAM gate');
s=load(frozen_source_path,'src'); frozen=s.src;
assert(frozen.n_original==984 && frozen.z_tx_m==100);
N=frozen.n_original; W=192.1875; c0=1500; x0=-W/2;
x=x0+(0:N-1)'*W/N;
assert(abs(frozen.x0_m-x0)<1e-12);
source_tx=ifft(frozen.coeff(:));
assert(max(abs(source_tx-exp(-.5*(x/.3).^2)))<1e-12);
frequencies_hz=4000+(0:128)'*31.25;
coarse_frequencies_hz=4000+(0:64)'*62.5;
assert(isequal(frequencies_hz(1:2:end),coarse_frequencies_hz));
tx_error=zeros(129,1); direct_error=zeros(129,1);
minimum_radiation_margin=zeros(129,1); pe_seconds=zeros(129,1);
direct_analytic=complex(zeros(129,1)); direct_pe=direct_analytic;
tic_total=tic;
for ii=1:129
    f=frequencies_hz(ii); k=2*pi*f/c0;
    src=closeout2d_source_at_frequency(frozen,f,c0);
    assert(isequal(src.coeff,frozen.coeff),'Frozen Fourier coefficients changed');
    minimum_radiation_margin(ii)=min(k^2-src.kx(:).^2);
    assert(minimum_radiation_margin(ii)>0,'Unexpected evanescent term');
    assert(norm(src.kz(:).^2+src.kx(:).^2-k^2)/ ...
        (sqrt(N)*k^2)<1e-13,'Longitudinal dispersion changed');
    if ii==1
        assert(norm(src.kz-frozen.kz)/norm(frozen.kz)<1e-14);
    end
    tx=fk_single_receiver_incident(src,x,100+zeros(N,1));
    tx_error(ii)=norm(tx-source_tx)/norm(source_tx);
    direct_analytic(ii)=fk_single_receiver_incident(src,0,3);
    cfg=struct('frequency_hz',f,'c0_mps',c0,'xw_m',W, ...
        'nx',N,'z_tx_m',100,'z_rx_m',3,'sigma_src_m',.3, ...
        'surface_reflect_coeff',-1,'step_m',.05,'x_rx_m',0, ...
        'reflection_model','model0_normal', ...
        'source_field_override',source_tx,'eta_z_m',zeros(N,1));
    tic_pe=tic; pe=run_pe_physical_surface_model0_validation(cfg);
    pe_seconds(ii)=toc(tic_pe);
    direct_pe(ii)=pe.direct_receiver*exp(1i*k*97);
    direct_error(ii)=abs(direct_pe(ii)-direct_analytic(ii))/ ...
        abs(direct_analytic(ii));
    assert(tx_error(ii)<=1e-10 && direct_error(ii)<=1e-10, ...
        'Frozen source or PE direct field control failed');
end
metrics=table(frequencies_hz,tx_error,direct_error, ...
    minimum_radiation_margin,real(direct_analytic),imag(direct_analytic), ...
    real(direct_pe),imag(direct_pe),pe_seconds, ...
    'VariableNames',{'frequency_hz','tx_source_relative', ...
    'pe_direct_relative','minimum_kz_squared_radm2', ...
    'analytic_direct_native_real','analytic_direct_native_imag', ...
    'pe_direct_native_real','pe_direct_native_imag','pe_wall_seconds'});
receipt=struct('status','A_SOURCE_DIRECT_BAND_PASS_ONLY', ...
    'matlab_version',version,'frequency_count',numel(frequencies_hz), ...
    'frequency_start_hz',frequencies_hz(1), ...
    'frequency_end_hz',frequencies_hz(end), ...
    'frequency_spacing_hz',31.25,'coarse_nested_count',65, ...
    'max_tx_source_relative',max(tx_error), ...
    'max_pe_direct_relative',max(direct_error), ...
    'minimum_kz_squared_radm2',min(minimum_radiation_margin), ...
    'pe_calls',129,'bie_boundary_solves',0, ...
    'estimated_increment_bytes',estimated_increment_bytes, ...
    'available_physical_bytes',available_physical_bytes, ...
    'elapsed_seconds',toc(tic_total), ...
    'field_unit','unit-source response, not Pa', ...
    'native_phase_convention','exp(-i omega t)', ...
    'direct_reference','same frozen Gaussian Fourier source');
assert(receipt.elapsed_seconds<900,'Single workflow time gate');
mkdir(output_dir);
save(fullfile(output_dir,'source_band_controls.mat'), ...
    'metrics','receipt','frequencies_hz','coarse_frequencies_hz', ...
    'source_tx','frozen_source_path','-v7.3');
writetable(metrics,fullfile(output_dir,'source_band_metrics.csv'));
fid=fopen(fullfile(output_dir,'receipt.json'),'w');
assert(fid>0); cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(receipt,PrettyPrint=true));
disp(receipt);
end
