function audit=audit_two_dimensional_s5a_weak_bie(remote_mirror,local_weak_mat,local_pe_mat,output_dir)
%AUDIT_TWO_DIMENSIONAL_S5A_WEAK_BIE Reopen independent 6 kHz P22 evidence.
arguments
    remote_mirror (1,:) char
    local_weak_mat (1,:) char
    local_pe_mat (1,:) char
    output_dir (1,:) char
end
assert(isfolder(remote_mirror) && isfile(local_weak_mat) && isfile(local_pe_mat));
assert(~isfolder(output_dir) && ~isfile(output_dir));
ids={'main96','self64','space14','window60','window70'};
U=complex(zeros(5,1)); node_count=zeros(5,1);
linear_residual=zeros(5,1); offgrid_residual=zeros(5,1);
for ii=1:5
    path=fullfile(remote_mirror,'jobs',ids{ii},'result.mat');
    assert(isfile(path),'Missing BIE layer');
    s=load(path,'boundary','receipt','pre');
    b=s.boundary; r=s.receipt; p=s.pre;
    assert(strcmp(r.status,'COMPLETE') && strcmp(r.job_id,ids{ii}));
    assert(b.frequency_hz==6000 && p.frequency_hz==6000 && ...
        p.amplitude_m==.01 && b.receiver_x_m==0 && b.receiver_z_m==3);
    assert(b.finite && b.node_count==r.node_count && ...
        b.node_count==p.node_estimate);
    assert(abs(b.receiver_field-complex(r.receiver_native_real, ...
        r.receiver_native_imag))<1e-14);
    assert(abs(b.linear_residual-r.linear_residual)<1e-15 && ...
        abs(b.offgrid_boundary_residual-r.offgrid_boundary_residual)<1e-15);
    U(ii)=b.receiver_field;
    node_count(ii)=b.node_count;
    linear_residual(ii)=b.linear_residual;
    offgrid_residual(ii)=b.offgrid_boundary_residual;
end
ref=U(1); ref_sensitivity=max(abs(U(2:end)-ref))/abs(ref);
weak=load(local_weak_mat,'pe_reflect_native','fk800','u_direct');
pe=load(local_pe_mat,'u_base','metrics');
assert(abs(weak.pe_reflect_native-pe.u_base)<1e-12);
pe_sensitivity=pe.metrics.empirical_relative;
fk_sensitivity=abs(weak.fk800.receiver_field- ...
    local_fk400(local_weak_mat))/abs(weak.fk800.receiver_field);
pe_model_relative=abs(weak.pe_reflect_native-ref)/abs(ref);
fk_model_relative=abs(weak.fk800.receiver_field-ref)/abs(ref);
pe_resolution=ref_sensitivity+pe_sensitivity;
fk_resolution=ref_sensitivity+fk_sensitivity;
ref_gate=ref_sensitivity<=1e-4;
pe_resolved=pe_model_relative>5*pe_resolution;
fk_resolved=fk_model_relative>5*fk_resolution;
phase=exp(1i*2*pi*6000*97/1500);
H_direct=conj(weak.u_direct)*phase;
H_BIE_reflect=conj(ref)*phase;
H_PE_reflect=conj(weak.pe_reflect_native)*phase;
H_FullFK_reflect=conj(weak.fk800.receiver_field)*phase;
H_BIE_total=H_direct+H_BIE_reflect;
H_PE_total=H_direct+H_PE_reflect;
H_FullFK_total=H_direct+H_FullFK_reflect;
response=table(6000,real(H_direct),imag(H_direct), ...
    real(H_BIE_reflect),imag(H_BIE_reflect), ...
    real(H_BIE_total),imag(H_BIE_total), ...
    real(H_PE_reflect),imag(H_PE_reflect), ...
    real(H_PE_total),imag(H_PE_total), ...
    real(H_FullFK_reflect),imag(H_FullFK_reflect), ...
    real(H_FullFK_total),imag(H_FullFK_total), ...
    'VariableNames',{'frequency_hz','H_direct_real','H_direct_imag', ...
    'H_BIE_reflect_real','H_BIE_reflect_imag', ...
    'H_BIE_total_real','H_BIE_total_imag', ...
    'H_PE_reflect_real','H_PE_reflect_imag', ...
    'H_PE_total_real','H_PE_total_imag', ...
    'H_FullFK_reflect_real','H_FullFK_reflect_imag', ...
    'H_FullFK_total_real','H_FullFK_total_imag'});
layers=table(string(ids(:)),node_count,real(U),imag(U), ...
    abs(U-ref)/abs(ref),linear_residual,offgrid_residual, ...
    'VariableNames',{'job_id','node_count','native_real','native_imag', ...
    'difference_from_main_relative','linear_residual','offgrid_residual'});
audit=struct('status','AUDITED', 'frequency_hz',6000, ...
    'amplitude_m',.01,'receiver_x_m',0,'receiver_z_m',3, ...
    'reference_sensitivity_relative',ref_sensitivity, ...
    'reference_gate_1e_4_pass',ref_gate, ...
    'pe_model_relative',pe_model_relative, ...
    'fk_model_relative',fk_model_relative, ...
    'pe_empirical_resolution',pe_resolution, ...
    'fk_empirical_resolution',fk_resolution, ...
    'pe_difference_over_5x_resolution',pe_resolved, ...
    'fk_difference_over_5x_resolution',fk_resolved, ...
    'same_source_native_unit','unit-source response, exp(-i omega t)', ...
    'scope','one weak sinusoid, P22, 6 kHz only; not S5/CIR');
mkdir(output_dir);
save(fullfile(output_dir,'independent_audit.mat'),'audit','layers', ...
    'response','U','ref','weak','pe');
writetable(layers,fullfile(output_dir,'bie_layers.csv'));
writetable(response,fullfile(output_dir,'p22_one_frequency_response.csv'));
fid=fopen(fullfile(output_dir,'independent_audit.json'),'w');
assert(fid>0); guard=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(audit,PrettyPrint=true));
disp(audit);
end

function u=local_fk400(path)
s=load(path,'fk400'); u=s.fk400.receiver_field;
end
