function receipt = validate_pe_screen_p22_common_window(run_id,parent_run_id,refined_run_id)
%VALIDATE_PE_SCREEN_P22_COMMON_WINDOW Compare PE grids on one 64 ms window.
arguments
    run_id (1,:) char
    parent_run_id (1,:) char
    refined_run_id (1,:) char
end
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
outdir=fullfile(root,'results','validation','pe_screen_p22_common_window',run_id);
assert(~isfolder(outdir) && ~isfile(outdir),'Run ID already exists');
p=load(fullfile(root,'results','validation','pe_screen_p22_comm', ...
    parent_run_id,'pe_screen_p22_broadband.mat'));
q=load(fullfile(root,'results','validation','pe_screen_p22_aliasing', ...
    refined_run_id,'pe_screen_p22_257.mat'));
assert(isequal(q.f257(1:2:end),p.f129));
assert(isequal(p.f129(1:2:end),p.f65));
assert(isequal(q.H_total(1:2:end,:),p.H_total));
tau0=97/1500; tau_reflect=6/1500;
H65=complex(zeros(257,2)); H129=H65;
for j=1:2
    H65(:,j)=local_predict(p.f65,p.H_direct(1:2:end,j), ...
        p.H_reflect(1:2:end,j),q.f257,tau_reflect);
    H129(:,j)=local_predict(p.f129,p.H_direct(:,j), ...
        p.H_reflect(:,j),q.f257,tau_reflect);
end
h65=ifft(H65(1:256,:),[],1);
h129=ifft(H129(1:256,:),[],1);
h257=ifft(q.H_total(1:256,:),[],1);
frequency_65_129=zeros(1,2); frequency_65_257=frequency_65_129;
frequency_129_257=frequency_65_129;
cir_65_129=frequency_65_129; cir_65_257=frequency_65_129;
cir_129_257=frequency_65_129;
late_energy_16_32=frequency_65_129;
outside_signed_window=frequency_65_129;
fft_error=frequency_65_129;
signed_t_ms=(-128:127)'*.25;
signed_window=signed_t_ms>=-4 & signed_t_ms<12;
for j=1:2
    frequency_65_129(j)=norm(H65(1:256,j)-H129(1:256,j))/norm(H129(1:256,j));
    frequency_65_257(j)=norm(H65(1:256,j)-q.H_total(1:256,j))/norm(q.H_total(1:256,j));
    frequency_129_257(j)=norm(H129(1:256,j)-q.H_total(1:256,j))/norm(q.H_total(1:256,j));
    cir_65_129(j)=norm(h65(:,j)-h129(:,j))/norm(h129(:,j));
    cir_65_257(j)=norm(h65(:,j)-h257(:,j))/norm(h257(:,j));
    cir_129_257(j)=norm(h129(:,j)-h257(:,j))/norm(h257(:,j));
    late_energy_16_32(j)=sum(abs(h257(65:128,j)).^2)/sum(abs(h257(:,j)).^2);
    hs=fftshift(h257(:,j));
    outside_signed_window(j)=sum(abs(hs(~signed_window)).^2)/sum(abs(hs).^2);
    fft_error(j)=norm(fft(h257(:,j))-q.H_total(1:256,j))/norm(q.H_total(1:256,j));
end
gates=struct('source_and_grid_identity',isequal(q.H_total(1:2:end,:),p.H_total), ...
    'frequency_65_129',max(frequency_65_129)<=1e-3, ...
    'independent_frequency_65_257',max(frequency_65_257)<=1e-3, ...
    'independent_frequency_129_257',max(frequency_129_257)<=1e-3, ...
    'common_window_cir_65_129',max(cir_65_129)<=1e-3, ...
    'independent_common_window_cir_65_257',max(cir_65_257)<=1e-3, ...
    'independent_common_window_cir_129_257',max(cir_129_257)<=1e-3, ...
    'late_energy_16_32ms',max(late_energy_16_32)<=1e-3, ...
    'outside_signed_window_energy',max(outside_signed_window)<=1e-3, ...
    'fft_roundtrip',max(fft_error)<=1e-10);
failed=sum(~cell2mat(struct2cell(gates)));
status='PE_SCREEN_COMMON_WINDOW_CIR_GATE_FAILED';
if failed==0, status='PE_SCREEN_COMMON_WINDOW_CIR_GATE_PASS'; end
receipt=struct('status',status,'matlab_version',version, ...
    'source','frozen Gaussian N984 sigma0.3m', ...
    'surface','flat and C2 weak sine A0.01m K0.1radpm', ...
    'receiver','P22 x0m z3m','time_origin_s',tau0, ...
    'reflection_relative_delay_s',tau_reflect, ...
    'common_frequency_count',257,'common_fft_bins',256, ...
    'common_time_window_s',.064,'delay_spacing_s',.00025, ...
    'signed_support_ms',[-4,12], ...
    'interpolation','linear complex envelopes after 4 ms reflection dephasing', ...
    'frequency_65_129_relative',frequency_65_129, ...
    'frequency_65_257_relative',frequency_65_257, ...
    'frequency_129_257_relative',frequency_129_257, ...
    'cir_65_129_relative',cir_65_129, ...
    'cir_65_257_relative',cir_65_257, ...
    'cir_129_257_relative',cir_129_257, ...
    'late_energy_16_32ms',late_energy_16_32, ...
    'outside_signed_window_energy',outside_signed_window, ...
    'fft_roundtrip_relative',fft_error, ...
    'original_raw_65_129_cir_relative',p.receipt.cir_refinement_relative, ...
    'original_raw_gate_pass',max(p.receipt.cir_refinement_relative)<=1e-3, ...
    'failed_check_count',failed,'gates',gates, ...
    'new_acoustic_solver_calls',0,'bie_calls',0,'fullfk_calls',0, ...
    'three_dimensional_calls',0);
mkdir(outdir);
save(fullfile(outdir,'common_window_cir.mat'),'receipt','H65','H129', ...
    'h65','h129','h257','signed_t_ms','-v7.3');
hs65=fftshift(h65,1); hs129=fftshift(h129,1); hs257=fftshift(h257,1);
t=table(repmat(signed_t_ms,2,1),repelem(["flat";"weak_sine"],256), ...
    real(hs65(:)),imag(hs65(:)), ...
    real(hs129(:)),imag(hs129(:)), ...
    real(hs257(:)),imag(hs257(:)), ...
    'VariableNames',{'delay_ms','surface','h65_real','h65_imag', ...
    'h129_real','h129_imag','h257_real','h257_imag'});
writetable(t,fullfile(outdir,'common_window_cir.csv'));
fid=fopen(fullfile(outdir,'receipt.json'),'w'); assert(fid>0);
cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(receipt,PrettyPrint=true));
disp(receipt);
end

function H=local_predict(f,hd,hr,target_f,tau_reflect)
envelope=hr(:).*exp(1i*2*pi*f(:)*tau_reflect);
H=interp1(f,hd,target_f,'linear')+ ...
    interp1(f,envelope,target_f,'linear').* ...
    exp(-1i*2*pi*target_f(:)*tau_reflect);
end
