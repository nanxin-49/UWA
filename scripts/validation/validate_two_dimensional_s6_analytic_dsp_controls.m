function receipt = validate_two_dimensional_s6_analytic_dsp_controls(output_dir)
%VALIDATE_TWO_DIMENSIONAL_S6_ANALYTIC_DSP_CONTROLS QPSK software controls only.
arguments
    output_dir (1,:) char
end
assert(~isfolder(output_dir) && ~isfile(output_dir), ...
    'Use a fresh result directory.');

cfg = struct('M',4,'bits_seed',61029,'noise_seed',62029, ...
    'noiseless_bit_count',20000,'awgn_bit_count',100000, ...
    'frame_bits',1000,'EbN0_dB',6,'symbol_rate_hz',1000, ...
    'tap_energy_ratio',1,'circular_peak_align',false, ...
    'h_taps',[1;0.2i], ...
    'scope','analytic discrete DSP only; no physical two-dimensional CIR');

[h_bb,tap_meta] = build_communication_taps_vertical( ...
    struct('h_t',cfg.h_taps),struct('symbol_rate_hz',cfg.symbol_rate_hz, ...
    'tap_energy_ratio',cfg.tap_energy_ratio, ...
    'circular_peak_align',cfg.circular_peak_align));
tap_error = norm(h_bb-cfg.h_taps)/norm(cfg.h_taps);
fft_error = norm(fft(h_bb)-ifftshift(tap_meta.H_baseband))/ ...
    norm(tap_meta.H_baseband);

% Exact carrier-centered 64-bin path: no interpolation or time shift needed.
f_axis_hz = 4000+(0:63)'*62.5;
H_f = exp(-1i*2*pi*f_axis_hz*0.001);
[h_frequency_bb,frequency_meta] = build_communication_taps_vertical( ...
    struct('H_f',H_f,'f_axis_hz',f_axis_hz, ...
    'phase_reference','direct_dsp'), ...
    struct('symbol_rate_hz',4000,'n_fft',64,'f_ref_hz',6000, ...
    'tap_energy_ratio',1,'circular_peak_align',false));
frequency_grid_error = max(abs(frequency_meta.f_bb_axis_hz-(f_axis_hz-6000)));
frequency_input_error = max(abs(frequency_meta.H_baseband-H_f));
frequency_fft_error = max(abs(fftshift(fft(frequency_meta.h_full))-H_f));
frequency_peak_error = abs(frequency_meta.raw_circular_peak_index-5);

rng(cfg.bits_seed,'twister');
bits_noiseless = randi([0,1],cfg.noiseless_bit_count,1);
[tx_noiseless,bits_noiseless] = modem_psk('modulate',bits_noiseless,cfg.M);
rx_noiseless_full = conv(tx_noiseless,h_bb);
rx_noiseless = rx_noiseless_full(1:numel(tx_noiseless));
eq_noiseless = filter(1,h_bb,rx_noiseless);
bits_noiseless_hat = modem_psk('demodulate',eq_noiseless,cfg.M);
noiseless_bit_errors = sum(bits_noiseless_hat~=bits_noiseless);
noiseless_frame_errors = sum(any(reshape( ...
    bits_noiseless_hat~=bits_noiseless,cfg.frame_bits,[]),1));
equalizer_relative_error = norm(eq_noiseless-tx_noiseless)/norm(tx_noiseless);

rng(cfg.bits_seed+1,'twister');
bits_awgn = randi([0,1],cfg.awgn_bit_count,1);
[tx_awgn,~] = modem_psk('modulate',local_gray_to_natural(bits_awgn),cfg.M);
noise_cfg = struct('enable_noise',true,'model','awgn', ...
    'ebn0_db',cfg.EbN0_dB,'bits_per_symbol',2,'seed',cfg.noise_seed);
[rx_awgn,noise,noise_meta] = noise_inject_vertical(tx_awgn,noise_cfg,tx_awgn);
bits_awgn_hat = local_natural_to_gray( ...
    modem_psk('demodulate',rx_awgn,cfg.M));
awgn_bit_errors = sum(bits_awgn_hat~=bits_awgn);
awgn_frame_errors = sum(any(reshape( ...
    bits_awgn_hat~=bits_awgn,cfg.frame_bits,[]),1));
awgn_ber = awgn_bit_errors/cfg.awgn_bit_count;
awgn_per = awgn_frame_errors/(cfg.awgn_bit_count/cfg.frame_bits);
awgn_evm_rms = sqrt(mean(abs(rx_awgn-tx_awgn).^2)/mean(abs(tx_awgn).^2));

% Explicit Gray mapping makes the two AWGN bit decisions independent.
ebn0_linear = 10^(cfg.EbN0_dB/10);
q = 0.5*erfc(sqrt(ebn0_linear));
predicted_ber = q;
prediction_count_95 = [local_binom_quantile(0.025,cfg.awgn_bit_count,predicted_ber), ...
    local_binom_quantile(0.975,cfg.awgn_bit_count,predicted_ber)];

gates = struct('tap_exact',tap_error<=1e-12, ...
    'fft_roundtrip',fft_error<=1e-12, ...
    'frequency_grid_and_carrier',frequency_grid_error==0 && ...
        frequency_input_error<=1e-12 && frequency_fft_error<=1e-12 && ...
        frequency_peak_error==0 && frequency_meta.circular_shift_samples==0, ...
    'noiseless_equalizer',equalizer_relative_error<=1e-12, ...
    'noiseless_zero_errors',noiseless_bit_errors==0 && noiseless_frame_errors==0, ...
    'awgn_binomial95',awgn_bit_errors>=prediction_count_95(1) && ...
    awgn_bit_errors<=prediction_count_95(2));
failed_check_count=sum(~cell2mat(struct2cell(gates)));
if failed_check_count==0
    status='ANALYTIC_DSP_QPSK_CONTROLS_PASS';
else
    status='ANALYTIC_DSP_QPSK_CONTROLS_FAIL';
end
receipt = struct('status',status,'matlab_version',version, ...
    'acoustic_solver_calls',0,'tap_relative_error',tap_error, ...
    'fft_roundtrip_relative_error',fft_error, ...
    'frequency_grid_error_hz',frequency_grid_error, ...
    'frequency_input_max_abs_error',frequency_input_error, ...
    'frequency_fft_max_abs_error',frequency_fft_error, ...
    'frequency_peak_index_error',frequency_peak_error, ...
    'equalizer_relative_error',equalizer_relative_error, ...
    'noiseless_bit_errors',noiseless_bit_errors, ...
    'noiseless_frame_errors',noiseless_frame_errors, ...
    'noiseless_bit_count',cfg.noiseless_bit_count, ...
    'awgn_bit_errors',awgn_bit_errors,'awgn_frame_errors',awgn_frame_errors, ...
    'awgn_bit_count',cfg.awgn_bit_count,'awgn_ber',awgn_ber, ...
    'awgn_per',awgn_per,'awgn_evm_rms',awgn_evm_rms, ...
    'gray_qpsk_predicted_ber',predicted_ber, ...
    'awgn_bit_error_prediction_count_95',prediction_count_95, ...
    'failed_check_count',failed_check_count,'gates',gates, ...
    'scope',cfg.scope);

mkdir(output_dir);
save(fullfile(output_dir,'analytic_dsp_controls.mat'),'cfg','receipt', ...
    'h_bb','tap_meta','f_axis_hz','H_f','h_frequency_bb','frequency_meta', ...
    'bits_noiseless','bits_noiseless_hat', ...
    'bits_awgn','bits_awgn_hat','tx_awgn','rx_awgn','noise','noise_meta');
summary = table(cfg.noiseless_bit_count,noiseless_bit_errors, ...
    noiseless_frame_errors,cfg.awgn_bit_count,awgn_bit_errors, ...
    awgn_frame_errors,awgn_ber,awgn_per,awgn_evm_rms,predicted_ber, ...
    prediction_count_95(1),prediction_count_95(2), ...
    'VariableNames',{'noiseless_bit_count','noiseless_bit_errors', ...
    'noiseless_frame_errors','awgn_bit_count','awgn_bit_errors', ...
    'awgn_frame_errors','awgn_ber','awgn_per','awgn_evm_rms', ...
    'predicted_ber','prediction_errors_low95','prediction_errors_high95'});
writetable(summary,fullfile(output_dir,'analytic_dsp_metrics.csv'));
fid=fopen(fullfile(output_dir,'receipt.json'),'w');
assert(fid>0,'Cannot write receipt.json.');
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(receipt,PrettyPrint=true));
disp(receipt);
if failed_check_count>0
    error('Analytic DSP controls failed; the result directory retains the evidence.');
end
end

function bits_natural = local_gray_to_natural(bits_gray)
bits_natural=bits_gray;
bits_natural(2:2:end)=xor(bits_gray(1:2:end),bits_gray(2:2:end));
end

function bits_gray = local_natural_to_gray(bits_natural)
bits_gray=bits_natural;
bits_gray(2:2:end)=xor(bits_natural(1:2:end),bits_natural(2:2:end));
end

function k = local_binom_quantile(probability,n,p)
lo=0; hi=n;
while lo<hi
    mid=floor((lo+hi)/2);
    if mid==n
        cdf=1;
    else
        cdf=betainc(1-p,n-mid,mid+1);
    end
    if cdf>=probability
        hi=mid;
    else
        lo=mid+1;
    end
end
k=lo;
end
