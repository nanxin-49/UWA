function receipt=check_deepsea3d_ubuntu_compatibility()
%CHECK_DEEPSEA3D_UBUNTU_COMPATIBILITY One frozen 6 kHz reference diagnostic.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
out=fullfile(root,'results','validation','deepsea3d_5k7k_20261026');
if ~isfolder(out),mkdir(out);end
file=fullfile(out,'compatibility_6000.mat');
assert(~isfile(file),'deepsea3d57:Exists','Compatibility diagnostic is single use.');
a=load(fullfile(root,'results','validation','deepsea3d_g1_azimuth','azimuth.mat'),'state');
b=load(fullfile(root,'results','validation','deepsea_dual_broadband_decision_20261015', ...
    'locked_candidate_and_gate.mat'),'decision','Q','predictions');
cfg=a.state.cfg;
assert(cfg.frequency_hz==6000 && isequal(double(cfg.tx_m),[0 150.5 1500]) && ...
    isequal(double(cfg.rx_m),[0 0 5]) && cfg.c0_mps==1500);
assert(isequal(cfg.profile.amplitudes_m,[.05 .025]) && ...
    isequal(cfg.profile.wavevectors_radpm,[.4 0;.2 .6]) && ...
    isequal(cfg.profile.phases_rad,[.2 .7]) && ...
    cfg.profile.plateau_m==8 && cfg.profile.support_m==12);
assert(isequal(b.decision.locked_new_frequencies_hz,[5000 7000]));
assert(all([b.predictions.predicted_not_observed]));
old=a.state.runs(a.state.reference_index).result;
v=a.state.runs(a.state.reference_index).settings;
assert(isequal(v,[32 .0625 20]));
opts=struct('domain_halfwidth_m',v(1),'spacing_m',v(2), ...
    'order',v(3),'residual_order',40,'offgrid',true);
tic_run=tic;
new=deepsea3d_dirichlet_fe(cfg,opts);
bg=deepsea3d_flat(cfg,0);
k=2*pi*cfg.frequency_hz/cfg.c0_mps;
Ld=norm(cfg.rx_m-cfg.tx_m);
image=cfg.tx_m;image(3)=-image(3);
Lr=norm(cfg.rx_m-image);
analytic_D=exp(1i*k*Ld)/(4*pi*Ld);
analytic_R0=-exp(1i*k*Lr)/(4*pi*Lr);
receipt=struct('release',version,'frequency_hz',6000,'configuration',v, ...
    'native_convention','exp(-i omega t), exp(i k R)/(4 pi R)', ...
    'direct_error',abs(bg.direct_native-analytic_D)/abs(analytic_D), ...
    'flat_reflect_error',abs(bg.reflect_native-analytic_R0)/abs(analytic_R0), ...
    'reflect_cross_platform_relative',abs(new.reflect_native-old.reflect_native)/abs(old.reflect_native), ...
    'delta_cross_platform_relative',abs(new.rough_correction-old.rough_correction)/abs(old.rough_correction), ...
    'boundary_relative',new.boundary_residual_relative, ...
    'halfgrid_relative',new.offgrid_boundary_residual_relative, ...
    'old_boundary_relative',old.boundary_residual_relative, ...
    'old_halfgrid_relative',old.offgrid_boundary_residual_relative, ...
    'elapsed_s',toc(tic_run),'old_reflect_native',old.reflect_native, ...
    'new_reflect_native',new.reflect_native);
save(file,'receipt','new','old','cfg','b','-v7');
disp(receipt);
end
