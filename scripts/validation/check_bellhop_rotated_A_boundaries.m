function receipt=check_bellhop_rotated_A_boundaries(run_dir)
%CHECK_BELLHOP_ROTATED_A_BOUNDARIES Saved finite-order field, no new solve.
start=tic; out=fullfile(run_dir,'boundary_audit01'); assert(~isfolder(out)); mkdir(out);
s=load(fullfile(run_dir,'assembly','result.mat'),'total','direct','envelope','plan','surface_family','bottom_family');
z=s.plan.depths_m(:); x=s.plan.x_m(:).'; it=find(z==0); ib=find(z==5000); valid=~s.plan.source_singularity_mask;
top=max(abs(s.total(it,:))./s.envelope(it,:));
mirror=s.total(:,end:-1:1); error=abs(s.total-mirror)./s.envelope; error(~valid)=NaN;
family_error=max(abs(s.direct(valid)+s.surface_family(valid)+s.bottom_family(valid)-s.total(valid))./s.envelope(valid));
receipt=struct('status','SAVED_BOUNDARY_CHECK','elapsed_s',toc(start),'failed_checks',double(top>.001), ...
    'top_pressure_release_max_over_envelope',top,'top_original_tolerance',.001, ...
    'left_right_symmetry_max_over_envelope',max(error,[],'all','omitnan'), ...
    'family_sum_association_max_over_envelope',family_error, ...
    'true_source_mask_count',nnz(s.plan.source_singularity_mask),'near_bottom_spacing_m',max(diff(z(z>=4900))), ...
    'bottom_pressure_finite',all(isfinite(s.total(ib,:))),'bottom_operator_status','Native lossy-fluid Reflect2D preserved; finite-aperture fluid DtN/independent FFP comparison not performed in A-only stage', ...
    'source_model','Omnidirectional3D point; 10kHz,5000m,source4950m; bottom assumptions unchanged');
fid=fopen(fullfile(out,'checkpoint.json'),'w','n','UTF-8'); fprintf(fid,'%s',jsonencode(receipt,PrettyPrint=true)); fclose(fid); disp(jsonencode(receipt));
end