function decision=preflight_deepsea_dual_broadband()
%PREFLIGHT_DEEPSEA_DUAL_BROADBAND Lock candidate and assess physical RAM.
% No solver invocation. A negative resource gate ends expansion for this Goal.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
outdir=fullfile(root,'results','validation','deepsea_dual_broadband_decision_20261015');
file=fullfile(outdir,'stage_gate.json');assert(~isfile(file),'dualDecision:Exists','No gate reroll.');
a=load(fullfile(outdir,'saved_evidence.mat'),'output','raw');
cfg=a.raw(2).cfg;eta=a.output.geometry.surface_height_at_flat_specular_m;
train=[4000;6000;8000];Q=zeros(3,1);Q0=Q;
for j=1:3
    cfg.frequency_hz=train(j);b=deepsea3d_flat(cfg,eta);b0=deepsea3d_flat(cfg,0);
    Q(j)=a.raw(j).reference.reflect_native/b.reflect_native;
    Q0(j)=a.raw(j).reference.reflect_native/b0.reflect_native;
end
predictions=struct([]);
for f=[5000 7000]
    cfg.frequency_hz=f;b=deepsea3d_flat(cfg,eta);b0=deepsea3d_flat(cfg,0);
    R=interp1(train,Q,f,'linear')*b.reflect_native;
    control=interp1(train,Q0,f,'linear')*b0.reflect_native;
    row=struct('frequency_hz',f,'reflect_native_real',real(R),'reflect_native_imag',imag(R), ...
        'delta_native_real',real(R-b0.reflect_native),'delta_native_imag',imag(R-b0.reflect_native), ...
        'total_native_real',real(R+b0.direct_native),'total_native_imag',imag(R+b0.direct_native), ...
        'zero_height_control_real',real(control),'zero_height_control_imag',imag(control), ...
        'flat_cancellation',(abs(b0.direct_native)+abs(b0.reflect_native))/abs(b0.total_native), ...
        'predicted_not_observed',true);
    if isempty(predictions),predictions=row;else,predictions(end+1)=row;end %#ok<AGROW>
end
[m,s]=memory;proc=System.Diagnostics.Process.GetCurrentProcess;proc.Refresh();
available=s.PhysicalMemory.Available/2^20;
forcing_arrays=(8+8+16+16)*21*1024^2/2^20;
estimate=forcing_arrays+512;
memory_pass=estimate<=.7*available;
decision=struct('time_information_gate','CONDITIONAL_PASS_FOR_TWO_POINT_TEST_ONLY', ...
    'candidate','native_reflection / analytic_plane_at_fixed_surface_height; complex linear on 4/6/8kHz', ...
    'locked_new_frequencies_hz',[5000 7000],'training_frequencies_hz',train, ...
    'locked_predictions',predictions,'memory_gate_pass',memory_pass, ...
    'physical_available_MiB',available,'physical_total_MiB',s.PhysicalMemory.Total/2^20, ...
    'reserve_fraction',.30,'reserve_MiB',.30*available,'allowed_increment_MiB',.70*available, ...
    'estimated_forcing_arrays_MiB',forcing_arrays,'temporary_and_FFT_allowance_MiB',512, ...
    'estimated_extra_working_set_MiB',estimate,'required_available_MiB',estimate/.7, ...
    'process_working_set_MiB',double(proc.WorkingSet64)/2^20, ...
    'process_private_MATLAB_MiB',m.MemUsedMATLAB/2^20, ...
    'process_lifetime_peak_MiB',double(proc.PeakWorkingSet64)/2^20, ...
    'memory_scope','conservative named-array planning estimate and point snapshots; not measured task peak', ...
    'kernel_cap_s',600,'single_frequency_cap_s',300,'new_physical_frequencies',0, ...
    'new_physical_kernel_wall_s',0,'G1_target_PM','OPEN','WP2_formal',false, ...
    'utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd HH:mm:ss XXX')));
if memory_pass
    decision.expansion_decision='ELIGIBLE_FOR_DECLARED_TWO_POINTS';
    decision.reason='Time/information and conservative preflight memory gates passed; no solve performed by this entrypoint.';
else
    decision.expansion_decision='STOP_RESOURCE_GATE_NO_NEW_PHYSICS';
    decision.reason='Full reference sequence cannot retain 30 percent available physical RAM under the declared working-set estimate. Do not run cheaper partial prechecks or reroll this gate.';
end
save(fullfile(outdir,'locked_candidate_and_gate.mat'),'decision','Q','Q0','predictions','-v7');
fid=fopen(file,'w');assert(fid>=0);clean=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(decision,PrettyPrint=true));
disp(decision);
end
