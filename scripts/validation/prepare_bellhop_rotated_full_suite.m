function receipt = prepare_bellhop_rotated_full_suite(metadata_file,executable,output_dir)
%PREPARE_BELLHOP_ROTATED_FULL_SUITE Freeze exact-grid plans, no solver launch.
arguments
    metadata_file (1,:) char
    executable (1,:) char
    output_dir (1,:) char
end
assert(~isfolder(output_dir)); mkdir(output_dir); t=tic;
m=load(metadata_file,'reference_metadata'); reference=m.reference_metadata;
assert(strcmpi(black_file_hash(reference.source_mat),'8e123af0beff9904289a5419fdb82f74473beda075792b7b2f9819bd133ce3be'));
project=setup_vertical_project(); root=project.project_root;
base=make_munk_5000m_ffp_config();
fields={'frequency_hz','source_depth_m','water_depth_m','bottom_cp_mps','bottom_rho_gcm3','bottom_atten_db_wavelength','water_rho_gcm3'};
for j=1:numel(fields), assert(isequal(base.(fields{j}),reference.cfg.(fields{j})),'Frozen physical contract mismatch.'); end
assert(isequal(base.munk_parameters,reference.cfg.munk_parameters));
labels={'A_Q125_h1_B401','B_Q625_h1_B401','C_Q625_h05_B401','D_Q625_h05_B801'};
spacing=[1.25 .625 .625 .625]; steps=[1 1 .5 .5]; rb=[401 401 401 801]; db=[2001 2001 2001 4001];
paths=cell(1,4); hashes=cell(1,4); job_counts=zeros(1,4);
for k=1:4
    plan=make_bellhop_rotated_field_plan(reference.depth_m(:).',reference.range_m(:).', ...
        Q_spacing_m=spacing(k),step_m=steps(k),reflection_beams=rb(k),direct_beams=db(k),max_order=16);
    assert(isequal(size(plan.source_singularity_mask),[10981 201]) && nnz(plan.source_singularity_mask)==1);
    paths{k}=fullfile(output_dir,[labels{k} '.mat']); save(paths{k},'plan','-v7.3');
    hashes{k}=black_file_hash(paths{k}); job_counts(k)=numel(plan.jobs);
end
code={ 'scripts/validation/run_bellhop_rotated_field_suite.m', ...
    'scripts/validation/run_bellhop_rotated_field_assembly.m', ...
    'scripts/validation/audit_bellhop_rotated_field_assembly.m', ...
    'scripts/validation/support/assess_bellhop_rotated_field_change.m', ...
    'scripts/validation/support/make_bellhop_rotated_field_plan.m', ...
    'scripts/validation/support/make_bellhop_rotated_direct_field_config.m', ...
    'scripts/validation/support/make_bellhop_rotated_multifield_config.m', ...
    'scripts/validation/support/run_bellhop_rotated_field_component.m', ...
    'scripts/validation/support/run_bellhop_rotated_local_case.m', ...
    'scripts/validation/support/write_bellhop_rotated_multifield_q.m', ...
    'scripts/validation/support/write_bellhop_rotated_munk_q.m', ...
    'scripts/validation/support/write_bellhop_rotated_horizontal_q.m', ...
    'scripts/validation/support/write_bellhop_rotated_field_options.m', ...
    'scripts/validation/support/read_bellhop_rotated_field.m', ...
    'scripts/validation/support/make_bellhop_rotated_munk_config.m', ...
    'scripts/validation/support/make_munk_5000m_ffp_config.m', ...
    'scripts/validation/support/munk_profile_sound_speed.m'};
versions=struct('path',{},'sha256',{});
for k=1:numel(code)
    path=fullfile(root,code{k}); versions(k)=struct('path',path,'sha256',black_file_hash(path));
end
suite=struct('status','PREPARED_NOT_AUTHORIZED','labels',{labels}, ...
    'plan_files',{paths},'plan_sha256',{hashes},'code_versions',versions, ...
    'executable_sha256',black_file_hash(executable),'control_labels',{{'Q_1p25_to_p625','h_1_to_p5','beams_double'}}, ...
    'reference_metadata_file',metadata_file,'reference_metadata_sha256',black_file_hash(metadata_file), ...
    'max_order',16,'depth_count',10981,'x_count',201,'job_counts',job_counts, ...
    'proposed_budget',struct('max_wall_s',3600,'max_job_s',120, ...
        'minimum_available_bytes',1.5*2^30,'minimum_runtime_available_bytes',256*2^20, ...
        'minimum_free_disk_bytes',20*2^30,'max_output_bytes',15*2^30, ...
        'allow_task_termination',true,'remote',false,'parallel_workers',0), ...
    'scope','Four exact original-FFP grids, streaming finite reflection order; independent FFP and final figures still require postchecks');
file=fullfile(output_dir,'suite.mat'); save(file,'suite');
receipt=rmfield(suite,{'code_versions','plan_files'}); receipt.suite_file=file; receipt.suite_sha256=black_file_hash(file);
receipt.elapsed_s=toc(t); receipt.result_dir=output_dir;
write(fullfile(output_dir,'checkpoint.json'),jsonencode(receipt,PrettyPrint=true));
write(fullfile(output_dir,'code_versions_sha256.json'),jsonencode(versions,PrettyPrint=true)); disp(jsonencode(receipt));
end
function write(path,content)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); cleaner=onCleanup(@()fclose(fid)); fprintf(fid,'%s',content);
end