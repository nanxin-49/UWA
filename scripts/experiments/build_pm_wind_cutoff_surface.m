function data = build_pm_wind_cutoff_surface(anchor, seed, U_PM, N, sample_count)
%BUILD_PM_WIND_CUTOFF_SURFACE Isolated K0 research generator; no acoustics.
% Stored Fourier values follow the R1/R2 depth convention z_s; eta=-z_s.
arguments
    anchor table
    seed (1,1) double {mustBeMember(seed,[260001 260002 260003])}
    U_PM (1,1) double {mustBeMember(U_PM,[5 6 8])}
    N (1,1) double {mustBeMember(N,[7 12 19 32 40])}
    sample_count (1,1) double {mustBeInteger,mustBePositive} = 8192
end
assert(mod(sample_count,2)==0 && sample_count>=256);
L=160; dk=2*pi/L; k=(1:40)'*dk;
Sk6=.0081./(2*k.^3).*exp(-.74*9.81^2./(6^4*k.^2));
assert(height(anchor)==12 && all(isfinite(table2array(anchor)),'all'));
assert(max(abs(anchor.k_rad_per_m-k(1:12)))<1e-14);
assert(max(abs(anchor.Sk_m3./Sk6(1:12)-1))<1e-11);
% Recover and verify original draw ordering: 12 a draws, then 12 b draws.
legacy=RandStream('mt19937ar','Seed',seed);
za=anchor.cos_coeff_m./sqrt(anchor.Sk_m3*dk);
zb=anchor.sin_coeff_m./sqrt(anchor.Sk_m3*dk);
recovery_error=max(abs([za-randn(legacy,12,1);zb-randn(legacy,12,1)]));
assert(recovery_error<1e-11,'Legacy Gaussian recovery failed; new family required');
% Freeze extension length at 28; drawing N-dependent lengths would move b.
extension_seed=seed+1000000;
ext=RandStream('mt19937ar','Seed',extension_seed);
za=[za;randn(ext,28,1)]; zb=[zb;randn(ext,28,1)];
A=.74*9.81^2/U_PM^4;
Sk=.0081./(2*k.^3).*exp(-A./k.^2);
a=sqrt(Sk*dk).*za; b=sqrt(Sk*dk).*zb;
if U_PM==6
    % The historical U=6 first twelve coefficients stay exactly unchanged.
    a(1:12)=anchor.cos_coeff_m; b(1:12)=anchor.sin_coeff_m;
end
k=k(1:N); Sk=Sk(1:N); a=a(1:N); b=b(1:N);
coefficients=table((1:N)',k,Sk,a,b,za(1:N),zb(1:N),'VariableNames', ...
    {'mode','k_rad_per_m','Sk_m3','cos_depth_coeff_m','sin_depth_coeff_m','gaussian_cos','gaussian_sin'});
x=(-sample_count/2:sample_count/2-1)'*(L/sample_count);
phase=x*k.';
z=cos(phase)*a+sin(phase)*b;
zp=-sin(phase)*(k.*a)+cos(phase)*(k.*b);
zpp=-cos(phase)*(k.^2.*a)-sin(phase)*(k.^2.*b);
chi=double(abs(x)<=42); cp=zeros(size(x)); cpp=cp;
mid=abs(x)>42 & abs(x)<50; t=(abs(x(mid))-42)/8;
chi(mid)=1-10*t.^3+15*t.^4-6*t.^5;
cp(mid)=(-30*t.^2+60*t.^3-30*t.^4).*sign(x(mid))/8;
cpp(mid)=(-60*t+180*t.^2-120*t.^3)/64;
eta=-z; ep=-zp; epp=-zpp;
emb=eta.*chi; embp=ep.*chi+eta.*cp; embpp=epp.*chi+2*ep.*cp+eta.*cpp;
samples=table(x,eta,ep,epp,emb,embp,embpp, ...
    'VariableNames',{'x_m','raw_elevation_m','raw_slope','raw_second_per_m', ...
    'embedded_elevation_m','embedded_slope','embedded_second_per_m'});
raw_power=abs(fft(eta)/sample_count).^2;
embedded_power=abs(fft(emb)/sample_count).^2;
weight=2*ones(sample_count/2+1,1); weight([1 end])=1;
raw_power=raw_power(1:sample_count/2+1).*weight;
embedded_power=embedded_power(1:sample_count/2+1).*weight;
spectra=table((0:sample_count/2)'*dk,raw_power,embedded_power, ...
    (embedded_power-raw_power)/dk, ...
    'VariableNames',{'k_rad_per_m','raw_bin_power_m2','embedded_bin_power_m2','PSD_difference_m3'});
variance_inf=.0081/(4*A); cdf=exp(-A/k(end)^2);
metrics=struct('seed',seed,'U_PM_mps',U_PM,'N',N,'L_m',L,'Kmax_rad_per_m',k(end), ...
    'sample_count',sample_count,'dx_m',L/sample_count,'Knyquist_rad_per_m',pi*sample_count/L, ...
    'Kpeak_rad_per_m',sqrt(2*A/3),'variance_infinite_m2',variance_inf, ...
    'continuous_coverage_0_Kmax',cdf,'variance_above_Kmax_m2',variance_inf*(1-cdf), ...
    'variance_below_fundamental_m2',variance_inf*exp(-A/dk^2), ...
    'continuous_coverage_Kmin_Kmax',cdf-exp(-A/dk^2), ...
    'discrete_expected_variance_m2',sum(Sk)*dk,'discrete_expected_coverage',sum(Sk)*dk/variance_inf, ...
    'raw_rms_height_m',sqrt(mean(eta.^2)),'raw_mean_height_m',mean(eta), ...
    'raw_min_elevation_m',min(eta),'raw_max_elevation_m',max(eta), ...
    'raw_rms_slope',sqrt(mean(ep.^2)),'raw_rms_second_per_m',sqrt(mean(epp.^2)), ...
    'raw_max_abs_slope',max(abs(ep)),'raw_max_abs_second_per_m',max(abs(epp)), ...
    'raw_rms_geometric_curvature_per_m',sqrt(mean((epp./(1+ep.^2).^1.5).^2)), ...
    'embedded_rms_height_m',sqrt(mean(emb.^2)),'embedded_mean_height_m',mean(emb), ...
    'embedded_min_elevation_m',min(emb),'embedded_max_elevation_m',max(emb), ...
    'embedded_rms_slope',sqrt(mean(embp.^2)),'embedded_rms_second_per_m',sqrt(mean(embpp.^2)), ...
    'embedded_max_abs_slope',max(abs(embp)), ...
    'embedded_max_abs_second_per_m',max(abs(embpp)), ...
    'embedded_rms_geometric_curvature_per_m',sqrt(mean((embpp./(1+embp.^2).^1.5).^2)), ...
    'embedded_power_above_Kmax_m2',sum(embedded_power(N+2:end)), ...
    'embedding_spectral_L1_power_change_m2',sum(abs(embedded_power-raw_power)), ...
    'embedding_spatial_L2_relative',norm(emb-eta)/norm(eta), ...
    'gaussian_recovery_max_error',recovery_error);
data=struct('coefficients',coefficients,'samples',samples,'spectra',spectra,'metrics',metrics, ...
    'family','legacy12_gaussian_extension_v1','extension_seed',extension_seed, ...
    'extension_draw_order','28 cosine then 28 sine; modes 13:40', ...
    'wind_definition','U_PM; measurement height and averaging duration unknown', ...
    'normalization','none; full-period RMS, no mean removal', ...
    'sign_convention','coefficients are R1/R2 physical depth z_s; elevation eta=-z_s');
end
