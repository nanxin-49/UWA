function data = d0_incident_diagnostics(x_m,p_f,px_f,pz_f,source,cfg)
%D0_INCIDENT_DIAGNOSTICS Research-only field, phase and window diagnostics.
x_m=x_m(:); p_f=p_f(:); px_f=px_f(:); pz_f=pz_f(:);
k=2*pi*source.frequency_hz/source.c_mps;
[~,center]=min(abs(x_m)); assert(x_m(center)==0);
mask=abs(p_f)>=cfg.gates.phase_mask_fraction*max(abs(p_f));
kx=imag(px_f./p_f); kz=imag(pz_f./p_f);
phase=unwrap(angle(p_f)); phase=phase-phase(center); phase(~mask)=NaN;
kx(~mask)=NaN; kz(~mask)=NaN;
curvature=gradient(kx,x_m); curvature([1 end])=NaN;
rmsPa=sqrt(mean(abs(p_f).^2));
data=struct('x_m',x_m,'p_f',p_f,'px_f',px_f,'pz_f',pz_f, ...
    'center_normalized_f',p_f/p_f(center),'rms_normalized_f',p_f/rmsPa, ...
    'relative_phase_rad',phase,'phase_mask',mask,'local_kx_rad_per_m',kx, ...
    'local_kz_rad_per_m',kz,'phase_curvature_rad_per_m2',curvature, ...
    'geometric_angle_deg',atan2d(x_m,source.z_source_m), ...
    'local_angle_deg',atan2d(kx,-kz),'source',source);
data.points=table(x_m,real(p_f),imag(p_f),abs(p_f),real(px_f),imag(px_f), ...
    real(pz_f),imag(pz_f),real(data.center_normalized_f),imag(data.center_normalized_f), ...
    real(data.rms_normalized_f),imag(data.rms_normalized_f),phase,mask,kx,kz,curvature, ...
    data.geometric_angle_deg,data.local_angle_deg,'VariableNames', ...
    {'x_m','p_real_Pa','p_imag_Pa','p_peak_Pa','px_real_Pa_per_m','px_imag_Pa_per_m', ...
    'pz_real_Pa_per_m','pz_imag_Pa_per_m','center_norm_real','center_norm_imag', ...
    'rms_norm_real','rms_norm_imag','relative_phase_rad','phase_valid', ...
    'phase_kx_rad_per_m','phase_kz_rad_per_m','phase_curvature_rad_per_m2', ...
    'geometric_angle_deg','local_phase_angle_deg'});
% FFT excludes the duplicated right endpoint. Convention F(kx)=int p exp(-i kx x) dx.
data.window_spectra=cell(4,1); jj=0;
for halfwidth=[200 220]
    ix=x_m>=-halfwidth & x_m<halfwidth; xx=x_m(ix); pp=p_f(ix); n=numel(xx);
    dx=xx(2)-xx(1); q=(-floor(n/2):ceil(n/2)-1)'*2*pi/(n*dx);
    for taper=0:1
        jj=jj+1; window=ones(n,1);
        if taper, window=.5*(1+cos(pi*xx/halfwidth)); end % deterministic Hann
        F=dx*fftshift(fft(pp.*window)).*exp(-1i*q*xx(1));
        valid=abs(F)>=cfg.gates.spectrum_phase_mask_fraction*max(abs(F));
        ph=angle(F); ph(~valid)=NaN;
        propagated=abs(q)<k; evband=abs(q)>k;
        E=sum(abs(F).^2);
        data.window_spectra{jj}=struct('halfwidth_m',halfwidth,'hann',logical(taper), ...
            'kx_rad_per_m',q,'spectrum_f',F,'phase_rad',ph, ...
            'phase_valid',valid,'propagating_band',propagated,'outside_band',evband, ...
            'outside_band_window_power_fraction',sum(abs(F(evband)).^2)/E, ...
            'parseval_relative',abs(sum(abs(pp.*window).^2)*dx-E/(n*dx))/ ...
                (sum(abs(pp.*window).^2)*dx), ...
            'fft_inverse_relative',norm(ifft(ifftshift(F.*exp(1i*q*xx(1))))/dx-pp.*window)/norm(pp.*window));
    end
end
% Full-line continuous Weyl density. Grazing endpoints are explicitly omitted.
theta=linspace(-pi/2+1e-4,pi/2-1e-4,4097)'; q=k*sin(theta); qz=k*cos(theta);
A=source.rho_kgpm3*2*pi*source.frequency_hz*source.v0_mps*source.total_width_m;
amp=local_sinc(q*source.total_width_m/2);
F=A*amp.*exp(1i*qz*source.z_source_m)./qz;
tau=linspace(.01,45,1025)'; alpha=tau/source.z_source_m;
qe=sqrt(k^2+alpha.^2); Fe=A*local_sinc(qe*source.total_width_m/2).*exp(-tau)./(1i*alpha);
data.continuous_spectrum=struct('prop_kx_rad_per_m',q,'prop_qz_rad_per_m',qz, ...
    'prop_density_f',F,'prop_phase_unwrapped_rad',qz*source.z_source_m, ...
    'ev_kx_positive_rad_per_m',qe,'ev_alpha_per_m',alpha,'ev_density_f',Fe, ...
    'ev_kx_negative_rad_per_m',-qe,'grazing_endpoints','singular, omitted; quadrature uses transformed coordinates', ...
    'units','Pa m; inverse integral dkx/(2 pi)', ...
    'warning','FFT outside-band power is window leakage plus field content, not physical evanescent energy');
% No fitted phase/amplitude: tangent plane uses the actual anchor and local phase direction.
rows=[];
for anchor=[0 100 200]
    [~,ia]=min(abs(x_m-anchor));
    for width=[1 5 10 40]
        ix=abs(x_m-anchor)<=width/2;
        pw=p_f(ia)*exp(1i*kx(ia)*(x_m(ix)-anchor));
        delta=angle(p_f(ix).*conj(pw));
        delta_unwrapped=phase(ix)-phase(ia)-kx(ia)*(x_m(ix)-anchor);
        denom=norm(p_f(ix));
        amplitude_error=norm(abs(p_f(ix))-abs(pw))/denom;
        phase_error=sqrt(sum(4*abs(p_f(ix)).*abs(pw).*sin(delta/2).^2))/denom;
        rows=[rows;anchor width norm(p_f(ix)-pw)/denom max(abs(delta)) ...
            max(abs(delta_unwrapped)) amplitude_error phase_error]; %#ok<AGROW>
    end
end
data.plane_wave= array2table(rows,'VariableNames', ...
    {'anchor_x_m','patch_width_m','complex_relative_L2','max_wrapped_phase_error_rad', ...
    'max_unwrapped_phase_error_rad','amplitude_component_relative','phase_component_relative'});
data.metrics=struct('depth_m',source.z_source_m,'pressure_max_Pa',max(abs(p_f)), ...
    'pressure_center_real_Pa',real(p_f(center)),'pressure_center_imag_Pa',imag(p_f(center)), ...
    'pressure_rms_Pa',rmsPa,'pressure_min_Pa',min(abs(p_f)), ...
    'px_rms_Pa_per_m',sqrt(mean(abs(px_f).^2)),'pz_rms_Pa_per_m',sqrt(mean(abs(pz_f).^2)), ...
    'center_phase_curvature_rad_per_m2',curvature(center), ...
    'geometric_angle_200_deg',atan2d(200,source.z_source_m), ...
    'geometric_range_200_m',hypot(200,source.z_source_m), ...
    'geometric_range_220_m',hypot(220,source.z_source_m), ...
    'geometric_excess_range_200_m',hypot(200,source.z_source_m)-source.z_source_m, ...
    'axis_phase_front_radius_m',k/curvature(center), ...
    'local_direction_difference_max_deg',max(abs(data.local_angle_deg-data.geometric_angle_deg)), ...
    'phase_valid_count',sum(mask),'plane_wave_full_line_relative',norm(p_f-p_f(center))/norm(p_f), ...
    'phase_curvature_paraxial_rad_per_m2',k/source.z_source_m);
end
function y=local_sinc(t)
y=ones(size(t)); ii=t~=0; y(ii)=sin(t(ii))./t(ii);
end
