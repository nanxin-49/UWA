function output=analyze_deepsea_dual_broadband_decision()
%ANALYZE_DEEPSEA_DUAL_BROADBAND_DECISION Read frozen physical data; no solves.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
outdir=fullfile(root,'results','validation','deepsea_dual_broadband_decision_20261015');
assert(isfolder(outdir));
outfile=fullfile(outdir,'saved_evidence.mat');
assert(~isfile(outfile),'dualDecision:Exists','Refuse to overwrite evidence.');
timer=tic;
inputdir=fullfile(root,'results','validation','deepsea3d_g1_frequency');
a=load(fullfile(inputdir,'frequency.mat'),'state');s=a.state;
cases={s.cases(1),s.baseline6,s.cases(2)};
metrics=struct([]);raw=struct([]);costs=struct([]);
for j=1:3
    c=cases{j};cfg=c.cfg;f=cfg.frequency_hz;
    restored=cfg;restored.frequency_hz=6000;assert(isequal(restored,s.baseline6.cfg));
    assert(c.reference_ready && c.G1_status=="CONDITIONAL_G1_PASS");
    bg=deepsea3d_flat(cfg,0);r=c.runs(c.reference_index).result;fk=c.fk(2);
    assert(abs(r.reflect_native-bg.reflect_native-r.rough_correction)<1e-16);
    assert(abs(r.total_native-bg.total_native-r.rough_correction)<1e-16);
    refs=[];
    for ix=[c.coarse_index,c.fine_index,c.reference_index]
        rr=c.runs(ix).result;
        part=rr.partials([rr.order-4,rr.order-2,rr.order]);
        refs=[refs;part(:)]; %#ok<AGROW>
    end
    fv=c.fk;
    if isfield(c,'fk_refinement') && ~isempty(fieldnames(c.fk_refinement))
        fv=[c.fk([1 2 4 5]),c.fk_refinement];
    end
    ref_sensitivity=max(abs(refs-r.rough_correction));
    fk_sensitivity=max(abs([fv.rough_correction]-fk.rough_correction));
    model_difference=abs(fk.rough_correction-r.rough_correction);
    q=r.reflect_native/bg.reflect_native;t=r.total_native/bg.total_native;
    row=struct('frequency_hz',f,'flat_reflect_abs',abs(bg.reflect_native), ...
        'rough_reflect_abs',abs(r.reflect_native),'flat_total_abs',abs(bg.total_native), ...
        'rough_total_abs',abs(r.total_native),'rough_increment_abs',abs(r.rough_correction), ...
        'reflect_complex_change',abs(q-1),'reflect_amplitude_ratio',abs(q), ...
        'reflect_amplitude_change_percent',100*(abs(q)-1),'reflect_power_change_dB',20*log10(abs(q)), ...
        'reflect_phase_change_wrapped_rad',angle(q),'total_complex_change',abs(t-1), ...
        'total_amplitude_ratio',abs(t),'total_power_change_dB',20*log10(abs(t)), ...
        'total_phase_change_wrapped_rad',angle(t), ...
        'ref_empirical_sensitivity_abs',ref_sensitivity,'fk_numerical_sensitivity_abs',fk_sensitivity, ...
        'fk_model_difference_abs',model_difference, ...
        'effect_over_ref_sensitivity',abs(r.rough_correction)/ref_sensitivity, ...
        'effect_over_fk_numerical',abs(r.rough_correction)/fk_sensitivity, ...
        'effect_over_model_difference',abs(r.rough_correction)/model_difference, ...
        'reference_sensitivity_over_reflect',ref_sensitivity/abs(r.reflect_native), ...
        'reference_sensitivity_over_increment',ref_sensitivity/abs(r.rough_correction), ...
        'reference_sensitivity_over_total',ref_sensitivity/abs(r.total_native), ...
        'fk_reflected_model_error',model_difference/abs(r.reflect_native), ...
        'fk_increment_model_error',model_difference/abs(r.rough_correction), ...
        'flat_cancellation',(abs(bg.direct_native)+abs(bg.reflect_native))/abs(bg.total_native), ...
        'rough_cancellation',(abs(bg.direct_native)+abs(r.reflect_native))/abs(r.total_native));
    % Amplitude ranges from saved order/grid/domain variants, not error bars.
    rv=bg.reflect_native+refs;tv=bg.total_native+refs;
    row.reflect_amplitude_ratio_min=min(abs(rv/bg.reflect_native));
    row.reflect_amplitude_ratio_max=max(abs(rv/bg.reflect_native));
    row.total_amplitude_ratio_min=min(abs(tv/bg.total_native));
    row.total_amplitude_ratio_max=max(abs(tv/bg.total_native));
    item=struct('cfg',cfg,'flat',bg,'reference',r,'fullfk',fk, ...
        'reference_increment_variants',refs,'fullfk_increment_variants',[fv.rough_correction], ...
        'reference_guards',c.reference_guards,'fk_guards',c.fk_guards);
    if isempty(metrics),metrics=row;raw=item;else,metrics(end+1)=row;raw(end+1)=item;end %#ok<AGROW>
    if f==6000
        cp=fullfile(root,'results','validation','deepsea3d_g1_azimuth','cost_summary.json');
    else
        cp=fullfile(inputdir,sprintf('f%d',f),'cost_summary.json');
    end
    cc=jsondecode(fileread(cp));
    cr=struct('frequency_hz',f,'FE_wall_s',cc.FE_wall_s,'M32_wall_s',0, ...
        'replay_wall_s',cc.observer_wall_s,'FK_wall_s',cc.FK_wall_s, ...
        'kernel_wall_s',cc.new_wall_s,'diagnostic_wall_s',0, ...
        'memory_spectral_max_MiB',max(arrayfun(@(x)x.result.stored_spectral_MiB,c.runs)));
    if isfield(cc,'M32_wall_s'),cr.M32_wall_s=cc.M32_wall_s;cr.diagnostic_wall_s=cc.evaluation_diagnostic_wall_s;end
    if isempty(costs),costs=cr;else,costs(end+1)=cr;end %#ok<AGROW>
end
% Algebraic geometry only; does not solve any new physical frequency.
cfg=s.baseline6.cfg;bg=deepsea3d_flat(cfg,0);
spec=cfg.rx_m(1:2)+(cfg.tx_m(1:2)-cfg.rx_m(1:2))*cfg.rx_m(3)/(cfg.rx_m(3)+cfg.tx_m(3));
eta=deepsea3d_surface(spec(1)-cfg.center_m(1),spec(2)-cfg.center_m(2),cfg.profile);
heightbg=deepsea3d_flat(cfg,eta);
geometry=struct('flat_specular_xy_m',spec,'surface_height_at_flat_specular_m',eta, ...
    'flat_excess_delay_s',bg.excess_delay_s,'flat_fringe_period_hz',1/bg.excess_delay_s, ...
    'height_plane_reflection_length_m',heightbg.Lr_m, ...
    'height_phase_correction_s',(heightbg.Lr_m-bg.Lr_m)/cfg.c0_mps, ...
    'flat_minimum_frequencies_hz',(ceil(4000*bg.excess_delay_s):floor(8000*bg.excess_delay_s))/bg.excess_delay_s, ...
    'raw_reflected_linear_df_for_1e3_hz',acos(1-1e-3)/(pi*bg.excess_delay_s));
% Three-point exploratory curvature. Existing 6kHz helps screen hypotheses,
% so it is not a held-out certification of a subsequently selected model.
frequencies=[4000;6000;8000];reference=reshape([raw.reference],[],1);
R=reshape([reference.reflect_native],[],1);Q=R;Q0=R;
for j=1:3
    cfg.frequency_hz=frequencies(j);b=deepsea3d_flat(cfg,eta);b0=deepsea3d_flat(cfg,0);
    Q(j)=R(j)/b.reflect_native;Q0(j)=R(j)/b0.reflect_native;
end
screening=struct('training_frequencies_hz',[4000 8000],'exploratory_frequency_hz',6000, ...
    'flat_phase_removed_midpoint_error',abs(mean(Q0([1 3]))-Q0(2))/abs(Q0(2)), ...
    'height_phase_removed_midpoint_error',abs(mean(Q([1 3]))-Q(2))/abs(Q(2)), ...
    'known_height_coefficient_real',real(Q),'known_height_coefficient_imag',imag(Q), ...
    'not_independent_model_selection_validation',true);
% Prospective costs: all endpoints plus one independent midpoint per interval.
% No choice is certified by this accounting; a second midpoint level is extra.
grids=struct([]);lo=min([costs.kernel_wall_s]);hi=max([costs.kernel_wall_s]);
for N=[9 17 33 65 129 257 513]
    M=2*N-1;new=M-3;
    gr=struct('source_points',N,'source_df_hz',4000/(N-1),'one_midpoint_total_points',M, ...
        'new_points_after_reusing_three',new,'training_only_new_low_h',(N-3)*lo/3600, ...
        'training_only_new_high_h',(N-3)*hi/3600,'with_midpoints_new_low_h',new*lo/3600, ...
        'with_midpoints_new_high_h',new*hi/3600, ...
        'planning_high_with_25pct_retry_20pct_overhead_h',new*hi*1.25*1.20/3600, ...
        'source_grid_DFT_window_ms',1000*(N-1)/4000, ...
        'raw_reflection_midpoint_error_flat',1-cos(pi*4000/(N-1)*bg.excess_delay_s));
    if isempty(grids),grids=gr;else,grids(end+1)=gr;end %#ok<AGROW>
end
% Reconcile independently saved CSV with MAT, without regenerating old outputs.
csv=readtable(fullfile(inputdir,'frequency_summary.csv'));
assert(max(abs(csv.reference_reflect_real-real(R)))<1e-16);
assert(max(abs(csv.reference_reflect_imag-imag(R)))<1e-16);
assert(max(abs(csv.reference_total_variant_change-[metrics.reference_sensitivity_over_total].'))<1e-12);
output=struct('metrics',metrics,'historical_costs',costs,'cost_candidates',grids, ...
    'geometry',geometry,'exploratory_screening',screening, ...
    'new_physical_solves',0,'certified_frequencies_hz',frequencies, ...
    'continuous_band_certified',false,'G1_target_PM','OPEN','WP2_formal',false, ...
    'sensitivity_scope','empirical saved order/grid/domain variations; not confidence interval or rigorous bound', ...
    'cost_scope','historical measured kernels extrapolated; retry and IO overhead are assumptions, not measured', ...
    'analysis_wall_s',toc(timer));
save(outfile,'output','raw','-v7');
writetable(struct2table(metrics),fullfile(outdir,'physical_effects.csv'));
writetable(struct2table(costs),fullfile(outdir,'historical_costs.csv'));
writetable(struct2table(grids),fullfile(outdir,'cost_candidates.csv'));
fid=fopen(fullfile(outdir,'saved_evidence.json'),'w');assert(fid>=0);clean=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(output,PrettyPrint=true));
disp(struct2table(metrics));disp(screening);disp(struct2table(grids));
end
