end

function local_validate_outputs(out_dir)
files = [arrayfun(@(ii)sprintf('%02d_',ii),1:13,'UniformOutput',false),{'14_'}];
listing = dir(out_dir);
for ii = 1:numel(files)
    hit = startsWith({listing.name},files{ii});
    if ~any(hit), error('Missing atlas output with prefix %s.',files{ii}); end
    sizes = [listing(hit).bytes];
    if isempty(sizes) || max(sizes)<1024, error('Atlas output %s is unexpectedly small.',files{ii}); end
end
end
