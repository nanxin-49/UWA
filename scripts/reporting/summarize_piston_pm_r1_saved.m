function summary=summarize_piston_pm_r1_saved(root)
%SUMMARIZE_PISTON_PM_R1_SAVED Additional spatial evidence; no new solve.
arguments
    root (1,:) char
end
t0=tic; out=fullfile(root,'saved_summary'); assert(~isfolder(out)); mkdir(out);
diary(fullfile(out,'diary.log')); guard=onCleanup(@()diary('off')); %#ok<NASGU>
q=load(fullfile(root,'common.mat')); a=load(fullfile(root,'comparison.mat'));
old=load(fullfile(root,'input','frozen_source.mat'),'src'); src=old.src;
assert(numel(src.coeff)==984 && src.z_tx_m==100);
xx=-192.1875/2+(0:983)'*(192.1875/984);
assert(max(abs(ifft(src.coeff(:))-exp(-.5*(xx/.3).^2)))<1e-12);
assert(all(q.x==sort(q.x)) && all(q.z==3));
summary=struct('status','STOPPED_BIE_REFERENCE_CONVERGENCE_UNRUN', ...
    'reference_qualified',a.reference_qualified,'receiver_count',411, ...
    'receiver_x_min_m',min(q.x),'receiver_x_max_m',max(q.x), ...
    'receiver_spacing_m',q.x(2)-q.x(1),'BIE_line_RMS_Pa',a.scale, ...
    'phase_mask_threshold_Pa',.01*a.scale,'phase_valid_points',nnz(a.mask), ...
    'BIE_rough_flat_relative_L2',a.rough_flat, ...
    'Gaussian_PS_BIE_relative_L2',a.gaussian.relative_L2_PS_FullFK(1), ...
    'Gaussian_FullFK_BIE_relative_L2',a.gaussian.relative_L2_PS_FullFK(2), ...
    'Gaussian_source','frozen N984 Fourier Gaussian sigma0.3m, period192.1875m, Tx100m; own normalization', ...
    'empirical_resolution','unknown because BIE grid/window/self-quadrature checks unrun; resolved=0 in provisional metric CSV does not establish numerical indistinguishability');
bins=[-Inf -20 0 20 Inf]; by_region=table; peaks=table; names=["PS" "FullFK"];
for j=1:2
    m=1; if j==2, m=3; end
    e=a.U(:,m)-a.U(:,2); sq=abs(e).^2; phase=angle(a.U(:,m).*conj(a.U(:,2)));
    amp=abs(a.U(:,m))-abs(a.U(:,2));
    [~,order]=sort(abs(e),'descend'); ii=order(1:20);
    peaks=[peaks;table(repmat(names(j),20,1),(1:20)',q.x(ii),abs(e(ii)), ...
        abs(e(ii))/a.scale,amp(ii),phase(ii),'VariableNames', ...
        {'method','rank','x_m','residual_abs_Pa','residual_over_BIE_RMS','amplitude_difference_Pa','phase_difference_rad'})]; %#ok<AGROW>
    for r=1:4
        mask=q.x>=bins(r) & q.x<bins(r+1);
        by_region=[by_region;table(names(j),r,bins(r),bins(r+1),nnz(mask),sum(sq(mask))/sum(sq), ...
            'VariableNames',{'method','region','left_x_m','right_x_m','points','squared_residual_energy_fraction'})]; %#ok<AGROW>
    end
    phase_term_sq=4*abs(a.U(:,m)).*abs(a.U(:,2)).*sin(phase/2).^2;
    assert(max(abs(sq-amp.^2-phase_term_sq))<1e-10);
    metrics=struct('complex_relative_L2',norm(e)/norm(a.U(:,2)), ...
        'amplitude_relative_L2',norm(amp)/norm(a.U(:,2)), ...
        'phase_term_relative_L2',sqrt(sum(phase_term_sq))/norm(a.U(:,2)), ...
        'phase_term_fraction_of_residual_energy',sum(phase_term_sq)/sum(sq), ...
        'maximum_abs_phase_difference_rad',max(abs(phase(a.mask))), ...
        'maximum_abs_amplitude_difference_Pa',max(abs(amp)), ...
        'peak_residual_Pa',abs(e(ii(1))),'peak_receiver_x_m',q.x(ii(1)));
    summary.(char(names(j)))=metrics;
end
writetable(by_region,fullfile(out,'spatial_error_energy.csv')); writetable(peaks,fullfile(out,'top_residual_receivers.csv'));
files={'run_piston_pm_r1_job','audit_piston_pm_r1','render_piston_pm_r1','summarize_piston_pm_r1_saved'};
analysis=struct; for j=1:numel(files), analysis.(files{j})=checkcode(which(files{j}),'-id'); end
save(fullfile(out,'summary.mat'),'summary','by_region','peaks','analysis','-v7');
summary.elapsed_s=toc(t0); fid=fopen(fullfile(out,'summary.json'),'w'); fprintf(fid,'%s',jsonencode(summary,PrettyPrint=true)); fclose(fid);
disp(jsonencode(summary));
end
