function receipt = render_bellhop_rotated_sparse_diagnostic(comparison_file,output_dir)
%RENDER_BELLHOP_ROTATED_SPARSE_DIAGNOSTIC Saved sample markers, never a TL map.
% This pilot atlas is deliberately labeled incomplete, separate from final
% full-grid Figure12(b) products. Raw complex arrays remain in the MAT copy.
arguments
    comparison_file (1,:) char
    output_dir (1,:) char
end
assert(~isfolder(output_dir)); [~,mem]=memory;
assert(mem.PhysicalMemory.Available>=512*2^20,'Saved-diagnostic render RAM gate.');
d=load(comparison_file); assert(strcmp(d.receipt.scope,'pilot') && numel(d.p_bellhop)<=10000);
mkdir(output_dir); t=tic; diary(fullfile(output_dir,'diary.log')); cleaner=onCleanup(@()diary('off'));
raw_file=fullfile(output_dir,'raw_comparison.mat'); copyfile(comparison_file,raw_file);
assert(strcmp(black_file_hash(comparison_file),black_file_hash(raw_file)));
fig=figure('Visible','off','Color','w','Position',[80 80 1450 700],'Tag','rotated_sparse_diag_owned');
tiles=tiledlayout(fig,1,2,'TileSpacing','compact','Padding','compact');
ax=nexttile(tiles); [X,Z]=meshgrid(d.x,d.z); use=~d.source_mask;
s=scatter(ax,X(use),Z(use),55,d.envelope_error(use),'filled','MarkerEdgeColor',[.2 .2 .2]);
s.Tag='sampled_envelope_error'; set(ax,'YDir','reverse','Color',[.95 .95 .95]);
xlim(ax,[-5.5 5.5]); ylim(ax,[-100 5100]); xlabel(ax,'physical x (m)'); ylabel(ax,'physical depth z (m)');
colormap(ax,parula(256)); clim(ax,[0 .04]); cb=colorbar(ax); cb.Label.String='|p_{Bellhop}-p_{FFP}| / component envelope';
title(ax,{'Saved sample points only','No interpolation; unequal physical axis scales'}); grid(ax,'on');
ax2=nexttile(tiles); axis(ax2,'off');
lines={sprintf('Pilot: reflection order N = %d; %d actual receiver points',d.receipt.reflection_order,nnz(use)), ...
    'Source: omnidirectional 3D point', ...
    'Phase bridge: fixed -conj(native); no fitted gain', ...
    'Water 5000 m; source 4950 m; 10 kHz', ...
    'Lossy fluid-bottom parameters are assumptions.', ...
    'Metrics: receiving-point L2, delta/E, phase', ...
    'A small global L2 does not qualify unsampled regions.', ...
    '', ...
    sprintf('Top residual / envelope: %.6g (criterion .001)',d.receipt.boundary.top_bellhop_max_envelope), ...
    sprintf('Near-bottom largest saved depth spacing: %.6g m',d.receipt.resolution.maximum_spacing_m), ...
    'Required .01 m near-bottom coverage: NOT MET', ...
    'Bottom derivative: NOT EVALUABLE here', ...
    '', ...
    'Full grids/convergence are outside this diagnostic.', ...
    'Final Fig.12(b) products remain outstanding.'};
text(ax2,.01,.98,lines,'Units','normalized','VerticalAlignment','top','Interpreter','none','FontSize',13);
title(tiles,sprintf('Sparse N=%d: truncation unqualified; full field unrun',d.receipt.reflection_order),'FontSize',17);
save_pair(fig,'F01_sparse_receivers_and_limits');
fig=figure('Visible','off','Color','w','Position',[80 80 1500 650],'Tag','rotated_sparse_diag_owned');
tiles=tiledlayout(fig,1,3,'TileSpacing','compact','Padding','compact');
j=find(d.x==0,1); assert(~isempty(j));
ax=nexttile(tiles); hold(ax,'on');
a=plot(ax,d.z,abs(d.p_bellhop(:,j)),'o','LineStyle','none','Color',[0 .35 .7],'DisplayName','rotated N=2'); a.Tag='axis_abs_bellhop';
a=plot(ax,d.z,abs(d.p_ffp(:,j)),'x','LineStyle','none','Color',[.8 .3 .05],'DisplayName','independent FFP'); a.Tag='axis_abs_ffp';
set(ax,'YScale','log'); grid(ax,'on'); xlabel(ax,'depth z (m)'); ylabel(ax,'|p| / 1m source reference');
xlim(ax,[0 5000]); title(ax,{'Actual axis samples','zero/NaN absent on log axis; raw values retained'}); legend(ax,'Location','best');
ax=nexttile(tiles); hold(ax,'on');
a=plot(ax,d.z,d.phase_difference(:,j),'o','LineStyle','none','Color',[0 .35 .7]); a.Tag='axis_phase_difference';
yline(ax,.05,'--','+.05 rad'); yline(ax,-.05,'--','-.05 rad'); grid(ax,'on');
xlim(ax,[0 5000]); ylim(ax,[-.055 .055]); xlabel(ax,'depth z (m)'); ylabel(ax,'arg(p_{Bellhop}/p_{FFP}) (rad)'); title(ax,{'Phase difference at saved points','only where both |p| >= .05 envelope'});
ax=nexttile(tiles); hold(ax,'on');
a=plot(ax,d.z,d.envelope_error(:,j),'s','LineStyle','none','Color',[.6 .2 .55]); a.Tag='axis_envelope_error';
yline(ax,.02,'--','.02 comparison criterion'); grid(ax,'on');
xlim(ax,[0 5000]); xlabel(ax,'depth z (m)'); ylabel(ax,'|delta p| / component envelope'); title(ax,{'Axis error and unresolved intervals','markers only; no connecting/interpolating across gaps'});
title(tiles,'Sparse axis comparison: untested intervals and high-order tail remain','FontSize',17);
save_pair(fig,'F02_sparse_axis_complex_comparison');
metrics=d.metrics; writetable(metrics,fullfile(output_dir,'reference_metrics.csv'));
rows='';
for k=1:height(metrics)
    rows=[rows sprintf('<tr><td>%s</td><td>%d</td><td>%.6g</td><td>%.6g</td><td>%.6g</td><td>%.6g</td><td>%d</td></tr>', ...
        metrics.region(k),metrics.points(k),metrics.complex_relative_L2(k),metrics.cell_weighted_complex_relative(k), ...
        metrics.max_envelope_error(k),metrics.max_phase_rad(k),metrics.sampled_criterion_met(k))]; %#ok<AGROW>
end
html=['<!doctype html><html lang="zh-CN"><meta charset="utf-8"><title>Bellhop稀疏诊断：完整场未执行</title>' ...
    '<style>body{font:16px/1.6 sans-serif;max-width:1400px;margin:30px auto;padding:0 20px;color:#17212b}img{max-width:100%;height:auto}' ...
    'table{border-collapse:collapse}th,td{padding:7px;border:1px solid #ccd3da}strong{color:#9b270f}</style>' ...
    sprintf('<h1>%d阶稀疏诊断：尚非完整场</h1><p><strong>本页为%d个接收点的先导。没有生成完整Fig.12(b)，也未取得反射阶数收敛。</strong></p>',d.receipt.reflection_order,numel(d.p_bellhop)) ...
    '<p>5000m水深、源4950m、10kHz；全向三维点源及示例有损流体底是假设。复声压不拟合增益/相位，不插值补点。</p>' ...
    '<h2>实际接收点与证据缺口</h2><img src="F01_sparse_receivers_and_limits.png" alt="仅显示实际稀疏接收点的误差颜色；海面残压和近底采样不满足完整场要求。">' ...
    '<p>色标0到.04仅用于逐点误差，超过色标值仍保存在原始MAT。本页不是相干TL连续场图。</p>' ...
    '<h2>中央轴线的实际复场对照</h2><img src="F02_sparse_axis_complex_comparison.png" alt="轴上幅度、相位差和包络归一误差的离散标记，不跨未采样区连线。">' ...
    '<h2>逐区域数值</h2><p>判据为工程诊断：复L2/逐点差除分量包络 .02，相位 .05rad；不是论文容差或物理资格。等权点范数与梯形单元加权采样范数均列出，未采样细条纹不在其覆盖范围。</p>' ...
    '<table><tr><th>区域</th><th>点数</th><th>等权复L2</th><th>单元加权复差</th><th>最大差/E</th><th>有效点最大相位(rad)</th><th>所测数值达门(0/1)</th></tr>' ...
    rows '</table><p>源奇点保留NaN；相位只在两方法幅度均达到.05E时显示；零压对数不显示。底部完整DtN闭合不能由有限±5m孔径独立恢复；稀疏点不够计算底部导数。</p>' ...
    '<h2>可复核文件</h2><p><a href="raw_comparison.mat">未裁剪复场及配置MAT</a> · <a href="reference_metrics.csv">分区CSV</a> · ' ...
    '<a href="F01_sparse_receivers_and_limits.fig">图1可编辑FIG</a> · <a href="F02_sparse_axis_complex_comparison.fig">图2可编辑FIG</a></p>' ...
    '<p>本页保留稀疏先导数据；完整网格及最终图件尚未执行，预算状态以当前授权回执为准。本页不替代最终交付。</p></html>'];
write(fullfile(output_dir,'index.html'),html);
receipt=struct('status','SPARSE_DIAGNOSTIC_RENDERED_NOT_FINAL_ATLAS','elapsed_s',toc(t), ...
    'source_comparison_sha256',black_file_hash(comparison_file),'output_dir',output_dir,'figure_count',2, ...
    'matlab_release',version,'exports',{{'PNG','editable FIG','raw MAT','CSV','offline HTML'}},'unrun_checks',{{'visual inspection','independent FIG/data/pixel audit'}});
write(fullfile(output_dir,'receipt.json'),jsonencode(receipt,PrettyPrint=true)); disp(jsonencode(receipt));
    function save_pair(f,stem)
        drawnow; savefig(f,fullfile(output_dir,[stem '.fig'])); exportgraphics(f,fullfile(output_dir,[stem '.png']),'Resolution',120); close(f);
    end
end
function write(path,content)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); cleaner=onCleanup(@()fclose(fid)); fprintf(fid,'%s',content);
end