    'frequency_correlation_mode', mode, ...
    'frequency_correlation_rho', rho, ...
    'random_spectrum_seed_base', seed_base, ...
    'random_spectrum_seed_innovation', seed_innovation, ...
    'random_spectrum_frequency_index', frequency_index, ...
    'random_spectrum_generation_rule', rule);
end

