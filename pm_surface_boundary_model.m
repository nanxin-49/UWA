function [surface_elevation, delta_phi, psi_ref, meta] = ...
    pm_surface_boundary_model(psi_inc, KX, KY, x, y, xw, yw, lambda0, pm_cfg)
%PM_SURFACE_BOUNDARY_MODEL
% PM rough-surface boundary model for spatial Kirchhoff and SSA kernels.

if nargin < 9 || isempty(pm_cfg)
    pm_cfg = struct();
end
if ~isfield(pm_cfg, 'U') || isempty(pm_cfg.U)
    pm_cfg.U = 5.0;
end
if ~isfield(pm_cfg, 'Hs_target') || isempty(pm_cfg.Hs_target)
    pm_cfg.Hs_target = 0.5;
end
if ~isfield(pm_cfg, 'roughness_scale_mode') || isempty(pm_cfg.roughness_scale_mode)
    pm_cfg.roughness_scale_mode = 'target_hs';
end
if ~isfield(pm_cfg, 'seed') || isempty(pm_cfg.seed)
    pm_cfg.seed = 12345;
end
if ~isfield(pm_cfg, 'show_figure') || isempty(pm_cfg.show_figure)
    pm_cfg.show_figure = true;
end
if ~isfield(pm_cfg, 'reflect_coeff') || isempty(pm_cfg.reflect_coeff)
    pm_cfg.reflect_coeff = -1;
end
if ~isfield(pm_cfg, 'phase_mode') || isempty(pm_cfg.phase_mode)
    pm_cfg.phase_mode = 'normal';
end
if ~isfield(pm_cfg, 'oblique_clip') || isempty(pm_cfg.oblique_clip)
    pm_cfg.oblique_clip = [0, 1];
end
if ~isfield(pm_cfg, 'tx_xyz') || isempty(pm_cfg.tx_xyz)
    pm_cfg.tx_xyz = [0, 0, NaN];
end
if ~isfield(pm_cfg, 'rx_xyz') || isempty(pm_cfg.rx_xyz)
    pm_cfg.rx_xyz = [0, 0, NaN];
end
if ~isfield(pm_cfg, 'z_surface') || isempty(pm_cfg.z_surface)
    pm_cfg.z_surface = 0;
end
if ~isfield(pm_cfg, 'boundary_model') || isempty(pm_cfg.boundary_model)
    pm_cfg.boundary_model = 'kirchhoff_spatial';
end
if ~isfield(pm_cfg, 'boundary_check_equivalence') || isempty(pm_cfg.boundary_check_equivalence)
    pm_cfg.boundary_check_equivalence = false;
end
if ~isfield(pm_cfg, 'boundary_debug') || isempty(pm_cfg.boundary_debug)
    pm_cfg.boundary_debug = false;
end
if ~isfield(pm_cfg, 'boundary_equivalence_tol') || isempty(pm_cfg.boundary_equivalence_tol)
    pm_cfg.boundary_equivalence_tol = 1e-10;
end
if ~isfield(pm_cfg, 'boundary_coupling_diagnostics') || isempty(pm_cfg.boundary_coupling_diagnostics)
    pm_cfg.boundary_coupling_diagnostics = false;
end
if ~isfield(pm_cfg, 'boundary_coupling_debug') || isempty(pm_cfg.boundary_coupling_debug)
    pm_cfg.boundary_coupling_debug = false;
end
if ~isfield(pm_cfg, 'boundary_redistribution_diagnostics') || isempty(pm_cfg.boundary_redistribution_diagnostics)
    pm_cfg.boundary_redistribution_diagnostics = false;
end
if ~isfield(pm_cfg, 'boundary_redistribution_debug') || isempty(pm_cfg.boundary_redistribution_debug)
    pm_cfg.boundary_redistribution_debug = false;
end
if ~isfield(pm_cfg, 'ssa_random_scatter') || isempty(pm_cfg.ssa_random_scatter)
    pm_cfg.ssa_random_scatter = true;
end
if ~isfield(pm_cfg, 'ssa_scatter_scale') || isempty(pm_cfg.ssa_scatter_scale)
    pm_cfg.ssa_scatter_scale = 1.0;
end
if ~isfield(pm_cfg, 'ssa_seed_offset') || isempty(pm_cfg.ssa_seed_offset)
    pm_cfg.ssa_seed_offset = 100000;
end
if ~isfield(pm_cfg, 'ssa_kernel_mode') || isempty(pm_cfg.ssa_kernel_mode)
    pm_cfg.ssa_kernel_mode = 'pm_convolution';
end
if ~isfield(pm_cfg, 'ssa_coherent_order') || isempty(pm_cfg.ssa_coherent_order)
    pm_cfg.ssa_coherent_order = 'ssa1';
end
if ~isfield(pm_cfg, 'ssa_frequency_correlation_mode') || isempty(pm_cfg.ssa_frequency_correlation_mode)
    pm_cfg.ssa_frequency_correlation_mode = 'independent';
end
if ~isfield(pm_cfg, 'ssa_frequency_correlation_rho') || isempty(pm_cfg.ssa_frequency_correlation_rho)
    pm_cfg.ssa_frequency_correlation_rho = 0.8;
end
if ~isfield(pm_cfg, 'ssa_geometry_source_id') || isempty(pm_cfg.ssa_geometry_source_id)
    pm_cfg.ssa_geometry_source_id = '';
end
if ~isfield(pm_cfg, 'ssa_kz_branch') || isempty(pm_cfg.ssa_kz_branch)
    pm_cfg.ssa_kz_branch = 'downward_positive_real';
end
if ~isfield(pm_cfg, 'ssa_conv_padding') || isempty(pm_cfg.ssa_conv_padding)
    pm_cfg.ssa_conv_padding = 'periodic';
end
if ~isfield(pm_cfg, 'kstat_random_scatter') || isempty(pm_cfg.kstat_random_scatter)
    pm_cfg.kstat_random_scatter = true;
end
if ~isfield(pm_cfg, 'kstat_seed_offset') || isempty(pm_cfg.kstat_seed_offset)
    pm_cfg.kstat_seed_offset = 200000;
end
if ~isfield(pm_cfg, 'kstat_conv_padding') || isempty(pm_cfg.kstat_conv_padding)
    pm_cfg.kstat_conv_padding = 'periodic';
end
if ~isfield(pm_cfg, 'kstat_trusted_angle_deg') || isempty(pm_cfg.kstat_trusted_angle_deg)
    pm_cfg.kstat_trusted_angle_deg = NaN;
end
if ~isfield(pm_cfg, 'frequency_index') || isempty(pm_cfg.frequency_index)
    pm_cfg.frequency_index = 1;
end

if ~(isscalar(pm_cfg.reflect_coeff) && isnumeric(pm_cfg.reflect_coeff) && isfinite(pm_cfg.reflect_coeff))
    error('pm_cfg.reflect_coeff must be a finite scalar (real or complex).');
end
if isstring(pm_cfg.phase_mode)
    pm_cfg.phase_mode = char(pm_cfg.phase_mode);
end
phase_mode = lower(pm_cfg.phase_mode);
if ~ischar(phase_mode) || (~strcmp(phase_mode, 'normal') && ~strcmp(phase_mode, 'oblique'))
    error('pm_cfg.phase_mode must be ''normal'' or ''oblique''.');
end
if ~(isnumeric(pm_cfg.oblique_clip) && numel(pm_cfg.oblique_clip) == 2 && all(isfinite(pm_cfg.oblique_clip(:))))
    error('pm_cfg.oblique_clip must be a finite 1x2 numeric range.');
end
clip_pair = sort(pm_cfg.oblique_clip(:).');
if clip_pair(1) < 0 || clip_pair(2) > 1
    error('pm_cfg.oblique_clip must stay within [0,1].');
end
if ~(isnumeric(pm_cfg.tx_xyz) && numel(pm_cfg.tx_xyz) == 3 && all(isfinite(pm_cfg.tx_xyz(:))))
    error('pm_cfg.tx_xyz must be a finite [x,y,z].');
end
if ~(isnumeric(pm_cfg.rx_xyz) && numel(pm_cfg.rx_xyz) == 3 && all(isfinite(pm_cfg.rx_xyz(:))))
    error('pm_cfg.rx_xyz must be a finite [x,y,z].');
end
boundary_model = local_normalize_choice(pm_cfg.boundary_model, 'pm_cfg.boundary_model');
if ~any(strcmp(boundary_model, {'kirchhoff_spatial', 'kirchhoff_kdomain', 'ssa_stat_kernel', 'kirchhoff_kstat'}))
    error('pm_cfg.boundary_model must be ''kirchhoff_spatial'', ''kirchhoff_kdomain'', ''ssa_stat_kernel'', or ''kirchhoff_kstat''.');
end
roughness_scale_mode = local_normalize_choice(pm_cfg.roughness_scale_mode, 'pm_cfg.roughness_scale_mode');
if ~any(strcmp(roughness_scale_mode, {'target_hs', 'raw_pm'}))
    error('pm_cfg.roughness_scale_mode must be ''target_hs'' or ''raw_pm''.');
end
if ~isscalar(pm_cfg.boundary_check_equivalence)
    error('pm_cfg.boundary_check_equivalence must be a scalar logical flag.');
end
boundary_check_equivalence = logical(pm_cfg.boundary_check_equivalence);
if ~isscalar(pm_cfg.boundary_debug)
    error('pm_cfg.boundary_debug must be a scalar logical flag.');
end
boundary_debug = logical(pm_cfg.boundary_debug);
if ~(isscalar(pm_cfg.boundary_equivalence_tol) && isnumeric(pm_cfg.boundary_equivalence_tol) && ...
     isfinite(pm_cfg.boundary_equivalence_tol) && pm_cfg.boundary_equivalence_tol > 0)
    error('pm_cfg.boundary_equivalence_tol must be a positive finite scalar.');
end
boundary_equivalence_tol = pm_cfg.boundary_equivalence_tol;
if ~isscalar(pm_cfg.boundary_coupling_diagnostics)
    error('pm_cfg.boundary_coupling_diagnostics must be a scalar logical flag.');
end
boundary_coupling_diagnostics = logical(pm_cfg.boundary_coupling_diagnostics);
if ~isscalar(pm_cfg.boundary_coupling_debug)
    error('pm_cfg.boundary_coupling_debug must be a scalar logical flag.');
end
boundary_coupling_debug = logical(pm_cfg.boundary_coupling_debug);
if ~isscalar(pm_cfg.boundary_redistribution_diagnostics)
    error('pm_cfg.boundary_redistribution_diagnostics must be a scalar logical flag.');
end
boundary_redistribution_diagnostics = logical(pm_cfg.boundary_redistribution_diagnostics);
if ~isscalar(pm_cfg.boundary_redistribution_debug)
    error('pm_cfg.boundary_redistribution_debug must be a scalar logical flag.');
end
boundary_redistribution_debug = logical(pm_cfg.boundary_redistribution_debug);
if ~isscalar(pm_cfg.ssa_random_scatter)
    error('pm_cfg.ssa_random_scatter must be a scalar logical flag.');
end
ssa_random_scatter = logical(pm_cfg.ssa_random_scatter);
if ~(isscalar(pm_cfg.ssa_scatter_scale) && isnumeric(pm_cfg.ssa_scatter_scale) && ...
     isfinite(pm_cfg.ssa_scatter_scale) && pm_cfg.ssa_scatter_scale >= 0)
    error('pm_cfg.ssa_scatter_scale must be a nonnegative finite scalar.');
end
ssa_scatter_scale = pm_cfg.ssa_scatter_scale;
ssa_seed_offset = local_force_int(pm_cfg.ssa_seed_offset, 'pm_cfg.ssa_seed_offset');
if ssa_seed_offset < 0
    error('pm_cfg.ssa_seed_offset must be nonnegative.');
end
ssa_kernel_mode = local_normalize_choice(pm_cfg.ssa_kernel_mode, 'pm_cfg.ssa_kernel_mode');
if ~any(strcmp(ssa_kernel_mode, {'pm_convolution', 'ssa1_geometry', 'ssa1_debug_dense'}))
    error('pm_cfg.ssa_kernel_mode must be ''pm_convolution'', ''ssa1_geometry'', or ''ssa1_debug_dense''.');
end
ssa_coherent_order = local_normalize_choice(pm_cfg.ssa_coherent_order, 'pm_cfg.ssa_coherent_order');
if ~any(strcmp(ssa_coherent_order, {'ssa1', 'ssa2_broschat_coherent'}))
    error('pm_cfg.ssa_coherent_order must be ''ssa1'' or ''ssa2_broschat_coherent''.');
end
ssa_frequency_correlation_mode = local_normalize_choice(pm_cfg.ssa_frequency_correlation_mode, 'pm_cfg.ssa_frequency_correlation_mode');
if ~any(strcmp(ssa_frequency_correlation_mode, {'independent', 'shared_seed_phase', 'ar1_frequency'}))
    error('pm_cfg.ssa_frequency_correlation_mode must be ''independent'', ''shared_seed_phase'', or ''ar1_frequency''.');
end
if ~(isscalar(pm_cfg.ssa_frequency_correlation_rho) && isnumeric(pm_cfg.ssa_frequency_correlation_rho) && ...
     isfinite(pm_cfg.ssa_frequency_correlation_rho) && pm_cfg.ssa_frequency_correlation_rho >= 0 && ...
     pm_cfg.ssa_frequency_correlation_rho < 1)
    error('pm_cfg.ssa_frequency_correlation_rho must satisfy 0 <= rho < 1.');
end
ssa_frequency_correlation_rho = pm_cfg.ssa_frequency_correlation_rho;
if isstring(pm_cfg.ssa_geometry_source_id)
    pm_cfg.ssa_geometry_source_id = char(pm_cfg.ssa_geometry_source_id);
end
if ~ischar(pm_cfg.ssa_geometry_source_id)
    error('pm_cfg.ssa_geometry_source_id must be a char vector or string scalar.');
end
ssa_geometry_source_id = pm_cfg.ssa_geometry_source_id;
ssa_kz_branch = local_normalize_choice(pm_cfg.ssa_kz_branch, 'pm_cfg.ssa_kz_branch');
if ~strcmp(ssa_kz_branch, 'downward_positive_real')
    error('pm_cfg.ssa_kz_branch currently supports only ''downward_positive_real''.');
end
ssa_conv_padding = local_normalize_choice(pm_cfg.ssa_conv_padding, 'pm_cfg.ssa_conv_padding');
if ~any(strcmp(ssa_conv_padding, {'periodic', 'zero_padded'}))
    error('pm_cfg.ssa_conv_padding must be ''periodic'' or ''zero_padded''.');
end
if ~isscalar(pm_cfg.kstat_random_scatter)
    error('pm_cfg.kstat_random_scatter must be a scalar logical flag.');
end
kstat_random_scatter = logical(pm_cfg.kstat_random_scatter);
kstat_seed_offset = local_force_int(pm_cfg.kstat_seed_offset, 'pm_cfg.kstat_seed_offset');
if kstat_seed_offset < 0
    error('pm_cfg.kstat_seed_offset must be nonnegative.');
end
kstat_conv_padding = local_normalize_choice(pm_cfg.kstat_conv_padding, 'pm_cfg.kstat_conv_padding');
if ~any(strcmp(kstat_conv_padding, {'periodic', 'zero_padded'}))
    error('pm_cfg.kstat_conv_padding must be ''periodic'' or ''zero_padded''.');
end
if ~(isscalar(pm_cfg.kstat_trusted_angle_deg) && isnumeric(pm_cfg.kstat_trusted_angle_deg) && ...
     (isnan(pm_cfg.kstat_trusted_angle_deg) || ...
      (isfinite(pm_cfg.kstat_trusted_angle_deg) && pm_cfg.kstat_trusted_angle_deg >= 0 && pm_cfg.kstat_trusted_angle_deg <= 90)))
    error('pm_cfg.kstat_trusted_angle_deg must be NaN or a finite scalar in [0,90].');
end
kstat_trusted_angle_deg = pm_cfg.kstat_trusted_angle_deg;
frequency_index = local_force_int(pm_cfg.frequency_index, 'pm_cfg.frequency_index');
if frequency_index < 1
    error('pm_cfg.frequency_index must be positive.');
end

% -----------------------------
% 1) PM spectrum and boundary phase geometry
% -----------------------------
pm_spectrum = local_pm_spectrum(KX, KY, xw, yw, pm_cfg.U);
U = pm_spectrum.U;          % m/s
g = pm_spectrum.g;          % m/s^2
alpha_PM = pm_spectrum.alpha_PM;
beta_PM = pm_spectrum.beta_PM;
K = pm_spectrum.K;
E1D = pm_spectrum.E1D;
Phi2D = pm_spectrum.Phi2D;
mask = pm_spectrum.mask;
dkx = pm_spectrum.dkx;
dky = pm_spectrum.dky;
Hs_target = pm_cfg.Hs_target; % m
if ~(isscalar(Hs_target) && isnumeric(Hs_target) && isfinite(Hs_target) && Hs_target >= 0)
    error('pm_cfg.Hs_target must be a nonnegative finite scalar.');
end
pm_variance_raw_discrete_m2 = sum(Phi2D(:)) * dkx * dky;
sigma_eta_raw_discrete_m = sqrt(max(pm_variance_raw_discrete_m2, 0));
Hs_raw_discrete_m = 4 * sigma_eta_raw_discrete_m;
pm_variance_raw_continuous_m2 = pm_variance_raw_discrete_m2 / (2*pi)^2;
sigma_eta_raw_continuous_m = sqrt(max(pm_variance_raw_continuous_m2, 0));
Hs_raw_continuous_m = 4 * sigma_eta_raw_continuous_m;
k0 = 2*pi / lambda0;
[X, Y] = meshgrid(x, y);
phase_factor = local_surface_phase_factor( ...
    phase_mode, X, Y, pm_cfg.tx_xyz, pm_cfg.rx_xyz, pm_cfg.z_surface, clip_pair);
kstat_disabled_roughness_mode = roughness_scale_mode;
ssa_meta = local_disabled_ssa_stat_kernel_meta(Hs_target, ssa_seed_offset, roughness_scale_mode);
kstat_meta = local_disabled_kirchhoff_kstat_meta(Hs_target, kstat_seed_offset, ...
    kstat_conv_padding, kstat_trusted_angle_deg, kstat_disabled_roughness_mode);
sigma_eta_raw_m = NaN;
Hs_raw_m = NaN;

% -----------------------------
% 2) Surface boundary operator
% -----------------------------
surface_realization_generated = any(strcmp(boundary_model, {'kirchhoff_spatial', 'kirchhoff_kdomain'}));
if surface_realization_generated
    A = sqrt(Phi2D .* dkx .* dky);
    rng(pm_cfg.seed, 'twister')
    N = (randn(size(K)) + 1i*randn(size(K))) / sqrt(2);
    Zk = A .* N;

    eta_raw = real(ifft2(Zk));
    eta_raw = eta_raw * numel(eta_raw); % compensate MATLAB ifft2 normalization
    eta_raw = sqrt(2) * eta_raw; % real part of unconstrained complex spectrum carries half the target variance

    % Calibrate to target Hs by default; raw_pm keeps the PM realization amplitude.
    Hs_raw = 4 * std(eta_raw(:));
    switch roughness_scale_mode
        case 'target_hs'
            if Hs_raw > 0
                scale_factor = Hs_target / Hs_raw;
            else
                scale_factor = 0;
            end
        case 'raw_pm'
            scale_factor = 1;
    end
    sigma_eta_raw_m = Hs_raw / 4;
    Hs_raw_m = Hs_raw;
    surface_elevation = eta_raw * scale_factor;
    Hs_scaled = 4 * std(surface_elevation(:));

    % Kirchhoff phase screen: delta_phi = k0*(cos_i+cos_r)*eta.
    % In normal incidence phase_factor=2, so delta_phi=2*k0*eta.
    delta_phi = k0 * surface_elevation .* phase_factor;
    G_xy = pm_cfg.reflect_coeff .* exp(1i * delta_phi);
    [coupling_diag, coupling_debug] = local_boundary_coupling_diagnostics( ...
        G_xy, KX, KY, boundary_coupling_diagnostics, boundary_coupling_debug);
    [psi_ref, boundary_meta] = local_apply_kirchhoff_boundary( ...
        psi_inc, G_xy, boundary_model, boundary_check_equivalence, ...
        boundary_debug, boundary_equivalence_tol);
    [redistribution_diag, redistribution_debug] = local_boundary_redistribution_diagnostics( ...
        psi_inc, psi_ref, pm_cfg.reflect_coeff .* psi_inc, KX, KY, k0, ...
        boundary_redistribution_diagnostics, boundary_redistribution_debug);
elseif strcmp(boundary_model, 'ssa_stat_kernel')
    surface_elevation = [];
    delta_phi = [];
    spectral_variance = sum(Phi2D(:)) * dkx * dky;
    sigma_eta_raw_m = sqrt(max(spectral_variance, 0));
    Hs_raw_m = 4 * sigma_eta_raw_m;
    Hs_raw = Hs_raw_m;
    switch roughness_scale_mode
        case 'target_hs'
            sigma_eta = Hs_target / 4;
            if spectral_variance > 0 && sigma_eta > 0
                scale_factor = sigma_eta / sqrt(spectral_variance);
            else
                scale_factor = 0;
            end
        case 'raw_pm'
            sigma_eta = sigma_eta_raw_m;
            scale_factor = 1;
    end
    Hs_scaled = 4 * sigma_eta;
    W_eta = Phi2D * scale_factor^2;

    seed_ssa = pm_cfg.seed + ssa_seed_offset + frequency_index - 1;
    [psi_ref, boundary_meta, ssa_meta] = local_apply_ssa_stat_kernel( ...
        psi_inc, W_eta, KX, KY, phase_factor, dkx, dky, k0, pm_cfg.reflect_coeff, ...
        ssa_scatter_scale, ssa_random_scatter, seed_ssa, ssa_seed_offset, ...
        Hs_target, sigma_eta, boundary_equivalence_tol, ssa_kernel_mode, ...
        ssa_coherent_order, ssa_frequency_correlation_mode, ...
        ssa_frequency_correlation_rho, frequency_index, ...
        ssa_geometry_source_id, ssa_kz_branch, ssa_conv_padding);
    coupling_diag = local_disabled_coupling_diagnostics();
    coupling_debug = struct();
    [redistribution_diag, redistribution_debug] = local_boundary_redistribution_diagnostics( ...
        psi_inc, psi_ref, ssa_meta.R_coh .* psi_inc, KX, KY, k0, ...
        boundary_redistribution_diagnostics, boundary_redistribution_debug);
else
    surface_elevation = [];
    delta_phi = [];
    spectral_variance = sum(Phi2D(:)) * dkx * dky;
    sigma_eta_raw_m = sqrt(max(spectral_variance, 0));
    Hs_raw_m = 4 * sigma_eta_raw_m;
    Hs_raw = Hs_raw_m;
    switch roughness_scale_mode
        case 'target_hs'
            sigma_eta_target = Hs_target / 4;
            spectral_variance_continuous = sum(Phi2D(:)) * dkx * dky / (2*pi)^2;
            if spectral_variance_continuous > 0 && sigma_eta_target > 0
                scale_factor = sigma_eta_target / sqrt(spectral_variance_continuous);
            else
                scale_factor = 0;
            end
        case 'raw_pm'
            sigma_eta_target = sigma_eta_raw_m;
            scale_factor = 2*pi;
    end
    Hs_scaled = 4 * sigma_eta_target;
    W_eta = Phi2D * scale_factor^2;

    seed_kstat = pm_cfg.seed + kstat_seed_offset + frequency_index - 1;
    [psi_ref, boundary_meta, kstat_meta] = local_apply_kirchhoff_kstat( ...
        psi_inc, W_eta, KX, KY, xw, yw, dkx, dky, k0, pm_cfg.reflect_coeff, ...
        kstat_random_scatter, seed_kstat, kstat_seed_offset, Hs_target, ...
        boundary_equivalence_tol, kstat_conv_padding, kstat_trusted_angle_deg, ...
        roughness_scale_mode, sigma_eta_raw_m, Hs_raw_m, scale_factor);
    coupling_diag = local_disabled_coupling_diagnostics();
    coupling_debug = struct();
    [redistribution_diag, redistribution_debug] = local_boundary_redistribution_diagnostics( ...
        psi_inc, psi_ref, kstat_meta.R_coh .* psi_inc, KX, KY, k0, ...
        boundary_redistribution_diagnostics, boundary_redistribution_debug);
end

% -----------------------------
% 3) Sanity-check visualization
% -----------------------------
if pm_cfg.show_figure
    figure(15); clf
    subplot(1,2,1)
    if surface_realization_generated
        surf(X, Y, surface_elevation, 'EdgeColor', 'none')
        view(40, 35)
        axis tight
        xlabel('x (m)')
        ylabel('y (m)')
        zlabel('\xi(x,y) (m)')
        title('PM rough sea surface elevation')
    else
        imagesc(fftshift(log10(max(W_eta, realmin))))
        axis xy tight
        xlabel('k_x index')
        ylabel('k_y index')
        title('log10 W_\eta(K_x,K_y), no surface realization')
    end
    colorbar

    subplot(1,2,2)
    imagesc(x, y, angle(psi_ref))
    axis xy tight
    xlabel('x (m)')
    ylabel('y (m)')
    title(sprintf('Phase of reflected field angle(\\psi_{ref}), mode=%s, boundary=%s', ...
        phase_mode, boundary_model))
    colorbar
end

E_from_Phi = zeros(size(K));
E_from_Phi(mask) = Phi2D(mask) .* 2*pi .* K(mask);
rel_err = abs(E_from_Phi(mask) - E1D(mask)) ./ max(abs(E1D(mask)), eps);

meta = struct();
meta.U = U;
meta.g = g;
meta.alpha_PM = alpha_PM;
meta.beta_PM = beta_PM;
meta.dkx = dkx;
meta.dky = dky;
meta.spectrum_definition = 'E1D(K)=alpha/(2K^3)exp(-beta g^2/(U^4 K^2)); Phi2D(Kx,Ky)=E1D(K)/(2*pi*K)';
meta.E1D = local_field_stats(E1D(mask));
meta.Phi2D = local_field_stats(Phi2D(mask));
meta.phi2d_transform_error = struct( ...
    'max_rel', max(rel_err(:), [], 'omitnan'), ...
    'mean_rel', mean(rel_err(:), 'omitnan'));
meta.Hs_target = Hs_target;
meta.Hs_target_m = Hs_target;
meta.roughness_scale_mode = roughness_scale_mode;
meta.sigma_eta_raw_m = sigma_eta_raw_m;
meta.Hs_raw_m = Hs_raw_m;
meta.pm_variance_raw_discrete_m2 = pm_variance_raw_discrete_m2;
meta.sigma_eta_raw_discrete_m = sigma_eta_raw_discrete_m;
meta.Hs_raw_discrete_m = Hs_raw_discrete_m;
meta.pm_variance_raw_continuous_m2 = pm_variance_raw_continuous_m2;
meta.sigma_eta_raw_continuous_m = sigma_eta_raw_continuous_m;
meta.Hs_raw_continuous_m = Hs_raw_continuous_m;
meta.Hs_raw = Hs_raw;
meta.Hs_scaled = Hs_scaled;
meta.scale_factor = scale_factor;
meta.seed = pm_cfg.seed;
meta.reflection_coeff_used = pm_cfg.reflect_coeff;
