discrete_variance = sum(W_eta(:)) * dkx * dky;
if target_variance == 0
    rel_error = abs(discrete_variance);
else
    rel_error = abs(discrete_variance - target_variance) / max(abs(target_variance), eps);
end
end

function [conv_power, conv_meta] = local_fft_convolution_on_k_grid(W_eta, A_inc, conv_padding)
switch conv_padding
    case 'periodic'
        conv_power = real(ifft2(fft2(W_eta) .* fft2(A_inc)));
        conv_meta = struct( ...
            'conv_operator', 'periodic_fft_circular', ...
            'conv_padding_size', size(W_eta), ...
            'conv_crop_start_index', [1, 1], ...
            'conv_crop_end_index', size(W_eta), ...
            'conv_crop_rule', 'none: output is the native circular convolution grid');
    case 'zero_padded'
        [ny, nx] = size(W_eta);
        pad_size = [2*ny - 1, 2*nx - 1];
        W_centered = fftshift(W_eta);
        A_centered = fftshift(A_inc);
        conv_full = real(ifft2(fft2(W_centered, pad_size(1), pad_size(2)) .* ...
            fft2(A_centered, pad_size(1), pad_size(2))));

        crop_start = [floor(ny/2) + 1, floor(nx/2) + 1];
        crop_end = crop_start + [ny - 1, nx - 1];
        conv_centered = conv_full(crop_start(1):crop_end(1), crop_start(2):crop_end(2));
        conv_power = ifftshift(conv_centered);
        conv_meta = struct( ...
            'conv_operator', 'linear_fft_zero_padded', ...
            'conv_padding_size', pad_size, ...
            'conv_crop_start_index', crop_start, ...
            'conv_crop_end_index', crop_end, ...
            'conv_crop_rule', ['fftshift inputs to signed-k order; compute full zero-padded ', ...
                'linear convolution; crop the original signed-k support; ifftshift back to FFT order']);
    otherwise
        error('pm_surface_boundary_model:SsaConvPaddingUnsupported', ...
            'Unsupported surface_ssa_conv_padding=''%s''.', conv_padding);
end
conv_power = max(real(conv_power), 0);
end

function G = local_compute_ssa1_geometry_factor( ...
    KX, KY, kz_grid, propagating_mask, k0, R0, geometry_source_id) %#ok<INUSD>
