function [z_rand, meta] = local_generate_ssa_random_spectrum( ...
    array_size, seed_ssa_requested, frequency_index, mode, rho)

seed_current = local_rng_seed(seed_ssa_requested);
seed_base = local_rng_seed(seed_ssa_requested - frequency_index + 1);
switch mode
    case 'independent'
        rng(seed_current, 'twister')
        z_rand = local_complex_white_noise(array_size);
        seed_innovation = seed_current;
        rule = ['independent: seed_ssa=sea_seed+seed_offset+frequency_index-1; ', ...
            'matches the legacy ssa_stat_kernel random scatter realization.'];
    case 'shared_seed_phase'
        rng(seed_base, 'twister')
        z_rand = local_complex_white_noise(array_size);
        seed_innovation = seed_base;
        rule = ['shared_seed_phase: all frequencies use the same complex Gaussian ', ...
            'spectrum seed while P_sca and propagation remain frequency dependent.'];
    case 'ar1_frequency'
        rng(seed_base, 'twister')
        z_rand = local_complex_white_noise(array_size);
        seed_innovation = seed_base;
        for idx = 2:frequency_index
            seed_innovation = local_rng_seed(seed_base + idx - 1);
            rng(seed_innovation, 'twister')
            z_innovation = local_complex_white_noise(array_size);
            z_rand = rho .* z_rand + sqrt(max(1 - rho^2, 0)) .* z_innovation;
        end
        rule = ['ar1_frequency: deterministic complex Gaussian AR(1) sequence ', ...
            'over frequency_index with target adjacent innovation correlation rho.'];
    otherwise
        error('Unsupported SSA frequency correlation mode: %s', mode);
end
