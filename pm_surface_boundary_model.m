function info = local_compute_ssa_coherent_reflection( ...
    W_eta, KX, KY, dkx, dky, k0, R0, sigma_eta, ...
    coherent_gamma_sum_eff_rad_per_m, coherent_vertical_factor_eff, coherent_order)

coherent_exponent = -0.5 * coherent_gamma_sum_eff_rad_per_m^2 * sigma_eta^2;
R_coh_ssa1 = R0 .* exp(coherent_exponent);

R_coh_ssa2 = complex(NaN, NaN);
ssa2_correction_integral = complex(NaN, NaN);
ssa2_propagating_integral = complex(NaN, NaN);
ssa2_evanescent_integral = complex(NaN, NaN);
ssa2_evanescent_fraction_abs = NaN;
gamma_i_eff = NaN;
K_i_eff = [NaN, NaN];
ssa2_limitations = ['not_evaluated: Broschat-style SSA2 coherent correction ', ...
    'requires pressure-release / Dirichlet R0=-1.'];

is_dirichlet = abs(R0 + 1) <= 1e-12;
if strcmp(coherent_order, 'ssa2_broschat_coherent') && ~is_dirichlet
    error('pm_surface_boundary_model:Ssa2DirichletReflectCoeffRequired', ...
        ['surface_ssa_coherent_order=''ssa2_broschat_coherent'' implements a ', ...
         'Broschat-style pressure-release / Dirichlet coherent correction and ', ...
         'requires surface_reflect_coeff=-1.']);
end

if is_dirichlet
    gamma_i_eff = 0.5 * real(coherent_gamma_sum_eff_rad_per_m);
    gamma_i_eff = min(max(gamma_i_eff, 0), k0);
    K_i_mag_eff = sqrt(max(k0^2 - gamma_i_eff^2, 0));
    K_i_eff = [K_i_mag_eff, 0];

    K_shift_x = K_i_eff(1) + KX;
    K_shift_y = K_i_eff(2) + KY;
    gamma_arg = k0^2 - (K_shift_x.^2 + K_shift_y.^2);
    gamma_shifted = sqrt(complex(gamma_arg, 0));
    correction_kernel = W_eta .* (gamma_shifted - gamma_i_eff);
    ssa2_correction_integral = sum(correction_kernel(:)) * dkx * dky;

    propagating_mask = gamma_arg >= 0;
    if any(propagating_mask(:))
        ssa2_propagating_integral = sum(correction_kernel(propagating_mask)) * dkx * dky;
    else
        ssa2_propagating_integral = complex(0, 0);
    end
    ssa2_evanescent_integral = ssa2_correction_integral - ssa2_propagating_integral;
    if abs(ssa2_correction_integral) > 0
        ssa2_evanescent_fraction_abs = abs(ssa2_evanescent_integral) / ...
            max(abs(ssa2_correction_integral), eps);
    else
        ssa2_evanescent_fraction_abs = 0;
    end

    ssa1_dirichlet = -exp(-2 * gamma_i_eff^2 * sigma_eta^2);
    R_coh_ssa2 = ssa1_dirichlet + 2 * gamma_i_eff * ...
        exp(-2 * gamma_i_eff^2 * sigma_eta^2) * ssa2_correction_integral;
    ssa2_limitations = ['Broschat 1993 one-dimensional Dirichlet coherent ', ...
        'reflection correction extended here to the project two-dimensional PM spectrum. ', ...
        'This is not second-order incoherent P_sca, a full SSA2 T-matrix, NLSSA, ', ...
        'an impedance boundary model, or an experimentally calibrated cross section. ', ...
        'For oblique mode the effective incident azimuth is assumed along +kx; ', ...
        'primary conclusions should use normal / near-vertical cases.'];
end

switch coherent_order
    case 'ssa1'
        R_coh_selected_raw = R_coh_ssa1;
    case 'ssa2_broschat_coherent'
        R_coh_selected_raw = R_coh_ssa2;
    otherwise
        error('Unsupported SSA coherent order: %s', coherent_order);
end

coherent_loss_ssa1_db = -20 * log10(max(abs(R_coh_ssa1), eps));
coherent_loss_ssa2_db = -20 * log10(max(abs(R_coh_ssa2), eps));
coherent_loss_delta_db = coherent_loss_ssa2_db - coherent_loss_ssa1_db;
delta_R_abs = abs(R_coh_ssa2 - R_coh_ssa1);
delta_R_rel = delta_R_abs / max(abs(R_coh_ssa1), eps);

info = struct( ...
    'coherent_order', coherent_order, ...
    'R_coh_selected_raw', R_coh_selected_raw, ...
    'R_coh_ssa1', R_coh_ssa1, ...
    'R_coh_ssa2', R_coh_ssa2, ...
    'abs_R_coh_ssa1', abs(R_coh_ssa1), ...
    'abs_R_coh_ssa2', abs(R_coh_ssa2), ...
    'coherent_loss_ssa1_db', coherent_loss_ssa1_db, ...
    'coherent_loss_ssa2_db', coherent_loss_ssa2_db, ...
    'coherent_loss_delta_db', coherent_loss_delta_db, ...
    'delta_R_abs', delta_R_abs, ...
    'delta_R_rel', delta_R_rel, ...
    'coherent_exponent', coherent_exponent, ...
    'coherent_reflection_formula', ['ssa1: R1=R0*exp(-0.5*(gamma_i+gamma_s)^2*sigma_eta^2); ', ...
        'normal pressure-release: R1=-exp(-2*k0^2*sigma_eta^2). ', ...
        'ssa2_broschat_coherent replaces only R_coh using the Broschat-style coherent correction.'], ...
    'ssa2_correction_integral', ssa2_correction_integral, ...
    'ssa2_correction_integral_real', real(ssa2_correction_integral), ...
    'ssa2_correction_integral_imag', imag(ssa2_correction_integral), ...
    'ssa2_gamma_i_eff_rad_per_m', gamma_i_eff, ...
    'ssa2_K_i_eff_rad_per_m', K_i_eff, ...
    'ssa2_sqrt_branch', 'sqrt(complex(k0^2-|K_i+q|^2,0)); positive real root for propagating bins and positive imaginary root for evanescent bins', ...
    'ssa2_formula', ['R2=R1+2*gamma_i*exp(-2*gamma_i^2*sigma_eta^2)*', ...
        'sum(W_eta(q)*(gamma(K_i+q)-gamma_i))*dkx*dky'], ...
    'ssa2_formula_source', 'Broschat 1993 one-dimensional Dirichlet coherent reflection coefficient; two-dimensional project extension supplied by user', ...
    'ssa2_limitations', ssa2_limitations, ...
    'ssa2_evanescent_handling', 'full complex branch integral is used; propagating-only and evanescent contributions are recorded for diagnostics', ...
    'ssa2_propagating_integral', ssa2_propagating_integral, ...
    'ssa2_evanescent_integral', ssa2_evanescent_integral, ...
    'ssa2_evanescent_fraction_abs', ssa2_evanescent_fraction_abs, ...
    'coherent_vertical_factor_eff', coherent_vertical_factor_eff);
end

function [P_sca_raw, detail] = local_compute_ssa_scatter_power( ...
    kernel_mode, W_eta, P_inc, KX, KY, kz_grid, propagating_mask, ...
    dkx, dky, k0, R0, scatter_scale, phase_factor_eff, ...
    geometry_source_id, conv_padding)

switch kernel_mode
    case 'pm_convolution'
        [conv_power, conv_meta] = local_fft_convolution_on_k_grid(W_eta, P_inc, conv_padding);
        conv_power = max(conv_power, 0);
        corrected_phase_scale_rad_per_m = k0 * phase_factor_eff;
        legacy_phase_scale_rad_per_m = 2 * k0 * phase_factor_eff;
        P_sca_raw = scatter_scale * abs(R0)^2 * corrected_phase_scale_rad_per_m^2 * ...
            dkx * dky * conv_power;
        P_sca_raw = max(real(P_sca_raw), 0);
        detail = struct( ...
            'kernel_mode', kernel_mode, ...
            'geometry_source_id', geometry_source_id, ...
            'formula_source', 'not_applicable: engineering PM convolution baseline', ...
            'boundary_condition', 'engineering scalar reflection coefficient', ...
            'evanescent_included', false, ...
            'conv_padding', conv_padding, ...
            'conv_operator', conv_meta.conv_operator, ...
            'conv_padding_size', conv_meta.conv_padding_size, ...
            'conv_crop_start_index', conv_meta.conv_crop_start_index, ...
            'conv_crop_end_index', conv_meta.conv_crop_end_index, ...
            'conv_crop_rule', conv_meta.conv_crop_rule, ...
            'uses_strict_geometry_factor', false, ...
            'uses_dense_matrix', false, ...
            'phase_scale_corrected_rad_per_m', corrected_phase_scale_rad_per_m, ...
            'phase_scale_legacy_rad_per_m', legacy_phase_scale_rad_per_m, ...
            'phase_scale_formula', 'corrected pm_convolution baseline uses k0*phase_factor_eff, where phase_factor_eff=cos_i+cos_s', ...
            'phase_scale_legacy_formula', 'legacy pm_convolution used 2*k0*phase_factor_eff and over-counted the already two-way phase factor', ...
            'G_SSA1_formula', 'not_applicable', ...
            'kernel_formula', ['pm_convolution baseline: ', ...
                'P_sca_raw=scatter_scale*abs(R0)^2*(k0*phase_factor_eff)^2*dkx*dky*', ...
                'circconv(W_eta,abs(Psi_inc_k).^2).'], ...
            'limitations', ['Engineering PM-spectrum convolution baseline. ', ...
                'No strict G_SSA(K,K'';f), angular calibration, or calibrated scattering cross section is implemented.']);
    case 'ssa1_geometry'
        local_require_dirichlet_reflect_coeff(R0, kernel_mode);
        G_note = local_compute_ssa1_geometry_factor(KX, KY, kz_grid, propagating_mask, ...
            k0, R0, geometry_source_id);
        A_inc = kz_grid .* P_inc;
        A_inc(~propagating_mask) = 0;
        [conv_power, conv_meta] = local_fft_convolution_on_k_grid(W_eta, A_inc, conv_padding);
        conv_power = max(conv_power, 0);
        P_sca_raw = 4 * scatter_scale * kz_grid .* conv_power * dkx * dky;
        P_sca_raw(~propagating_mask) = 0;
        P_sca_raw = max(real(P_sca_raw), 0);
        detail = struct( ...
            'kernel_mode', kernel_mode, ...
            'geometry_source_id', geometry_source_id, ...
            'formula_source', local_ssa1_formula_source(geometry_source_id), ...
            'boundary_condition', 'pressure-release / Dirichlet', ...
            'evanescent_included', false, ...
            'conv_padding', conv_padding, ...
            'conv_operator', conv_meta.conv_operator, ...
            'conv_padding_size', conv_meta.conv_padding_size, ...
            'conv_crop_start_index', conv_meta.conv_crop_start_index, ...
            'conv_crop_end_index', conv_meta.conv_crop_end_index, ...
            'conv_crop_rule', conv_meta.conv_crop_rule, ...
            'uses_strict_geometry_factor', true, ...
            'uses_dense_matrix', false, ...
            'G_SSA1_formula', G_note.G_SSA1_formula, ...
            'kernel_formula', ['ssa1_geometry: P_sca_raw(K)=4*C_norm*gamma(K)*', ...
                'circconv(W_eta,gamma(Kprime)*abs(Psi_inc(Kprime))^2)*dkx*dky, ', ...
                'with C_norm=surface_ssa_scatter_scale.'], ...
            'limitations', ['First-order Dirichlet SSA / perturbation-limit geometry from SSA.md. ', ...
                'No NLSSA, multiple scattering, impedance boundary, experimental calibration, or evanescent scattering is included.']);
    case 'ssa1_debug_dense'
        if ~strcmp(conv_padding, 'periodic')
            error('pm_surface_boundary_model:SsaConvPaddingNotImplemented', ...
                ['surface_ssa_conv_padding=''%s'' is not implemented for ssa1_debug_dense. ', ...
                 'Use ''periodic'' because the dense debug path validates the periodic FFT convolution.'], conv_padding);
        end
        [P_sca_raw, detail] = local_compute_scatter_power_dense( ...
            W_eta, P_inc, KX, KY, kz_grid, propagating_mask, ...
            dkx, dky, k0, R0, scatter_scale, geometry_source_id);
    otherwise
        error('Unsupported SSA kernel mode: %s', kernel_mode);
end
end

function [target_variance, discrete_variance, rel_error] = local_w_eta_variance_audit(W_eta, dkx, dky, sigma_eta)
