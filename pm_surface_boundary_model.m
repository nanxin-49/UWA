function spec = local_pm_spectrum(KX, KY, xw, yw, U)
if ~(isscalar(U) && isnumeric(U) && isfinite(U) && U > 0)
    error('pm_cfg.U must be a positive finite wind speed.');
end

g = 9.81;
alpha_PM = 8.10e-3;
beta_PM = 0.74;
K = sqrt(KX.^2 + KY.^2);
E1D = zeros(size(K));
Phi2D = zeros(size(K));

mask = (K > 0);
K_nonzero = K(mask);
E1D(mask) = (alpha_PM ./ (2 .* K_nonzero.^3)) .* ...
            exp(-beta_PM * (g^2) ./ (U^4 .* K_nonzero.^2));
Phi2D(mask) = E1D(mask) ./ (2*pi*K_nonzero);

spec = struct( ...
    'U', U, ...
    'g', g, ...
    'alpha_PM', alpha_PM, ...
    'beta_PM', beta_PM, ...
    'K', K, ...
    'E1D', E1D, ...
    'Phi2D', Phi2D, ...
    'mask', mask, ...
    'dkx', 2*pi / xw, ...
    'dky', 2*pi / yw);
end

function phase_factor = local_surface_phase_factor( ...
    phase_mode, X, Y, tx_xyz, rx_xyz, z_surface, clip_pair)
switch phase_mode
    case 'normal'
        phase_factor = 2 * ones(size(X));
    case 'oblique'
        tx_xyz = tx_xyz(:).';
        rx_xyz = rx_xyz(:).';

        dz_i = tx_xyz(3) - z_surface;
        dz_r = rx_xyz(3) - z_surface;
        if dz_i <= 0 || dz_r < 0
            error('For oblique mode, tx/rx must be at or below the surface: z >= z_surface.');
        end

        dx_i = X - tx_xyz(1);
        dy_i = Y - tx_xyz(2);
        Ri = sqrt(dx_i.^2 + dy_i.^2 + dz_i.^2);
        cos_i = dz_i ./ max(Ri, eps);

        dx_r = X - rx_xyz(1);
        dy_r = Y - rx_xyz(2);
        Rr = sqrt(dx_r.^2 + dy_r.^2 + dz_r.^2);
        cos_r = dz_r ./ max(Rr, eps);

        cos_i = min(max(cos_i, clip_pair(1)), clip_pair(2));
        cos_r = min(max(cos_r, clip_pair(1)), clip_pair(2));
        phase_factor = cos_i + cos_r;
    otherwise
        error('Unsupported phase_mode: %s', phase_mode);
end
end

